def ege_time_color(seconds, ege_number):
    """
    Цвет времени над задачей ЕГЭ относительно рекомендованного:
    зелёный – уложился в норму, жёлтый – до полутора норм, красный – дольше.
    Пустая строка – задача не решалась, красить нечего.

    Одна функция на все места, где показывается время ЕГЭ (результаты варианта,
    отчёт по ученику, профиль, итог сессии тренировки): расхождение цветов между
    ними ученик читал бы как ошибку в данных.
    """
    if not seconds:
        return ''
    rec_min = EGE_RECOMMENDED_TIME.get(ege_number or 0, DEFAULT_TASK_MINUTES)
    minutes = seconds // 60
    if minutes <= rec_min:
        return 'green'
    if minutes <= rec_min * 1.5:
        return 'yellow'
    return 'red'


# Шкала «плохо – хорошо» для прогноза балла. Пять ступеней, а не непрерывный
# градиент: Tailwind собирается заранее, и класса под вычисленный на лету
# оттенок в CSS просто не окажется. Пяти хватает, чтобы разница между 40 и 70
# баллами читалась с одного взгляда.
SCALE_COLORS = ('red', 'orange', 'amber', 'lime', 'emerald')

# Шкала долга по ошибкам – всегда красная, меняется только насыщенность:
# от бледной у пары задач до полной у трёх десятков. Зелёного здесь нет
# намеренно – ошибки не бывают достижением, даже когда их мало.
MISTAKE_COLORS = ('red1', 'red2', 'red3', 'red4', 'red5')

# Сколько нерешённых задач красит счётчик ошибок в самый насыщенный красный.
MISTAKES_RED_AT = 30


def ratio_color(ratio, scale=SCALE_COLORS):
    """0.0 – начало шкалы, 1.0 – её конец; промежуточные значения по ступеням."""
    ratio = max(0.0, min(1.0, ratio or 0.0))
    return scale[round(ratio * (len(scale) - 1))]


def ege_score_color(test_score):
    """Цвет тестового балла: 0 – красный, 100 – зелёный."""
    return ratio_color((test_score or 0) / 100)


def ege_mistakes_color(count):
    """Цвет счётчика ошибок: чем длиннее долг, тем насыщеннее красный."""
    return ratio_color((count or 0) / MISTAKES_RED_AT, MISTAKE_COLORS)


def test_score_for(primary):
    """Тестовый балл по первичному, с потолком на 100."""
    if primary is None:
        return 0
    primary = max(0, int(primary))
    if primary >= EGE_MAX_PRIMARY:
        return 100
    return EGE_SCORE_CONVERSION.get(primary, 0)


