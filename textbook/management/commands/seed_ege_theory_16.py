"""Разбор задания 16 ЕГЭ: рекуррентная функция и выражение из её значений.

Скелет – docs/ege-theory-brief.md. Отступлений от него три, и все они растут
из одного: у этого номера два равноправных решения, программное и бумажное.

Первое: блоков не шесть, а десять. Рекуррентное соотношение вынесено из прозы
в отдельный блок `formula` – это и есть всё условие задачи, – а «Из формулы
в программу» переводит каждую его строку в строку кода: база становится
`F[1] = 1`, шаг – телом цикла.

Второе: у второго способа блок `formula`, а не `code`. Свернуть выражение
на листке быстрее, чем открыть среду разработки, а на вариантах с аргументом
в сотнях тысяч это ещё и единственный выход: список значений не помещается
в память. Листинг в статье поэтому ровно один, и он же – константа
SOLUTION_LOOP, чтобы текст и код не разъезжались.

Третье: блок «Если условие другое». Вариации номера сводятся к трём правкам –
вид шага, граница базы, число функций, – и таблица «что в условии → что
делать» избавляет от разбора каждого варианта заново. Все строки таблицы
взяты из банка задания (fixtures/bank-16.json), ни одной выдуманной.

Оба способа обязаны дать одно число, и оно не берётся на слово: `_factorials()`
повторяет цикл из SOLUTION_LOOP, `_check()` сверяет программу с бумажной
свёрткой и с ответом ФИПИ. Разойдутся – команда упадёт здесь, а не оставит
в опубликованной статье свёртку, доказывающую неверный ответ.

Числа, которыми статья доказывает свой выбор, тоже проверяются: 9263 знака
в 3038!, предел вложенности 1000, OverflowError на делении на 519, ValueError
на печати самой функции. Каждое из них – довод в пользу цикла; перестанет быть
верным – статья не должна попасть на сайт.

Условие – задание 16 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-16).

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
import math
import sys

from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks
from textbook.templatetags.textbook_tags import plural

SLUG = 'ege-16-rekursivnye-algoritmy'
N = 3038            # наибольший аргумент выражения из условия
ANSWER = 9241591    # ответ ФИПИ
ADD = 5             # слагаемое при F(N-1) в числителе
DIGITS = 9263       # знаков в 3038!
RECURSION_LIMIT = 1000   # предел вложенности рекурсии в Python по умолчанию
STR_LIMIT = 4300    # знаков, дальше Python отказывается переводить int в строку
DIVISOR = 519       # делитель из вариантов банка: на нём падает одиночное `/`
BANK_N = 247563     # аргумент из вариантов банка: там, где бумага выигрывает
BANK_DIGITS = 1227765   # знаков в факториале от него

# Ровно тот код, что стоит в блоке `code`. Держим его отдельной константой,
# а не внутри dict: это единственный листинг статьи, и в diff он должен
# выглядеть так же, как на странице.
SOLUTION_LOOP = """N = 3038                        # наибольший аргумент в выражении

F = [0] * (N + 1)
F[1] = 1                        # база: F(1) = 1
for n in range(2, N + 1):
    F[n] = n * F[n - 1]         # шаг: F(n) = n * F(n - 1)

print((F[3038] + 5 * F[3037]) // F[3036])   # 9241591
"""


def _factorials():
    """Значения $F(1) \\dots F(N)$ – тот же цикл, что в SOLUTION_LOOP.

    Разбор обязан считать ровно тем кодом, который показывает читателю:
    второй, «правильный» цикл рядом с листингом рано или поздно разойдётся
    с ним, и статья начнёт доказывать не то, что печатает.
    """
    f = [0] * (N + 1)
    f[1] = 1
    for n in range(2, N + 1):
        f[n] = n * f[n - 1]
    return f


def _digits(value):
    """Сколько десятичных знаков в числе – без перевода числа в строку.

    `len(str(value))` здесь не годится: Python отказывается переводить
    в строку число длиннее 4300 знаков и падает тем самым ValueError, которое
    цитирует пункт 3 «Типичных ошибок». Логарифм работает с числом напрямую.
    """
    return int(math.log10(value)) + 1


def _recurrence():
    """Рекуррентное соотношение – выносной блок `formula`.

    Кириллицы внутри нет намеренно: в математических шрифтах MathJax её нет,
    а `\\text{…}` выдаёт «тофу». Соотношение здесь записано так, как его дают
    в условии, – сверху вниз от базы к шагу.
    """
    return (
        r'F(n) = \begin{cases}'
        r'1, & n = 1,\\'
        r'n \cdot F(n-1), & n > 1.'
        r'\end{cases}'
    )


def _fold():
    """Свёртка выражения – выносной блок `formula` второго способа.

    Числа вписаны, а не подставлены из констант: внутри LaTeX почти каждый
    второй символ – фигурная скобка, и f-строка с удвоенными скобками читалась
    бы хуже, чем сама формула. Связь с константами держит не форматирование,
    а `_check()`: он сверяет последнюю строку выкладки с N, ADD и ANSWER.
    """
    return (
        r'\begin{aligned}'
        r'\frac{F(3038) + 5F(3037)}{F(3036)}'
        r' &= \frac{3038 \cdot F(3037) + 5F(3037)}{F(3036)} \\'
        r' &= \frac{3043 \cdot F(3037)}{F(3036)}'
        r' = \frac{3043 \cdot 3037 \cdot F(3036)}{F(3036)} \\'
        r' &= 3043 \cdot 3037 = 9241591'
        r'\end{aligned}'
    )


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ и с текстом статьи.

    Поменяется условие – команда упадёт здесь, вместо того чтобы оставить
    в опубликованной статье выкладку, доказывающую неверный ответ. Главная
    проверка – совпадение двух способов: программы и бумаги. Если разойдутся
    они, разойдётся и статья, где оба обещают одно число.
    """
    f = _factorials()

    assert (f[N] + ADD * f[N - 1]) // f[N - 2] == ANSWER, (
        f'цикл даёт {(f[N] + ADD * f[N - 1]) // f[N - 2]}, у ФИПИ {ANSWER} – '
        'листинг решает другую задачу, чем условие'
    )
    # Множители свёртки выведены из условия, а не вписаны: числитель после
    # подстановки шага – это (N + ADD) копий F(N-1), а сам F(N-1) – это
    # (N - 1) копий F(N-2).
    high, low = N + ADD, N - 1
    assert high * low == ANSWER, (
        f'бумажная свёртка даёт {high} * {low} = {high * low}, у ФИПИ '
        f'{ANSWER} – блок «Способ 2» сворачивает не то выражение'
    )
    assert (f[N] + ADD * f[N - 1]) % f[N - 2] == 0, (
        'выражение делится с остатком – абзац «Почему сокращать законно» '
        'обещает обратное, и `//` в листинге теряет смысл'
    )
    assert f[N - 2] != 0, (
        f'F({N - 2}) равно нулю – выносить его за скобку и сокращать нельзя, '
        'вся выкладка второго способа рушится'
    )
    assert _digits(f[N]) == DIGITS, (
        f'в {N}! {_digits(f[N])} знаков вместо {DIGITS} – блок «Что проверяет '
        'задание» и пункт 3 «Как рассуждать» называют другое число'
    )
    assert sys.getrecursionlimit() == RECURSION_LIMIT, (
        f'предел вложенности в Python стал {sys.getrecursionlimit()} – блок '
        '«Из формулы в программу» называет другое число'
    )
    assert N > sys.getrecursionlimit(), (
        f'глубина {N} не больше предела {sys.getrecursionlimit()} – довод '
        'против рекурсии пропал, а статья его обещает'
    )
    try:
        f[N] / DIVISOR
    except OverflowError:
        pass
    else:
        raise AssertionError(
            f'F({N}) / {DIVISOR} посчиталось – пункт 1 «Типичных ошибок» '
            'называет ошибку, которой больше нет'
        )
    try:
        text = str(f[N])
    except ValueError as exc:
        assert f'({STR_LIMIT} digits)' in str(exc), (
            f'сообщение об ошибке теперь «{exc}» – пункт 3 «Типичных ошибок» '
            'цитирует его дословно'
        )
    else:
        raise AssertionError(
            f'str(F({N})) вернула строку в {len(text)} знаков – пункт 3 '
            '«Типичных ошибок» обещает ValueError'
        )
    assert f'N = {N}' in SOLUTION_LOOP, (
        f'в листинге нет строки `N = {N}` – условие изменилось, а блок '
        '`code` остался прежним'
    )
    assert 'F[1] = 1' in SOLUTION_LOOP, (
        'в листинге нет строки базы – блок «Из формулы в программу» обещает '
        '`F[1] = 1`'
    )
    assert f'// F[{N - 2}]' in SOLUTION_LOOP, (
        f'листинг делит не на F({N - 2}) – он разошёлся с условием'
    )
    assert SOLUTION_LOOP.replace('//', '').count('/') == 0, (
        'в листинге осталось одиночное деление – текст обещает `//`, '
        'и пункт 1 «Типичных ошибок» объясняет почему'
    )
    assert r'n \cdot F(n-1)' in _recurrence(), (
        'в блоке «Рекуррентное соотношение» потерян шаг – «Из формулы '
        'в программу» переводит не ту строку'
    )
    assert f'{high} \\cdot {low} = {ANSWER}' in _fold(), (
        f'в блоке «Свёртка выражения» нет строки {high} \\cdot {low} = '
        f'{ANSWER} – формула разошлась с числами разбора'
    )


