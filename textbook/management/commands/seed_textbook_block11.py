def _self_check(slug, title, description, questions):
    """Создаёт (или переиспользует) тест самопроверки с вопросами."""
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check:
        quiz.is_self_check = True
        quiz.save(update_fields=['is_self_check'])

    # Тест ещё никто не решал — пересоздаём вопросы, чтобы до базы доехали
    # и правки формулировок, и перемешанный порядок вариантов ответа.
    if quiz.questions.exists() and not UserAnswer.objects.filter(question__quiz=quiz).exists():
        quiz.questions.all().delete()

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                points=1,
            )
            for choice_text, is_correct in _shuffle_choices(q['text'], q.get('choices', [])):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
    # Правки формулировок должны доезжать и до тестов, которые уже решали:
    # пересоздать вопросы там нельзя — каскад унёс бы ответы учеников.
    _sync_question_texts(quiz, questions)
    return quiz


def _bubble_trace(values):
    """Готовая трасса пузырька для виджета loop-trace (урок 11.2).

    Виджет ничего не считает сам — прогоняем алгоритм здесь и записываем
    полное состояние переменных после каждой выполненной строки.
    """
    code = [
        'a = ' + repr(list(values)),
        'n = len(a)',
        'for i in range(n - 1):',
        '    for j in range(n - 1 - i):',
        '        if a[j] > a[j + 1]:',
        '            a[j], a[j + 1] = a[j + 1], a[j]',
        'print(a)',
    ]

    a = list(values)
    n = len(a)
    state = {}
    steps = []

    def snap(line, note=None, check=None, out=None):
        step = {
            'line': line,
            'vars': {k: (list(v) if isinstance(v, list) else v) for k, v in state.items()},
        }
        if note is not None:
            step['note'] = note
        if check is not None:
            step['check'] = check
        if out is not None:
            step['out'] = out
        steps.append(step)

    state['a'] = list(a)
    snap(1, note='Список, который надо отсортировать.')
    state['n'] = n
    snap(2, note='n — длина списка, здесь {}.'.format(n))

    for i in range(n - 1):
        state['i'] = i
        snap(3, note=(
            'Проход {}. Последние {} элемент(ов) уже на своих местах — '
            'внутренний цикл до них не дойдёт.'.format(i + 1, i)
        ))
        for j in range(n - 1 - i):
            state['j'] = j
            snap(4, note='Берём пару соседей: a[{}] и a[{}].'.format(j, j + 1))
            x, y = a[j], a[j + 1]
            snap(5, check=x > y, note='{} > {}?'.format(x, y))
            if x > y:
                a[j], a[j + 1] = a[j + 1], a[j]
                state['a'] = list(a)
                snap(6, note='Меняем местами: {} уходит вправо.'.format(x))
    snap(7, out=str(a), note='Список отсортирован.')
    return {'code': code, 'vars': ['a', 'n', 'i', 'j'], 'steps': steps}


def _selection_trace(values):
    """Готовая трасса сортировки выбором для loop-trace (урок 11.3).

    Как и у пузырька, виджет ничего не считает: прогоняем алгоритм здесь и
    записываем полное состояние переменных после каждой выполненной строки.
    """
    code = [
        'a = ' + repr(list(values)),
        'n = len(a)',
        'for i in range(n - 1):',
        '    m = i',
        '    for j in range(i + 1, n):',
        '        if a[j] < a[m]:',
        '            m = j',
        '    if m != i:',
        '        a[i], a[m] = a[m], a[i]',
        'print(a)',
    ]

    a = list(values)
    n = len(a)
    state = {}
    steps = []

    def snap(line, note=None, check=None, out=None):
        step = {
            'line': line,
            'vars': {k: (list(v) if isinstance(v, list) else v) for k, v in state.items()},
        }
        if note is not None:
            step['note'] = note
        if check is not None:
            step['check'] = check
        if out is not None:
            step['out'] = out
        steps.append(step)

    state['a'] = list(a)
    snap(1, note='Список, который надо отсортировать.')
    state['n'] = n
    snap(2, note='n — длина списка, здесь {}.'.format(n))

    for i in range(n - 1):
        state['i'] = i
        snap(3, note=(
            'Проход {}. Ищем, кого поставить на позицию {}.'.format(i + 1, i)
            if i == 0 else
            'Проход {}. Первые {} элемент(ов) уже расставлены, '
            'остаток начинается с a[{}].'.format(i + 1, i, i)
        ))
        m = i
        state['m'] = m
        snap(4, note='Пока считаем минимумом сам a[{}] = {}.'.format(i, a[i]))
        for j in range(i + 1, n):
            state['j'] = j
            snap(5, note='Берём следующий элемент остатка: a[{}] = {}.'.format(j, a[j]))
            less = a[j] < a[m]
            snap(6, check=less, note='{} < {}?'.format(a[j], a[m]))
            if less:
                m = j
                state['m'] = m
                snap(7, note=(
                    'Новый минимум — {} на позиции {}. Сам список не изменился: '
                    'мы только запомнили индекс.'.format(a[j], j)
                ))
        snap(8, check=(m != i), note=(
            'Минимум остатка лежит на позиции {}, а нужен на {}.'.format(m, i)
            if m != i else
            'Минимум остатка и так лежит на позиции {} — обмен не нужен.'.format(i)
        ))
        if m != i:
            a[i], a[m] = a[m], a[i]
            state['a'] = list(a)
            snap(9, note='Меняем местами: {} встал на своё окончательное место.'.format(a[i]))
    snap(10, out=str(a), note='Список отсортирован.')
    return {'code': code, 'vars': ['a', 'n', 'i', 'j', 'm'], 'steps': steps}


def _insertion_trace(values):
    """Готовая трасса сортировки вставками для loop-trace (урок 11.4).

    Виджет ничего не считает сам: прогоняем алгоритм здесь и записываем
    полное состояние переменных после каждой выполненной строки. Условие
    while разбито на два шага-заметки, чтобы было видно оба способа выйти
    из внутреннего цикла — по левому краю и по найденному месту.
    """
    code = [
        'a = ' + repr(list(values)),
        'n = len(a)',
        'for i in range(1, n):',
        '    key = a[i]',
        '    j = i - 1',
        '    while j >= 0 and a[j] > key:',
        '        a[j + 1] = a[j]',
        '        j -= 1',
        '    a[j + 1] = key',
        'print(a)',
    ]

    a = list(values)
    n = len(a)
    state = {}
    steps = []

    def snap(line, note=None, check=None, out=None):
        step = {
            'line': line,
            'vars': {k: (list(v) if isinstance(v, list) else v) for k, v in state.items()},
        }
        if note is not None:
            step['note'] = note
        if check is not None:
            step['check'] = check
        if out is not None:
            step['out'] = out
        steps.append(step)

    state['a'] = list(a)
    snap(1, note='Список, который надо отсортировать.')
    state['n'] = n
    snap(2, note='n — длина списка, здесь {}.'.format(n))

    for i in range(1, n):
        state['i'] = i
        snap(3, note=(
            'Проход {}. Начало из {} элемент(ов) уже упорядочено, '
            'разбираем a[{}].'.format(i, i, i)
        ))
        key = a[i]
        state['key'] = key
        snap(4, note=(
            'Вынимаем {} в отдельную переменную — теперь ячейку {} '
            'можно затирать.'.format(key, i)
        ))
        j = i - 1
        state['j'] = j
        snap(5, note='Встаём на последний элемент упорядоченного начала.')

        while True:
            if j < 0:
                snap(6, check=False, note=(
                    'j = -1: левый край. Первая часть условия ложна, и вторую '
                    'Python уже не проверяет — иначе прочитал бы a[-1], '
                    'то есть последний элемент списка.'
                ))
                break
            if a[j] <= key:
                snap(6, check=False, note=(
                    r'j = {} — не край, но a[{}] = {} $\le$ {}: место найдено, '
                    'дальше влево идти незачем.'.format(j, j, a[j], key)
                ))
                break
            snap(6, check=True, note='a[{}] = {} > {} — этот элемент должен '
                                     'стоять правее.'.format(j, a[j], key))
            a[j + 1] = a[j]
            state['a'] = list(a)
            snap(7, note=(
                'Сдвигаем {} на позицию {}. Прежнее значение ячейки не жалко: '
                'оно либо уже уехало правее, либо лежит в key.'.format(a[j], j + 1)
            ))
            j -= 1
            state['j'] = j
            snap(8, note='Смотрим на следующий элемент влево.')

        a[j + 1] = key
        state['a'] = list(a)
        snap(9, note='Кладём {} на позицию {} — в освободившуюся ячейку.'.format(key, j + 1))

    snap(10, out=str(a), note='Список отсортирован.')
    return {'code': code, 'vars': ['a', 'n', 'i', 'key', 'j'], 'steps': steps}


def _quick_trace(values):
    """Готовая трасса быстрой сортировки для loop-trace (урок 11.5).

    Прогоняем ровно тот код, который напечатан в уроке, и записываем полное
    состояние после каждой выполненной строки. Проверки условий (строки 3, 7,
    12) — отдельные шаги с бейджем «истина/ложь»: за ними и надо следить,
    именно они решают, разбивать отрезок или выбросить его.
    """
    code = [
        'a = ' + repr(list(values)),
        'tasks = [[0, len(a) - 1]]',
        'while len(tasks) > 0:',
        '    task = tasks.pop()',
        '    lo = task[0]',
        '    hi = task[1]',
        '    if lo >= hi:',
        '        continue',
        '    pivot = a[hi]',
        '    i = lo - 1',
        '    for j in range(lo, hi):',
        '        if a[j] < pivot:',
        '            i += 1',
        '            a[i], a[j] = a[j], a[i]',
        '    a[i + 1], a[hi] = a[hi], a[i + 1]',
        '    p = i + 1',
        '    tasks.append([lo, p - 1])',
        '    tasks.append([p + 1, hi])',
        'print(a)',
    ]

    a = list(values)
    n = len(a)
    state = {}
    steps = []

    def snap(line, note=None, check=None, out=None):
        step = {
            'line': line,
            'vars': {
                k: ([list(x) if isinstance(x, list) else x for x in v]
                    if isinstance(v, list) else v)
                for k, v in state.items()
            },
        }
        if note is not None:
            step['note'] = note
        if check is not None:
            step['check'] = check
        if out is not None:
            step['out'] = out
        steps.append(step)

    def seg(lo, hi):
        return '{}…{}'.format(lo, hi)

    state['a'] = list(a)
    snap(1, note='Список, который надо отсортировать.')
    tasks = [[0, n - 1]]
    state['tasks'] = [list(t) for t in tasks]
    snap(2, note=(
        'Список неразобранных отрезков. Пока он один — весь список, '
        'от 0 до {}.'.format(n - 1)
    ))

    while True:
        if len(tasks) == 0:
            snap(3, check=False, note='Неразобранных отрезков не осталось — выходим.')
            break
        snap(3, check=True, note=(
            'Отрезков в очереди: {}. Значит, работа не кончена.'.format(len(tasks))
        ))

        task = tasks.pop()
        lo, hi = task[0], task[1]
        state['tasks'] = [list(t) for t in tasks]
        snap(4, note=(
            'Снимаем со списка последний отрезок — {}. Порядок разбора не '
            'важен: отрезки не пересекаются.'.format(seg(lo, hi))
        ))
        state['lo'] = lo
        snap(5, note='Левая граница отрезка.')
        state['hi'] = hi
        snap(6, note='Правая граница отрезка.')

        if lo >= hi:
            snap(7, check=True, note=(
                'В отрезке {} меньше двух элементов — разбивать нечего.'.format(
                    seg(lo, hi))
            ))
            snap(8, note='Пропускаем этот отрезок и возвращаемся к строке 3.')
            continue

        snap(7, check=False, note=(
            'В отрезке {} хотя бы два элемента — есть что разбивать.'.format(
                seg(lo, hi))
        ))
        pivot = a[hi]
        state['pivot'] = pivot
        snap(9, note='Опорным берём последний элемент отрезка — a[{}] = {}.'.format(
            hi, pivot))
        i = lo - 1
        state['i'] = i
        snap(10, note=(
            'Граница «маленьких». Пока за ней ни одного элемента, поэтому она '
            'стоит левее начала отрезка.'
        ))

        for j in range(lo, hi):
            state['j'] = j
            snap(11, note='Смотрим на a[{}] = {}. До опорного, но не включая его.'.format(
                j, a[j]))
            if a[j] < pivot:
                snap(12, check=True, note='{} < {} — элементу место в левой части.'.format(
                    a[j], pivot))
                i += 1
                state['i'] = i
                snap(13, note='Двигаем границу вправо: теперь маленькие занимают '
                              'позиции по {} включительно.'.format(i))
                a[i], a[j] = a[j], a[i]
                state['a'] = list(a)
                if i == j:
                    note = ('Меняем элемент сам с собой: он и так стоит сразу за '
                            'границей. Одна лишняя проверка тут дороже, чем обмен.')
                else:
                    note = ('Меняем: {} уехал за границу, а {} — на его место.'.format(
                        a[i], a[j]))
                snap(14, note=note)
            else:
                snap(12, check=False, note=(
                    '{} > {} — элемент остаётся в правой части, граница не '
                    'двигается.'.format(a[j], pivot)
                ))

        a[i + 1], a[hi] = a[hi], a[i + 1]
        state['a'] = list(a)
        snap(15, note=(
            'Отрезок пройден. Меняем опорный с первым элементом справа от '
            'границы — с позицией {}.'.format(i + 1)
        ))
        p = i + 1
        state['p'] = p
        snap(16, note=(
            'Опорный {} стоит на позиции {} — это его окончательное место.'.format(
                pivot, p)
        ))
        tasks.append([lo, p - 1])
        state['tasks'] = [list(t) for t in tasks]
        snap(17, note='Откладываем левый отрезок {}.'.format(seg(lo, p - 1)))
        tasks.append([p + 1, hi])
        state['tasks'] = [list(t) for t in tasks]
        snap(18, note='И правый — {}.'.format(seg(p + 1, hi)))

    snap(19, out=str(a), note='Список отсортирован.')
    return {
        'code': code,
        'vars': ['a', 'tasks', 'lo', 'hi', 'pivot', 'i', 'j', 'p'],
        'steps': steps,
    }


