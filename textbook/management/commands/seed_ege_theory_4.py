"""Разбор задания 4 ЕГЭ: условие Фано и подбор недостающих кодовых слов.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блока `code` нет вовсе, как и в задании 1. Норматив – 2 минуты, самое
  быстрое задание варианта: рисуется дерево, снимаются длины, складываются
  биты. Программа тут не ускоряет, а отвлекает;
* виджет `fano-code` (тот же, что в уроке учебника 7-4) стоит **внутри**
  разбора, а не после него: разбор ведётся по дереву, а рисует дерево
  виджет. Отсюда и деление на два текстовых блока – «рисуем дерево» перед
  ним и «раздаём концы и считаем» после. Второй способ – ASCII-дерево в
  блоке `pre` – отвергнут: то же дерево во второй раз, только хуже, и
  разойтись с виджетом оно может молча. Виджет стоит в урезанном виде
  (`minimal`): только таблица кодов и дерево, без ленты, вердикта и
  пресетов – здесь подбирают коды, а не разбирают чужое сообщение.

Блока «Если условие другое» здесь нет – по общему правилу скелета. Он был
написан (в банке fixtures/bank-4.json три жанра поровну: длина слова,
суммарная длина оставшихся кодов, само кратчайшее кодовое слово) и снят:
дерево во всех трёх строится одинаково, а разница сводится к одной строчке –
что именно писать в бланк. Это и осталось, последним пунктом «Типичных
ошибок», где оно и есть ошибка, а не отдельная тема.

Числа в тексте вычисляются, а не вписываются руками: `_solution()` подбирает
коды тем же жадным ходом, что и ученик (самое короткое свободное слово – самой
частой букве), `_sum_table()` собирает из них таблицу подсчёта, а `_check()`
сверяет итог с ответом ФИПИ. Разойдётся – команда упадёт здесь, а не выдаст
статью с враньём.

Условие – задание 4 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-04).

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
from collections import Counter

from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks
from textbook.templatetags.textbook_tags import plural

SLUG = 'ege-4-kodirovanie-i-uslovie-fano'

# Условие демоверсии: известные коды, буквы без кода, слово и ответ ФИПИ.
KNOWN = [('Б', '00'), ('Н', '010'), ('Л', '111')]
UNKNOWN = ('К', 'О')
WORD = 'КОЛОБОК'
ANSWER = 17


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _is_free(code, taken):
    """Можно ли отдать слово `code` новой букве, не нарушив условие Фано.

    Проверка двусторонняя, и вторая половина – та самая, которую забывают:
    мало того что занятый код не должен начинать наше слово, наше слово не
    должно начинать занятый код. Иначе «01» выглядело бы свободным при
    занятом «010».
    """
    return all(
        not code.startswith(t) and not t.startswith(code)
        for t in taken
    )


def _free_ends(taken):
    """Свободные концы дерева – ровно те, что виджет рисует пунктиром.

    Повторяет `addFree` из static/js/textbook-widgets.js: под узлом, который
    сам не буква, недостающая ветка становится свободным концом и дальше не
    растёт. Тем же разделением труда, что у `graph-match` в задании 1 –
    виджет показывает, а считает Python: разбор называет эти концы поимённо,
    и сверять их с картинкой глазами автор не должен.

    Порядок – по возрастанию длины, при равной длине по значению: это и есть
    правило «кратчайшее кодовое слово, при нескольких – наименьшее числом»,
    которым кончается часть задач этого номера.
    """
    nodes = {''}
    for code in taken:
        for k in range(len(code) + 1):
            nodes.add(code[:k])

    ends = []
    for node in nodes:
        if node in taken:
            continue          # под буквой дерево обрывается: буква – лист
        ends.extend(node + b for b in '01' if node + b not in nodes)
    return sorted(ends, key=lambda code: (len(code), code))


def _pick(count, taken):
    """`count` кодовых слов подряд: каждое взятое закрывает свою ветку целиком.

    Это и есть главная ловушка задания: отдали конец 10 букве – и 100, 101,
    1000… свободными концами быть перестали, они теперь ветки под буквой.
    Поэтому концы берутся по одному, со свежим пересчётом, а не отбираются
    все сразу из первоначального списка.
    """
    taken = list(taken)
    picked = []
    for _ in range(count):
        code = _free_ends(taken)[0]
        picked.append(code)
        taken.append(code)
    return picked


def _solution():
    """Коды всех букв, порядок раздачи и суммарная длина слова WORD.

    Буквы без кода выстраиваются по убыванию частоты в слове, и самое короткое
    свободное слово достаётся самой частой. Обмен доказывает, что иначе не
    выгоднее: отдать частой букве слово длиннее, а редкой короче – значит
    добавить к сумме разницу длин, помноженную на разницу частот.
    """
    known = dict(KNOWN)
    freq = Counter(WORD)
    order = sorted(UNKNOWN, key=lambda sym: (-freq[sym], sym))
    picked = _pick(len(order), known.values())

    codes = dict(known)
    codes.update(zip(order, picked))
    total = sum(len(codes[sym]) for sym in WORD)
    return codes, order, picked, total


def _sum_table(codes, order):
    """Markdown-таблица подсчёта битов: подобранные буквы, затем известные.

    Порядок строк повторяет ход решения – сначала то, что подбирали, потом то,
    что было дано. Известные буквы стоят в таблице не для полноты: их биты
    забывают складывать чаще всего, и строка в таблице напоминает о них
    нагляднее любого предостережения.
    """
    freq = Counter(WORD)
    rest = sorted(
        (sym for sym in freq if sym not in order),
        key=lambda sym: (-freq[sym], sym),
    )
    lines = [
        '| Буква | Код | Длина | Раз в слове | Битов |',
        '| --- | --- | --- | --- | --- |',
    ]
    for sym in list(order) + rest:
        code = codes[sym]
        mark = '**' if sym in order else ''
        lines.append(
            f'| {mark}{sym}{mark} | `{code}` | {len(code)} | {freq[sym]} '
            f'| {len(code) * freq[sym]} |'
        )
    total = sum(len(codes[sym]) for sym in WORD)
    lines.append(f'| **Итого** | | | {len(WORD)} | **{total}** |')
    return '\n'.join(lines)


def _check():
    """Ответ, полученный разбором, обязан совпасть с ответом ФИПИ.

    Заодно проверяются утверждения, на которые текст разбора опирается прямо:
    что свободных концов у дерева ровно три, что после раздачи первого их
    остаётся два и что они одной длины. Поменяется условие – упадёт команда,
    а не останется абзац, объясняющий несуществующую картинку.
    """
    codes, order, picked, total = _solution()
    assert total == ANSWER, f'разбор даёт {total}, у ФИПИ {ANSWER}'

    known_codes = [code for _, code in KNOWN]
    ends = _free_ends(known_codes)
    assert ends == ['10', '011', '110'], f'ожидались три конца, получено {ends}'

    rest = _free_ends(known_codes + [ends[0]])
    assert rest == ['011', '110'], f'после раздачи первого конца получено {rest}'
    assert len({len(code) for code in rest}) == 1, (
        'разбор опирается на то, что оставшиеся концы одной длины'
    )
    assert picked == ['10', '011'], f'ожидались коды 10 и 011, получены {picked}'
    assert list(order) == ['О', 'К'], f'ожидался порядок раздачи О, К – получен {order}'

    # Итоговая таблица обязана оставаться префиксным кодом: разбор учит
    # проверять именно это, и было бы неловко выдать таблицу с нарушением.
    all_codes = list(codes.values())
    for i, code in enumerate(all_codes):
        others = all_codes[:i] + all_codes[i + 1:]
        assert _is_free(code, others), f'код {code} нарушает условие Фано'


