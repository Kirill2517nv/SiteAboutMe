    @transaction.atomic
    def handle(self, *args, **options):
        _check()

        codes, order, picked, total = _solution()
        swapped = dict(codes)
        swapped[order[0]], swapped[order[1]] = picked[1], picked[0]
        swapped_total = sum(len(swapped[sym]) for sym in WORD)

        freq = Counter(WORD)
        known_codes = [code for _, code in KNOWN]
        free_ends = _free_ends(known_codes)

