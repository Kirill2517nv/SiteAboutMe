                '\n'
                '- **условие Фано**: ни одно кодовое слово не является началом '
                'другого – только тогда лента битов читается однозначно, без '
                'разделителей между буквами. Подробно – в учебнике: '
                + _link('7-4-neravnomernoe-kodirovanie', 'неравномерное кодирование') + ';\n'
                '- **кодовое дерево**: из каждого узла две ветки, влево $0$, '
