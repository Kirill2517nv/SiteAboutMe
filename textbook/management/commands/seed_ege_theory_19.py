def _trace_list():
    """Трасса `win((17, 28), 2)` вложенным списком Markdown.

    Строки берутся из `_trace()`, то есть из тех же `_win`/`_lose`, что
    считают ответы разбора: рассказ о вызовах не может разойтись с тем, что
    делает программа.
    """
    branches, (bad, save, save_top), (good, replies) = _trace()
    start = (FIRST, ANSWER_20[0])
    lines = []
    for pos, doomed in branches:
        head = f'- `lose({_pos(pos)}, 1)` → '
        if doomed:
            lines.append(head + '**True**: что бы Ваня ни ответил, у Пети '
                                'есть добивающий ход:')
            for reply, end in replies:
                lines.append(
                    f'    - Ваня ходит в {_pos(reply)}, Петя – в {_pos(end)}, '
                    f'сумма {sum(end)}'
                )
        elif pos == bad:
            lines.append(
                head + f'**False**: Ваня спасается ходом в {_pos(save)}, '
                f'откуда Петя дотягивается лишь до {save_top} при пороге {TOTAL}'
            )
        else:
            lines.append(head + '**False**: и здесь у Вани находится ответ, '
                                'после которого Петя не добивает')
    lines.append('')
    lines.append(
        f'Три первые ветки вернули `False`, четвёртая – `True`, значит и '
        f'`win({_pos(start)}, 2)` истинно. А `win({_pos(start)}, 1)` ложно: '
        f'одним ходом Петя добирается самое большее до '
        f'{max(sum(pos) for pos, _ in branches)}, а порог – {TOTAL}. Это и '
        f'есть вторая половина условия задания 20: «Петя не может выиграть '
        f'за один ход».'
    )
    return '\n'.join(lines)


def _moves_table():
    """Четыре хода Пети из позиции (17, 29) и потолок Вани после каждого.

    Строки берутся из `_first_moves()`, поэтому таблица статьи не может
    разойтись с числами `_check()`. Ход, после которого Ваня дотягивается до
    порога, выделяем жирным, а первую ячейку красим `<mark>`: правило
    `tr:has(mark) td` в static/css/textbook-article.css по этому `<mark>`
    красит всю строку, а сам `<mark>` в ячейке обесцвечен – он ничего не
    рисует, markdown-таблица ведь не умеет повесить класс на `<tr>`.
    """
    names = ['добавить 4 в первую кучу', 'добавить 4 во вторую кучу',
             'удвоить первую кучу', 'удвоить вторую кучу']
    lines = [
        '| Ход Пети | Позиция | Сумма | Максимум, которого достигнет Ваня '
        'следующим ходом |',
        '| --- | --- | --- | --- |',
    ]
    for name, (pos, total, top) in zip(names, _first_moves()):
        # Единственный ход, после которого Ваня заканчивает игру: Петя удвоил
        # вторую кучу, Ваня удваивает её ещё раз – 4 × 29 + 17 даёт порог ровно.
        finish = top == TOTAL
        bold = '**' if finish else ''
        first = f'<mark>{bold}{name}{bold}</mark>' if finish else name
        lines.append(
            f'| {first} | ({pos[0]}, {pos[1]}) | {total} | {bold}{top}{bold} |'
        )
    return '\n'.join(lines)


