"""Разбор заданий 19, 20 и 21 ЕГЭ: теория игр.

Три номера стоят на одном условии игры и решаются одной программой, поэтому
статья одна: она лежит на заглушке задания 19 и показывается на общей странице
связки 19–21. Вместе они дают 3 балла (по 1 за каждый номер), норматив –
22 минуты на все три.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* одиннадцать блоков вместо шести. Скелет написан про одно задание, а
  страница показывает три номера сразу, поэтому примеров два – две кучи из
  демоверсии и одна куча из банка: иначе связка объясняла бы только первый из
  трёх вопросов;
* два блока сверх скелета разбирают саму программу – «Как работают win и
  lose» про взаимную рекурсию и «Три строки с ответами» про генераторы. Без
  них статья показывала готовый код и молчала о том, почему он такой, а
  списать его целиком всё равно нельзя: в своём варианте другие числа;
* блок «Если условие другое» в скелете не значится, но здесь он главный:
  вариаций у 19–21 больше, чем у любого другого номера, а сводятся они к двум
  функциям. Таблица «что в условии → что править» избавляет от разбора
  каждой вариации заново;
* «Типичные ошибки» написаны без чисел разобранных задач: ученик приходит со
  своим вариантом, и ошибка у него та же (перепутанные `any` и `all`, не тот
  ходящий), а числа другие;
* виджет `ege-game-tree` стоит предпоследним, перед ошибками: до него
  разобраны обе игры, и дерево читается как инструмент, а не как картинка.
  Конфиг ему собирает WIDGET_CONFIG из тех же констант, что и текст.

Демонстрация – задания 19, 20 и 21 варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-19,
fipi-demo-2027-20, fipi-demo-2027-21). Однокучная задача – из
fixtures/bank-19-21.json, external_id kompege-19-23759.

`_win` и `_lose` в команде – те же функции, что в блоке `Решение`, только
правила игры переданы параметрами: ответы, таблица ходов и числа в тексте
берутся из них, а не вписываются руками. `_check()` сверяет их с ответами
ФИПИ и банка – разойдутся, и команда упадёт до публикации, вместо того чтобы
оставить статью с неверным разбором.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
