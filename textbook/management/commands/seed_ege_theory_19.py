def moves(pos):
    """Все позиции, в которые можно перейти из pos одним ходом."""
    a, b = pos
    return [(a + 4, b), (a, b + 4), (a * 2, b), (a, b * 2)]


def over(pos):
    """Игра кончилась: тот, кто сходил в эту позицию, победил."""
    return sum(pos) >= TOTAL


def win(pos, k):
    """Тот, чья очередь ходить, выигрывает не более чем за k своих ходов."""
    if k == 0:
        return False
    for nxt in moves(pos):
        if over(nxt) or lose(nxt, k - 1):
            return True
    return False


def lose(pos, k):
    """Тот, чья очередь ходить, проигрывает: соперник закончит не позже k-го хода."""
    for nxt in moves(pos):
        if over(nxt) or not win(nxt, k):
            return False
    return True


