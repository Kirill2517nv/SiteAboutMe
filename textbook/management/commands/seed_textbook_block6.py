def _self_check(slug, title, description, questions, replace=True):
    """Создаёт (или обновляет) тест самопроверки с вопросами.

    `replace=True` пересоздаёт вопросы – это нужно при переписывании урока,
    иначе на сайте остались бы старые формулировки. Если по тесту уже есть
    ответы учеников, замена не делается: удалять вопросы каскадом вместе с
    чужими ответами мы не будем.

    Поддерживаемые ключи вопроса: type, text, title, choices,
    correct_text_answer, alternative_answers, hint,
    test_cases [(stdin, stdout)].
    """
    quiz, created = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not created:
        quiz.title, quiz.description, quiz.is_self_check = title, description, True
        quiz.save(update_fields=['title', 'description', 'is_self_check'])

    if replace and quiz.questions.exists():
        if not UserAnswer.objects.filter(question__quiz=quiz).exists():
            quiz.questions.all().delete()

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                title=q.get('title', ''),
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                alternative_answers=q.get('alternative_answers'),
                hint=q.get('hint', ''),
                points=1,
            )
            for choice_text, is_correct in _shuffle_choices(q['text'], q.get('choices', [])):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
            for stdin, stdout in q.get('test_cases', []):
                TestCase.objects.create(question=question, input_data=stdin, output_data=stdout)
    else:
        # Вопросы уже решали – пересоздать нельзя, но условия обновить можно.
        _sync_question_texts(quiz, questions)
    return quiz


def _binary_digits_trace():
    """Трасса цикла, собирающего двоичную запись числа сдвигами.

    Виджет loop-trace ничего не считает сам – повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.
    """
    code = [
        'x = 13',
        "bits = ''",
        'while x > 0:',
        "    bits = str(x & 1) + bits",
        '    x = x >> 1',
        'print(bits)',
    ]
    steps = []
    x = 13
    steps.append({
        'line': 1, 'vars': {'x': x, 'bits': None},
        'note': 'Число, двоичную запись которого собираем вручную.',
    })
    bits = ''
    steps.append({
        'line': 2, 'vars': {'x': x, 'bits': bits},
        'note': 'Пустая строка-накопитель: цифры будем приписывать слева.',
    })
    while True:
        cond = x > 0
        steps.append({
            'line': 3, 'vars': {'x': x, 'bits': bits}, 'check': cond,
            'note': (
                f'x = {x}, единицы ещё есть – заходим в цикл.' if cond
                else 'x = 0: все биты уехали за правый край, цикл закончился.'
            ),
        })
        if not cond:
            break
        low = x & 1
        bits = str(low) + bits
        steps.append({
            'line': 4, 'vars': {'x': x, 'bits': bits},
            'note': f'Младший бит числа {x} равен {low} – приписали его слева к строке.',
        })
        prev = x
        x = x >> 1
        steps.append({
            'line': 5, 'vars': {'x': x, 'bits': bits},
            'note': (
                f'{prev} >> 1 = {x}: биты переехали на разряд вправо. Младший '
                'потерян, но он уже сохранён в строке.'
            ),
        })
    steps.append({
        'line': 6, 'vars': {'x': x, 'bits': bits}, 'out': bits,
        'note': 'Та же запись, что вернула бы bin(13) без цикла.',
    })
    return {'code': code, 'vars': ['x', 'bits'], 'steps': steps}


def _flags_trace():
    """Трасса цикла, который перечисляет включённые настройки по маскам.

    Как и в уроке 6.2, виджет ничего не считает: повторяем разбираемый
    алгоритм обычным циклом и складываем полное состояние каждого шага.
    """
    code = [
        "names = ['уведомления', 'тёмная тема', 'автосохранение', 'звук']",
        'settings = 165',
        'for i in range(4):',
        '    mask = 1 << i',
        '    if settings & mask:',
        '        print(names[i])',
    ]
    names = ['уведомления', 'тёмная тема', 'автосохранение', 'звук']
    settings = 165
    var_names = ['i', 'mask', 'settings & mask']

    def state(i=None, mask=None, hit=None):
        return {'i': i, 'mask': mask, 'settings & mask': hit}

    steps = [
        {
            'line': 1, 'vars': state(),
            'note': 'Названия настроек по порядку битов: индекс в списке – номер бита.',
        },
        {
            'line': 2, 'vars': state(),
            'note': f'Все настройки одним числом: {settings} = {settings:08b}.',
        },
    ]
    mask = None
    hit = None
    for i in range(4):
        steps.append({
            'line': 3, 'vars': state(i, mask, hit),
            'note': f'Итерация {i + 1} из четырёх: проверяем бит {i}.',
        })
        mask = 1 << i
        steps.append({
            'line': 4, 'vars': state(i, mask, hit),
            'note': (
                f'Маска считается, а не пишется руками: 1 << {i} = {mask} = '
                f'{mask:08b} – единица ровно в разряде {i}.'
            ),
        })
        hit = settings & mask
        steps.append({
            'line': 5, 'vars': state(i, mask, hit), 'check': bool(hit),
            'note': (
                f'{settings:08b} & {mask:08b} = {hit:08b}. '
                + (
                    f'Не ноль ({hit}) – значит бит поднят.' if hit
                    else 'Ноль – бит погашен, печатать нечего.'
                )
            ),
        })
        if hit:
            steps.append({
                'line': 6, 'vars': state(i, mask, hit), 'out': names[i],
                'note': f'Настройка «{names[i]}» включена.',
            })
    steps.append({
        'line': 3, 'vars': state(3, mask, hit),
        'note': (
            'Диапазон закончился, цикл завершён. Четыре проверки – один '
            'цикл и одна вычисляемая маска.'
        ),
    })
    return {'code': code, 'vars': var_names, 'steps': steps}


def _popcount_trace():
    """Трасса подсчёта единиц приёмом `x &= x - 1` (урок 6.4).

    Виджет loop-trace ничего не считает сам – повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.
    """
    code = [
        'x = 156',
        'count = 0',
        'while x:',
        '    x = x & (x - 1)',
        '    count = count + 1',
        'print(count)',
    ]
    var_names = ['x', 'x - 1', 'count']

    def state(x, count):
        return {'x': x, 'x - 1': (x - 1) if x else None, 'count': count}

    x = 156
    count = None
    steps = [{
        'line': 1, 'vars': state(x, count),
        'note': f'{x} = {x:08b} – четыре единицы. Их и будем гасить по одной.',
    }]
    count = 0
    steps.append({
        'line': 2, 'vars': state(x, count),
        'note': 'Счётчик: сколько единиц уже погашено.',
    })
    while True:
        cond = x != 0
        steps.append({
            'line': 3, 'vars': state(x, count), 'check': cond,
            'note': (
                f'x = {x:08b} – единицы ещё остались, заходим в цикл.' if cond
                else 'x = 0: гасить больше нечего, цикл закончился.'
            ),
        })
        if not cond:
            break
        bit = (x & -x).bit_length() - 1
        prev = x
        x = x & (x - 1)
        steps.append({
            'line': 4, 'vars': state(x, count),
            'note': (
                f'{prev:08b} & {prev - 1:08b} = {x:08b} – погасла младшая '
                f'единица, та, что стояла в разряде {bit}.'
            ),
        })
        count += 1
        steps.append({
            'line': 5, 'vars': state(x, count),
            'note': f'Единиц погашено: {count}.',
        })
    steps.append({
        'line': 6, 'vars': state(x, count), 'out': str(count),
        'note': (
            'Столько единиц было в числе 156. Цикл сделал ровно четыре шага – '
            'по одному на единицу; в нулевые разряды он вообще не заглядывал.'
        ),
    })
    return {'code': code, 'vars': var_names, 'steps': steps}


