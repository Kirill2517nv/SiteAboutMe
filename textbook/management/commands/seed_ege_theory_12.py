# Алфавит: нулевой символ – пустая ячейка ленты.
ALPHABET = ['λ', '0', '1']
STATES = ['q0', 'q1', 'q2']
# Состояние -> команды, выровненные по ALPHABET. Пустая строка – клетка,
# которой в программе нет.
PROGRAM = {
    'q0': ['λ, L, q1', '', ''],
    'q1': ['1, L, q2', '0, L, q1', '1, L, q1'],
    'q2': ['λ, S, q2', '', ''],
}

# Разминочный пример из того же описания ФИПИ: все «Z» на ленте меняются на
# «X», исполнитель встаёт в первую ячейку слева от них. Таблица набрана здесь
# руками с листа варианта, поэтому её работу проверяет _check() тем же
# исполнителем, что и основную: опечатка в клетке иначе ушла бы в статью
# вместе с обещанием, которого программа не выполняет.
EXAMPLE_ALPHABET = ['λ', 'Z']
EXAMPLE_STATES = ['q0', 'q1', 'q2']
EXAMPLE_PROGRAM = {
    'q0': ['λ, L, q0', 'X, L, q1'],
    'q1': ['λ, L, q1', 'X, L, q2'],
    'q2': ['λ, S, q2', 'X, L, q2'],
}
EXAMPLE_TAPE = 'ZZZZ'   # лента из условия: … λ λ Z Z Z Z λ λ …
EXAMPLE_HEAD = 5        # вторая справа пустая ячейка

NUMBER = 2025       # что записано на ленте в двоичном виде
ANSWER = 4073       # ответ ФИПИ
STEPS = 14          # столько тактов делает исполнитель
WRONG_RIGHT = 4051  # ответ того, кто приписал единицу справа, а не слева

# Такты, на которые разбор раскладывает работу исполнителя. Их сумма с числом
# цифр обязана дать STEPS – это и проверяет _check().
RAMP = 1    # разгон: головка шагает с пустой ячейки на последнюю цифру
WRITE = 1   # запись единицы слева от числа
STOP = 1    # остановка командой `λ, S, q2`
MOVE = {'L': -1, 'R': 1, 'N': 0, 'S': 0}


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _execute(program, alphabet, tape_str, head, state='q0', limit=1000, log=None):
    """Исполняет любую программу МТ; отдаёт (слово на ленте, такты, головка, состояние).

    Лента – словарь `{индекс: символ}`, пустые ячейки в нём просто
    отсутствуют: символы строки `tape_str` лежат в ячейках от нулевой, всё
    вокруг пусто. `head` – индекс стартовой ячейки, он может быть и за
    пределами строки, и отрицательным. Ученик делает то же самое на бумаге;
    здесь это делает Python, и потому числа в статье не могут разойтись с
    программой.

    Функция общая на обе программы блока «Типовой пример» – и на разминочный
    пример ФИПИ, и на саму задачу: обе таблицы набраны здесь руками, и
    проверять их надо одинаково.

    Клетка, которой в программе нет, роняет команду `ValueError` из
    распаковки: это и есть «в разборе ошибка» из блока 1, и заметить её лучше
    при наполнении статьи, чем на экзамене.

    `log` – список, в который складывается по строчке на такт. Из него блок
    «Как рассуждать» собирает трассу первых тактов: она обязана быть той же
    самой, что и ответ, а не набранной отдельно по памяти.
    """
    empty = alphabet[0]
    tape = {i: sym for i, sym in enumerate(tape_str) if sym != empty}
    steps = 0

    while True:
        symbol = tape.get(head, empty)
        was = state
        write, move, state = [
            part.strip()
            for part in program[state][alphabet.index(symbol)].split(',')
        ]
        if log is not None:
            log.append({
                'step': steps + 1, 'state': was, 'symbol': symbol,
                'write': write, 'move': move, 'next': state,
            })
        if write == empty:
            tape.pop(head, None)
        else:
            tape[head] = write
        head += MOVE[move]
        steps += 1
        if move == 'S':
            break
        assert steps < limit, 'программа зациклилась'

    filled = sorted(tape)
    word = ''.join(tape.get(i, empty) for i in range(filled[0], filled[-1] + 1))
    return word, steps, head, state


def _run():
    """Задача демоварианта: число NUMBER на ленте, головка справа от него."""
    binary = format(NUMBER, 'b')
    word, steps, _, _ = _execute(PROGRAM, ALPHABET, binary, len(binary))
    return word, steps


# Подписи короткие: колонка статьи узкая, и «сдвигаем стрелку влево» в пятой
# колонке таблицы разъезжалось на четыре строки в каждой ячейке.
MOVE_WORD = {'L': 'влево', 'R': 'вправо', 'N': 'на месте', 'S': 'стоп'}


def _trace_table():
    """Трасса первых тактов – то, что ученик пишет в тетради строчка за строчкой.

    Собирается из журнала `_execute()`, а не набирается руками: это тот же
    прогон, который дал ответ, и разойтись с таблицей команд он не может.

    Середина прохода по цифрам сворачивается в одну строку: девять одинаковых
    строчек подряд не учат ничему, кроме того, что их девять, – а вот вход в
    проход и выход из него надо видеть по тактам.
    """
    log = []
    binary = format(NUMBER, 'b')
    _execute(PROGRAM, ALPHABET, binary, len(binary), log=log)

    def action(row):
        parts = [f'пишем `{row["write"]}`', MOVE_WORD[row['move']]]
        if row['move'] != 'S':
            parts.append(f'`{row["next"]}`')
        return ', '.join(parts)

    def line(row):
        cmd = PROGRAM[row['state']][ALPHABET.index(row['symbol'])]
        return (f'| {row["step"]} | `{row["state"]}` над `{row["symbol"]}` '
                f'| `{cmd}` | {action(row)} |')

    lines = [
        '| Такт | Стрелка | Команда | Что делаем |',
        '| --- | --- | --- | --- |',
    ]
    head, tail = log[:3], log[-2:]
    middle = log[3:-2]
    lines += [line(row) for row in head]
    if middle:
        states = sorted({row['state'] for row in middle})
        cmds = sorted({
            PROGRAM[row['state']][ALPHABET.index(row['symbol'])]
            for row in middle
        })
        lines.append(
            f'| {middle[0]["step"]}–{middle[-1]["step"]} '
            f'| {" и ".join(f"`{st}`" for st in states)} над цифрами '
            f'| {" и ".join(f"`{c}`" for c in cmds)} '
            '| цифра не меняется, стрелка ползёт влево |'
        )
    lines += [line(row) for row in tail]
    return '\n'.join(lines)


def _table(program, alphabet, states):
    """Markdown-таблица команд: строка – состояние, столбец – символ.

    Собирается из той же программы, по которой считает `_execute()`, а не
    вписывается строкой – иначе таблицу в статье и таблицу исполнителя можно
    было бы править порознь.
    """
    lines = [
        '| | ' + ' | '.join(f'`{sym}`' for sym in alphabet) + ' |',
        '| --- |' + ' --- |' * len(alphabet),
    ]
    for state in states:
        cells = [f'`{cmd}`' if cmd else '' for cmd in program[state]]
        lines.append(f'| `{state}` | ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)


def _program_table():
    """Таблица команд самой задачи."""
    return _table(PROGRAM, ALPHABET, STATES)


def _generic_table():
    """Схема таблицы из описания ФИПИ: строки $q_i$, столбцы $a_j$, «команда».

    Единственная таблица статьи, которая ничего не исполняет, – это картинка
    из условия. Индексы здесь нижние, как у ФИПИ: `a_{n-1}` в строку не
    записать так, чтобы это читалось.
    """
    dots = '$\\ldots$'
    head = ['$a_0$', '$a_1$', dots, '$a_{n-1}$']
    rows = ['$q_0$', '$q_1$', dots, '$q_{n-1}$']
    lines = [
        '| | ' + ' | '.join(head) + ' |',
        '| --- |' + ' --- |' * len(head),
    ]
    for name in rows:
        # В строке многоточий многоточия стоят везде, в обычной – только
        # в колонке многоточий.
        cells = [dots if name == dots or col == dots else 'команда' for col in head]
        lines.append(f'| {name} | ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)


def _check():
    """Ответ, полученный разбором, обязан совпасть с ответом ФИПИ.

    Заодно проверяются утверждения, на которые текст опирается прямо: что
    единица приписалась слева (на ней держится весь блок «Как рассуждать»),
    что она стала новым старшим разрядом – то есть исходное число осталось на
    месте и разбор верно называет слагаемое, – и что раскладка тактов на
    разгон, цифры, запись и остановку сходится с той, что исполнил `_run()`.
    """
    word, steps = _run()
    binary = format(NUMBER, 'b')

    assert int(word, 2) == ANSWER, f'разбор даёт {int(word, 2)}, у ФИПИ {ANSWER}'
    assert steps == STEPS, f'исполнитель сделал {steps} тактов, в условии {STEPS}'
    assert word == '1' + binary, f'ожидалась единица слева, получено {word}'
    assert ANSWER == NUMBER + 2 ** len(binary), (
        'формула «приписать единицу слева» не даёт ответа ФИПИ'
    )
    assert WRONG_RIGHT == 2 * NUMBER + 1, (
        'контрольное число из блока ошибок не сходится'
    )
    assert RAMP + len(binary) + WRITE + STOP == steps, (
        'раскладка тактов в блоке 5 не сходится с исполнением'
    )

    # Разминочный пример из описания ФИПИ обещает три вещи, и все три
    # проверяемы: все «Z» стали «X», головка встала в первую ячейку слева от
    # них, состояние в конце – `q2`. Таблица набрана с листа руками, так что
    # опечатку ловить больше нечем.
    ex_word, _, ex_head, ex_state = _execute(
        EXAMPLE_PROGRAM, EXAMPLE_ALPHABET, EXAMPLE_TAPE, EXAMPLE_HEAD,
    )
    assert ex_word == 'X' * len(EXAMPLE_TAPE), (
        f'пример ФИПИ обещает одни «X», получено {ex_word}'
    )
    assert ex_head == -1, (
        f'пример ФИПИ обещает остановку слева от «X», головка на {ex_head}'
    )
    assert ex_state == EXAMPLE_STATES[-1], (
        f'пример ФИПИ обещает конечное состояние {EXAMPLE_STATES[-1]}, '
        f'получено {ex_state}'
    )


