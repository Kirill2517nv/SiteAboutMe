"""Разбор задания 14 ЕГЭ: вычисления в недесятичных системах счисления.

Статья разбирает три типа условия – по одному на каждый:

* неизвестная цифра в записи операндов – задание 14 демонстрационного
  варианта ФИПИ-2027 (fixtures/variant_fipi_demo_2027.json, external_id
  fipi-demo-2027-14);
* значащие нули в записи выражения – задание из банка
  (fixtures/bank-14.json, external_id kompege-14-17869);
* нули в записи выражения со слагаемым x – тоже банк
  (fixtures/bank-14.json, external_id kompege-14-17870).

Порядок – от простого к сложному: во втором типе цифры числа снимаются
циклом `%` и `//`, в третьем тот же цикл оборачивается перебором x.

Скелет docs/ege-theory-brief.md повторён трижды – условие, «как рассуждать»,
блок `code`, – и сходится в одних «Типичных ошибках». Три списка ошибок были
бы одним текстом в трёх местах: ловушки у типов общие (цифра подставлена
строкой, ответ не на тот вопрос, одиночное деление, подсчёт в десятичной
записи), меняется только условие, в котором они встречаются.

Листинги лежат модульными константами и исполняются в `_check()`: напечатанное
сверяется с константами-ответами, а числа в тексте подставляются из них же
f-строками. Разойдётся условие с кодом – упадёт команда, а не выйдет статья
с ответом, которого код не даёт.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
