def _replace_blocks(article, blocks):
    article.blocks.all().delete()
    for b in blocks:
        ArticleBlock.objects.create(article=article, **b)


def _self_check(slug, title, description, questions):
    """Создаёт (или переиспользует) тест самопроверки с вопросами."""
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check:
        quiz.is_self_check = True
        quiz.save(update_fields=['is_self_check'])

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                points=1,
            )
            for choice_text, is_correct in q.get('choices', []):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
    return quiz


# Код, который трассирует loop-trace в уроке 10.1: линейный поиск из урока 9.5,
# но с добавленным счётчиком сравнений. Смысл трассы — не сам поиск (он уже
# знаком), а поведение счётчика: искомого числа в списке нет, поэтому счётчик
# доходит ровно до длины списка — это и есть худший случай.
SEARCH_CODE = [
    'nums = [-3, 0, 5, -8, 2, 7, -1]',
    'target = 4',
    'steps = 0',
    'found = False',
    'for i in range(len(nums)):',
    '    steps = steps + 1',
    '    if nums[i] == target:',
    '        found = True',
    '        break',
    'print(found, steps)',
]


def _search_trace(data=(-3, 0, 5, -8, 2, 7, -1), target=4):
    """Пошаговая трасса линейного поиска со счётчиком сравнений.

    Виджет ничего не вычисляет сам — повторяем разбираемый алгоритм обычным
    циклом и складываем ПОЛНОЕ состояние на каждом шаге. Счётчик steps держим
    в состоянии постоянно: именно его рост — главное, за чем следит ученик.
    """
    steps = []
    nums = list(data)
    cnt = None
    found = None
    i = None

    def state():
        s = {'nums': list(nums), 'target': target}
        if cnt is not None:
            s['steps'] = cnt
        if found is not None:
            s['found'] = found
        if i is not None:
            s['i'] = i
            s['nums[i]'] = nums[i]
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Семь чисел в списке. Размер входных данных N = 7 — именно от него '
             'мы будем считать число действий.',
    ))
    steps.append(dict(
        line=2, vars=state(),
        note='Ищем число 4. В списке его нет — это важно, так мы попадём в '
             'худший случай.',
    ))

    cnt = 0
    steps.append(dict(
        line=3, vars=state(),
        note='Заводим счётчик сравнений. В самой задаче он не нужен — он нужен '
             'нам, чтобы измерить цену алгоритма.',
    ))

    found = False
    steps.append(dict(
        line=4, vars=state(),
        note='Пока считаем, что искомого числа нет.',
    ))

    stopped = False
    for pos in range(len(nums)):
        i = pos
        steps.append(dict(
            line=5, vars=state(),
            note='Берём индекс i = {}. По этому номеру лежит {}.'.format(pos, nums[pos]),
        ))

        cnt += 1
        steps.append(dict(
            line=6, vars=state(),
            note='Готовимся к очередному сравнению: счётчик стал {}.'.format(cnt),
        ))

        hit = nums[pos] == target
        steps.append(dict(
            line=7, vars=state(), check=hit,
            note='{} == {}? {} — {}.'.format(
                nums[pos], target,
                'да' if hit else 'нет',
                'элемент найден' if hit else 'идём дальше',
            ),
        ))
        if hit:
            found = True
            steps.append(dict(line=8, vars=state(), note='Запомнили, что нашли.'))
            steps.append(dict(
                line=9, vars=state(),
                note='break прерывает цикл: остальные элементы проверять незачем.',
            ))
            stopped = True
            break

    if not stopped:
        i = None
        steps.append(dict(
            line=5, vars=state(),
            note='Индексы кончились, цикл завершён. Счётчик показывает {} — ровно '
                 'длину списка.'.format(cnt),
        ))

    steps.append(dict(
        line=10, vars=state(), out='{} {}'.format(found, cnt),
        note='Числа в списке не оказалось, и убедиться в этом можно было только '
             'одним способом — проверив все N элементов. Это и есть худший '
             'случай линейного поиска: N сравнений. А если бы искали −3, break '
             'сработал бы после первого же сравнения.',
    ))
    return steps


# Код, который трассирует loop-trace в уроке 10.2: проверка «есть ли в списке
# два одинаковых числа» двойным перебором. Внутренний цикл начинается с i + 1,
# поэтому сравнений выходит N·(N−1)/2 — вдвое меньше полного перебора пар,
# и это ровно тот случай, когда «вдвое меньше» ничего не меняет: класс всё
# равно O(N²). Одинаковых чисел в списке нет — худший случай.
PAIRS_CODE = [
    'nums = [5, 3, 9, 1]',
    'steps = 0',
    'for i in range(len(nums)):',
    '    for j in range(i + 1, len(nums)):',
    '        steps = steps + 1',
    '        if nums[i] == nums[j]:',
    '            print("Есть одинаковые")',
    'print(steps)',
]


def _pairs_trace(data=(5, 3, 9, 1)):
    """Пошаговая трасса двойного перебора пар со счётчиком сравнений."""
    nums = list(data)
    n = len(nums)
    out = []
    cnt = None
    i = None
    j = None

    def state():
        s = {'nums': list(nums)}
        if cnt is not None:
            s['steps'] = cnt
        if i is not None:
            s['i'] = i
            s['nums[i]'] = nums[i]
        if j is not None:
            s['j'] = j
            s['nums[j]'] = nums[j]
        return s

    out.append(dict(
        line=1, vars=state(),
        note='Четыре числа, размер данных N = 4. Одинаковых среди них нет — '
             'значит, алгоритм отработает полностью, до последней пары.',
    ))

    cnt = 0
    out.append(dict(
        line=2, vars=state(),
        note='Счётчик сравнений. Он нужен не задаче, а нам — чтобы измерить цену.',
    ))

    for a in range(n):
        i = a
        j = None
        out.append(dict(
            line=3, vars=state(),
            note='Внешний цикл: берём i = {} и будем сравнивать nums[{}] = {} '
                 'со всеми, кто стоит правее.'.format(a, a, nums[a]),
        ))

        for b in range(a + 1, n):
            j = b
            out.append(dict(
                line=4, vars=state(),
                note='Внутренний цикл начинается с i + 1 = {}, поэтому пару '
                     '({}, {}) мы проверяем ровно один раз.'.format(a + 1, a, b),
            ))

            cnt += 1
            out.append(dict(
                line=5, vars=state(),
                note='Счётчик сравнений стал {}.'.format(cnt),
            ))

            hit = nums[a] == nums[b]
            out.append(dict(
                line=6, vars=state(), check=hit,
                note='{} == {}? {} — {}.'.format(
                    nums[a], nums[b],
                    'да' if hit else 'нет',
                    'одинаковые нашлись' if hit else 'идём к следующей паре',
                ),
            ))

        j = None
        left = n - 1 - a
        out.append(dict(
            line=4, vars=state(),
            note='Для i = {} пары кончились: сделано {} {}. Обратите внимание, '
                 'что с каждым разом внутренний цикл всё короче.'.format(
                     a, left,
                     'сравнение' if left == 1 else ('сравнения' if 2 <= left <= 4 else 'сравнений'),
                 ),
        ))

    i = None
    j = None
    out.append(dict(
        line=8, vars=state(), out=str(cnt),
        note='Итого {} сравнений — это 4·3/2, то есть примерно половина от N². '
             'Половина — постоянный множитель, а его O-нотация отбрасывает: '
             'сложность алгоритма O(N²). Для списка из 100 чисел сравнений '
             'будет уже 4950, для 1000 — почти полмиллиона.'.format(cnt),
    ))
    return out


