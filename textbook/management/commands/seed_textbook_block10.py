def _self_check(slug, title, description, questions):
    """Создаёт (или обновляет) тест самопроверки с вопросами.

    Поддерживаемые ключи вопроса: type, text, title, choices,
    correct_text_answer, alternative_answers, hint,
    test_cases [(stdin, stdout)].
    """
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check or quiz.title != title or quiz.description != description:
        quiz.title, quiz.description, quiz.is_self_check = title, description, True
        quiz.save(update_fields=['title', 'description', 'is_self_check'])

    # Тест ещё никто не решал – пересоздаём вопросы, чтобы до базы доехали
    # и правки формулировок, и перемешанный порядок вариантов ответа.
    if quiz.questions.exists() and not UserAnswer.objects.filter(question__quiz=quiz).exists():
        quiz.questions.all().delete()

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                title=q.get('title', ''),
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                alternative_answers=q.get('alternative_answers'),
                hint=q.get('hint', ''),
                points=1,
            )
            for choice_text, is_correct in _shuffle_choices(q['text'], q.get('choices', [])):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
            for stdin, stdout in q.get('test_cases', []):
                TestCase.objects.create(question=question, input_data=stdin, output_data=stdout)
    # Правки формулировок должны доезжать и до тестов, которые уже решали:
    # пересоздать вопросы там нельзя – каскад унёс бы ответы учеников.
    _sync_question_texts(quiz, questions)
    return quiz


# Код, который трассирует loop-trace в уроке 10.5: двоичный поиск числа,
# которого в списке нет. Смысл трассы – не найти число, а показать, что
# отрезок каждый раз делится пополам и за четыре проверки становится пустым.
BINSEARCH_CODE = [
    'a = [2, 5, 8, 12, 16, 23, 38, 56, 72, 91]',
    'x = 40',
    'lo = 0',
    'hi = len(a) - 1',
    'pos = -1',
    'while lo <= hi:',
    '    mid = (lo + hi) // 2',
    '    if a[mid] == x:',
    '        pos = mid',
    '        break',
    '    if a[mid] < x:',
    '        lo = mid + 1',
    '    else:',
    '        hi = mid - 1',
    'print(pos)',
]


def _binsearch_trace(data=(2, 5, 8, 12, 16, 23, 38, 56, 72, 91), target=40):
    """Пошаговая трасса двоичного поиска отсутствующего числа.

    Виджет ничего не вычисляет сам – повторяем разбираемый код обычным
    циклом и складываем ПОЛНОЕ состояние на каждом шаге. Искомого в списке
    нет, поэтому цикл доходит до пустого отрезка: lo оказывается больше hi.
    """
    steps = []
    a = list(data)
    lo = None
    hi = None
    mid = None
    pos = None

    def state():
        s = {'a': list(a), 'x': target}
        if lo is not None:
            s['lo'] = lo
        if hi is not None:
            s['hi'] = hi
        if mid is not None:
            s['mid'] = mid
            s['a[mid]'] = a[mid]
        if pos is not None:
            s['pos'] = pos
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Десять чисел по возрастанию. Размер данных N = 10 – число '
             'проверок будет считаться от него.',
    ))
    steps.append(dict(
        line=2, vars=state(),
        note='Ищем число 40. В списке его нет – значит, цикл пройдёт до '
             'конца и упрётся в пустой отрезок.',
    ))

    lo = 0
    steps.append(dict(
        line=3, vars=state(),
        note='Левая граница отрезка – индекс 0, он входит в отрезок.',
    ))
    hi = len(a) - 1
    steps.append(dict(
        line=4, vars=state(),
        note='Правая граница – индекс последнего элемента, 9. Она тоже '
             'входит: границы включительные.',
    ))
    pos = -1
    steps.append(dict(
        line=5, vars=state(),
        note='Пока считаем, что числа нет. Это значение и вернётся, если '
             'поиск не найдёт ничего.',
    ))

    stopped = False
    while lo <= hi:
        steps.append(dict(
            line=6, vars=state(), check=True,
            note='lo = {} не больше hi = {}, отрезок не пуст – можно '
                 'продолжать.'.format(lo, hi),
        ))
        mid = (lo + hi) // 2
        steps.append(dict(
            line=7, vars=state(),
            note='Середина отрезка: ({0} + {1}) // 2 = {2}. Индекс {2}, '
                 'значение {3}.'.format(lo, hi, mid, a[mid]),
        ))
        hit = a[mid] == target
        steps.append(dict(
            line=8, vars=state(), check=hit,
            note='{} == {}? {} – идём дальше.'.format(
                a[mid], target, 'да' if hit else 'нет'),
        ))
        if hit:
            pos = mid
            steps.append(dict(line=9, vars=state(), note='Запомнили позицию.'))
            steps.append(dict(
                line=10, vars=state(),
                note='break: остальные элементы проверять незачем.',
            ))
            stopped = True
            break

        less = a[mid] < target
        steps.append(dict(
            line=11, vars=state(), check=less,
            note='{} меньше {}? {} – {}.'.format(
                a[mid], target, 'да' if less else 'нет',
                'искомое правее, левую половину можно отбросить'
                if less else 'искомое левее, правую половину можно отбросить'),
        ))
        if less:
            lo = mid + 1
            steps.append(dict(
                line=12, vars=state(),
                note='Левая граница переехала на mid + 1: сам mid меньше '
                     'искомого и в новый отрезок не входит.',
            ))
        else:
            hi = mid - 1
            steps.append(dict(
                line=14, vars=state(),
                note='Правая граница переехала на mid - 1: сам mid больше '
                     'искомого и в новый отрезок не входит.',
            ))

    if not stopped:
        steps.append(dict(
            line=6, vars=state(), check=False,
            note='lo = {} больше hi = {} – отрезок пуст. Продолжать негде: '
                 'все элементы, которые могли подойти, отброшены.'.format(lo, hi),
        ))

    steps.append(dict(
        line=15, vars=state(), out='-1',
        note='Четыре проверки вместо десяти – и вывод -1. Числа 40 в списке '
             'нет, но убедились в этом не перебором: каждый шаг вдвое '
             'укорачивал отрезок, пока тот не стал пустым (lo > hi).',
    ))
    return steps


