def _run(code):
    """Запускает код блока статьи и возвращает напечатанные пары чисел."""
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        exec(code, {})
    return [tuple(map(int, line.split())) for line in out.getvalue().splitlines()]


