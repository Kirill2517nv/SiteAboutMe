def _self_check(slug, title, description, questions):
    """Создаёт (или переиспользует) тест самопроверки с вопросами."""
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check:
        quiz.is_self_check = True
        quiz.save(update_fields=['is_self_check'])

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                points=1,
            )
            for choice_text, is_correct in q.get('choices', []):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
    return quiz


# Код, который трассирует loop-trace в уроке 9.1: цикл повышает каждую оценку
# на балл. Смысл трассы — показать главное свойство list: список меняется
# на месте, а копия, снятая срезом до цикла, остаётся прежней.
MARKS_CODE = [
    'marks = [5, 4, 3, 5, 4]',
    'backup = marks[:]',
    'for i in range(len(marks)):',
    '    marks[i] = marks[i] + 1',
    'print(marks)',
    'print(backup)',
]


def _marks_trace(start=(5, 4, 3, 5, 4)):
    """Пошаговая трасса цикла, меняющего список на месте.

    Виджет ничего не вычисляет сам — повторяем разбираемый алгоритм обычным
    циклом и складываем ПОЛНОЕ состояние на каждом шаге. backup показываем
    в состоянии намеренно: смысл трассы в том, что он не меняется ни разу.
    """
    steps = []
    marks = None
    backup = None
    i = None

    def state():
        s = {}
        if marks is not None:
            s['marks'] = list(marks)
        if backup is not None:
            s['backup'] = list(backup)
        if i is not None:
            s['i'] = i
            s['marks[i]'] = marks[i]
        return s

    marks = list(start)
    steps.append(dict(
        line=1, vars=state(),
        note='Пять оценок лежат под одним именем, каждая доступна по своему номеру.',
    ))

    backup = marks[:]
    steps.append(dict(
        line=2, vars=state(),
        note='Срез скопировал всю ленту. backup — новый список, а не второе имя '
             'для marks: дальше он меняться не будет.',
    ))

    for pos in range(len(marks)):
        i = pos
        steps.append(dict(
            line=3, vars=state(),
            note='Берём очередной индекс: i = {}. По этому номеру сейчас лежит '
                 '{}.'.format(pos, marks[pos]),
        ))
        was = marks[pos]
        marks[pos] = was + 1
        note = 'Записали {} на место {}: было {}, стало {}.'.format(
            marks[pos], pos, was, marks[pos])
        if pos == 0:
            note += (' Список изменился на месте — новый объект не создавался, '
                     'id(marks) остался прежним. Со строкой так было нельзя.')
        steps.append(dict(line=4, vars=state(), note=note))

    i = None
    steps.append(dict(
        line=3, vars=state(),
        note='Индексы кончились — цикл завершён.',
    ))
    steps.append(dict(
        line=5, vars=state(), out=str(marks),
        note='Все оценки выросли на балл.',
    ))
    steps.append(dict(
        line=6, vars=state(), out=str(backup),
        note='А копия осталась ровно такой, какой её сняли до цикла.',
    ))
    return steps


# Код, который трассирует loop-trace в уроке 9.2: попытка убрать все нули
# удалением прямо во время перебора. Смысл трассы — показать скрытый счётчик
# цикла: список укорачивается влево, счётчик растёт вправо, элемент проскакивает.
REMOVE_CODE = [
    'nums = [1, 0, 0, 3]',
    'for x in nums:',
    '    if x == 0:',
    '        nums.remove(x)',
    'print(nums)',
]


def _remove_trace(start=(1, 0, 0, 3)):
    """Пошаговая трасса цикла, удаляющего элементы из перебираемого списка.

    Повторяем поведение for-по-списку вручную, через явный индекс: именно
    этот индекс в коде не виден, и именно из-за него теряется элемент.
    Переменную счётчика показываем в состоянии под именем «позиция».
    """
    steps = []
    nums = list(start)
    x = None
    pos = None

    def state():
        s = {'nums': list(nums)}
        if pos is not None:
            s['позиция'] = pos
        if x is not None:
            s['x'] = x
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Четыре числа, два нуля. Задача — убрать из списка все нули.',
    ))

    pos = 0
    while pos < len(nums):
        x = nums[pos]
        note = 'Цикл берёт элемент с позиции {}: x = {}.'.format(pos, x)
        if pos == 0:
            note += (' Этой позиции в коде не видно — счётчик у for свой, '
                     'внутренний, и он просто растёт на единицу каждый шаг.')
        steps.append(dict(line=2, vars=state(), note=note))

        is_zero = (x == 0)
        steps.append(dict(
            line=3, vars=state(), check=is_zero,
            note='Проверяем: {} {} нулю.'.format(x, 'равен' if is_zero else 'не равен'),
        ))

        if is_zero:
            nums.remove(x)
            steps.append(dict(
                line=4, vars=state(),
                note='Нуль удалён, и всё, что было правее, уехало влево на одну '
                     'клетку. В списке осталось {} элемента.'.format(len(nums)),
            ))

        pos += 1

    # x намеренно не сбрасываем: после цикла переменная в Python сохраняет
    # последнее значение, и в трассе она должна вести себя так же.
    steps.append(dict(
        line=2, vars=state(),
        note='Счётчик дорос до {}, а в списке всего {} элемента — индексы 0–{}. '
             'Брать больше нечего, цикл заканчивается.'.format(
                 pos, len(nums), len(nums) - 1),
    ))
    steps.append(dict(
        line=5, vars=state(), out=str(nums),
        note='Один нуль уцелел. После удаления он встал на позицию, которую '
             'счётчик уже прошёл, — цикл до него просто не добрался.',
    ))
    return steps


# Код, который трассирует loop-trace в уроке 9.3. Списочное выражение
# записано в несколько строк (Python это разрешает) специально: тогда
# подсветка строки честно показывает порядок исполнения — сначала for,
# потом if и только потом самое верхнее выражение.
COMPREHENSION_CODE = [
    'nums = [3, 8, 5, 12, 7]',
    'squares = [',
    '    x * x',
    '    for x in nums',
    '    if x % 2 == 1',
    ']',
    'print(squares)',
]


def _comprehension_trace(start=(3, 8, 5, 12, 7)):
    """Пошаговая трасса списочного выражения с фильтром.

    Внутренний список-накопитель показываем под именем «результат»: у него
    в программе имени нет, а имя squares появляется только на закрывающей
    скобке, когда выражение досчитано. Тогда же из состояния исчезает x —
    наружу переменная выражения не выходит.
    """
    steps = []
    nums = list(start)
    x = None
    acc = None
    squares = None

    def state():
        s = {'nums': list(nums)}
        if x is not None:
            s['x'] = x
        if acc is not None:
            s['результат'] = list(acc)
        if squares is not None:
            s['squares'] = list(squares)
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Пять чисел — источник. Из них соберётся новый список, а сам '
             'nums не изменится.',
    ))

    acc = []
    steps.append(dict(
        line=2, vars=state(),
        note='Открывающая скобка: здесь начинается выражение, и внутри него '
             'уже готов пустой список-накопитель. Имени у него в программе '
             'нет — в трассе он показан как «результат».',
    ))

    for pos, value in enumerate(nums):
        x = value
        note = 'Берём очередной элемент: x = {}.'.format(value)
        if pos == 0:
            note += (' Обратите внимание, откуда пошло выполнение: не с верхней '
                     'строки выражения, а со строки for — сначала надо понять, '
                     'что и откуда мы берём.')
        steps.append(dict(line=4, vars=state(), note=note))

        odd = (value % 2 == 1)
        note = 'Остаток от деления {} на 2 равен {}, число {}.'.format(
            value, value % 2, 'нечётное' if odd else 'чётное')
        if not odd:
            note += (' Условие ложно — строка «x * x» не выполняется вообще, '
                     'в список ничего не кладётся.')
        steps.append(dict(line=5, vars=state(), check=odd, note=note))

        if odd:
            acc.append(value * value)
            note = 'Условие истинно, и только теперь считается x * x = {}. ' \
                   'Результат уходит в конец списка.'.format(value * value)
            if pos == 0:
                note += (' Эта строка написана первой, а выполняется третьей — '
                         'после for и после if.')
            steps.append(dict(line=3, vars=state(), note=note))

    x = None
    steps.append(dict(
        line=4, vars=state(),
        note='Элементы кончились — брать больше нечего.',
    ))

    squares = list(acc)
    acc = None
    steps.append(dict(
        line=6, vars=state(),
        note='Закрывающая скобка: выражение досчитано, и готовый список '
             'получил имя squares. А переменная x наружу не вышла — она жила '
             'только внутри выражения.',
    ))
    steps.append(dict(
        line=7, vars=state(), out=str(squares),
        note='Из пяти чисел фильтр прошли три нечётных, и в списке лежат их '
             'квадраты. Исходный nums не изменился ни на одном шаге.',
    ))
    return steps


# Код, который трассирует loop-trace в уроке 9.4: sorted() и a.sort() рядом.
# Смысл трассы — показать две разницы сразу: что происходит с самим списком
# и что каждая запись возвращает. Последняя строка печатает результат sort()
# напрямую — вывести None можно только так: в колонке переменных прочерк
# означает «переменной ещё нет», и для None он читался бы неверно.
SORT_CODE = [
    'a = [3, 1, 2]',
    'b = sorted(a)',
    'print(a)',
    'print(b)',
    'a.sort()',
    'print(a)',
    'print(a.sort())',
]


def _sort_trace(start=(3, 1, 2)):
    """Пошаговая трасса пары sorted() / list.sort().

    Виджет ничего не вычисляет сам — повторяем обе операции обычным Python
    и складываем ПОЛНОЕ состояние на каждом шаге.
    """
    steps = []
    a = None
    b = None

    def state():
        s = {}
        if a is not None:
            s['a'] = list(a)
        if b is not None:
            s['b'] = list(b)
        return s

    a = list(start)
    steps.append(dict(
        line=1, vars=state(),
        note='Три числа не по порядку. Дальше мы упорядочим их двумя разными '
             'способами и посмотрим, чем эти способы отличаются.',
    ))

    b = sorted(a)
    steps.append(dict(
        line=2, vars=state(),
        note='sorted() построила НОВЫЙ список и вернула его — он достался '
             'имени b. Посмотрите на строку a: она не изменилась ни на один '
             'элемент.',
    ))
    steps.append(dict(
        line=3, vars=state(), out=str(a),
        note='Исходный список в прежнем беспорядке.',
    ))
    steps.append(dict(
        line=4, vars=state(), out=str(b),
        note='А в b лежат те же числа, выстроенные по возрастанию.',
    ))

    a.sort()
    steps.append(dict(
        line=5, vars=state(),
        note='Метод sort() работает наоборот: он ничего не создаёт и ничего '
             'не отдаёт — он перестраивает сам список a, на месте. Именно '
             'поэтому слева от него нет никакого присваивания.',
    ))
    steps.append(dict(
        line=6, vars=state(), out=str(a),
        note='Теперь по порядку выстроен и сам a.',
    ))

    a.sort()
    steps.append(dict(
        line=7, vars=state(), out='None',
        note='Вот что sort() возвращает на самом деле — None. Список уже '
             'упорядочен, поэтому переставлять нечего, зато видно значение. '
             'Запись b = a.sort() положила бы в b именно его: та самая '
             'ловушка из урока 9.2.',
    ))
    return steps


# Код, который трассирует loop-trace в уроке 9.5: поиск первого дня с
# плюсовой температурой. Смысл трассы — показать, что break обрывает поиск
# на середине списка: хвост в трассу просто не попадает.
SEARCH_CODE = [
    'temps = [-3, 0, 5, -8, 2, 7, -1]',
    'pos = -1',
    'for i in range(len(temps)):',
    '    if temps[i] > 0:',
    '        pos = i',
    '        break',
    'print(pos)',
]


def _search_trace(start=(-3, 0, 5, -8, 2, 7, -1)):
    """Пошаговая трасса линейного поиска первого элемента по критерию.

    Виджет ничего не вычисляет сам — повторяем алгоритм обычным циклом и
    складываем ПОЛНОЕ состояние на каждом шаге. temps[i] показываем отдельной
    строкой состояния: именно это значение проверяет условие.
    """
    steps = []
    temps = list(start)
    pos = None
    i = None

    def state():
        s = {'temps': list(temps)}
        if pos is not None:
            s['pos'] = pos
        if i is not None:
            s['i'] = i
            s['temps[i]'] = temps[i]
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Журнал из прошлого урока. Ищем первый день, когда температура '
             'поднялась выше нуля, — и нужен нам номер дня, а не сама '
             'температура.',
    ))

    pos = -1
    steps.append(dict(
        line=2, vars=state(),
        note='Заранее считаем, что не нашли. −1 выбран не случайно: настоящим '
             'индексом это число быть не может, значит его ни с чем не '
             'перепутать.',
    ))

    found = False
    for idx in range(len(temps)):
        i = idx
        note = 'Берём очередной индекс: i = {}. По этому номеру лежит ' \
               '{}.'.format(idx, temps[idx])
        if idx == 0:
            note += (' Перебираем именно индексы, а не значения: значение '
                     'своего номера не помнит, а номер нам и нужен.')
        steps.append(dict(line=3, vars=state(), note=note))

        ok = temps[idx] > 0
        note = 'Проверяем: {} {} нуля.'.format(
            temps[idx], 'больше' if ok else 'не больше')
        if temps[idx] == 0:
            note += ' Нуль не больше нуля — условие ложно, день не подходит.'
        steps.append(dict(line=4, vars=state(), check=ok, note=note))

        if ok:
            pos = idx
            steps.append(dict(
                line=5, vars=state(),
                note='Нашли: запоминаем номер, а не значение. В pos лежит {}, '
                     'то есть {}-й день по счёту.'.format(idx, idx + 1),
            ))
            steps.append(dict(
                line=6, vars=state(),
                note='break обрывает цикл прямо здесь. В списке осталось {} '
                     'непросмотренных элемента — до них поиск уже не '
                     'дойдёт.'.format(len(temps) - idx - 1),
            ))
            found = True
            break

    if not found:  # на этих данных не случается, но алгоритм честный
        i = None
        steps.append(dict(
            line=3, vars=state(),
            note='Индексы кончились, break так и не сработал — pos остался −1.',
        ))

    steps.append(dict(
        line=7, vars=state(), out=str(pos),
        note='Ответ — номер, по которому лежит первый подходящий элемент. '
             'Само значение всегда рядом: temps[pos].',
    ))
    return steps


