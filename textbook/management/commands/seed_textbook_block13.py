WAYS_CODE = [
    "order = ['А', 'Б', 'В', 'Г', 'Д', 'Е']",
    "ways = {'А': 1, 'Б': 0, 'В': 0, 'Г': 0, 'Д': 0, 'Е': 0}",
    'for v in order:',
    '    for u in scheme[v]:',
    '        ways[u] += ways[v]',
    '',
    "print(ways['Е'])",
]


def _ways_trace(scheme=None, order=None):
    """Трасса подсчёта маршрутов: число до вершины растекается по стрелкам.

    Виджет loop-trace ничего не считает сам — повторяем алгоритм обычным
    циклом и складываем полное состояние на каждом шаге. Словарь виджет
    собрать не умеет, поэтому кладём его готовой строкой через _raw().
    """
    scheme = scheme or PARK_SCHEME
    order = order or PARK_ORDER
    steps = []
    ways = {v: 0 for v in order}
    ways[order[0]] = 1
    v = None
    u = None

    def state():
        s = {'order': list(order), 'ways': _raw(ways)}
        if v is not None:
            s['v'] = v
        if u is not None:
            s['u'] = u
        return s

    steps.append(dict(
        line=1, vars={'order': list(order)},
        note='Порядок, в котором будем считать: каждая стрелка ведёт от '
             'вершины к той, что стоит в этом списке правее.',
    ))
    steps.append(dict(
        line=2, vars=state(),
        note='До входа А маршрут ровно один — «никуда не ходили». Про '
             'остальные точки мы пока ничего не знаем, поэтому нули.',
    ))

    for vertex in order:
        v = vertex
        u = None
        if v == order[0]:
            note = ('Берём вход {}: до него маршрут один, и прибавлять к нему '
                    'нечего — стрелок, ведущих в {}, нет.'.format(v, v))
        else:
            note = ('Берём {}: до неё маршрутов {}. Число окончательное — все '
                    'точки, откуда в {} ведут стрелки, уже '
                    'посчитаны.'.format(v, ways[v], v))
        steps.append(dict(line=3, vars=state(), note=note))
        if not scheme[v]:
            steps.append(dict(
                line=4, vars=state(),
                note='Из {} стрелок не выходит — прибавлять некуда, это конец '
                     'маршрута.'.format(v),
            ))
            continue
        for nb in scheme[v]:
            u = nb
            steps.append(dict(
                line=4, vars=state(),
                note='Есть стрелка {} → {}.'.format(v, u),
            ))
            was = ways[u]
            ways[u] += ways[v]
            steps.append(dict(
                line=5, vars=state(),
                note='Каждый маршрут до {} продолжается в {}: было {}, '
                     'прибавили {}, стало {}.'.format(v, u, was, ways[v],
                                                      ways[u]),
            ))
        u = None

    v = None
    u = None
    steps.append(dict(
        line=7, vars=state(), out=str(ways[order[-1]]),
        note='Готово. До {} ведёт {} маршрута — ровно столько, сколько мы '
             'выписали руками, и ни одного из них программа не '
             'выписывала.'.format(order[-1], ways[order[-1]]),
    ))
    return steps


