def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _net(ip, mask):
    """Сеть по адресу и маске – тот же вызов, что стоит в листинге статьи.

    `strict=False` обязателен: по умолчанию `ip_network` ждёт адрес сети,
    а в условии дан адрес узла.
    """
    return ip_network(f'{ip}/{mask}', strict=False)


def _sum_of_octets(addr):
    """Сумма числовых значений октетов – форма ответа у половины задач."""
    return sum(int(x) for x in str(addr).split('.'))


def _without_dots(addr):
    """Адрес без разделителей – форма ответа у наибольшего адреса."""
    return str(addr).replace('.', '')


def _count_odd(net, hosts=False):
    """Сколько адресов сети имеют нечётное число единиц в двоичной записи.

    `hosts=True` повторяет ошибку из банка: `net.hosts()` выбрасывает адрес
    сети и широковещательный, и счёт выходит на единицу меньше. Разбор учит
    перебирать `net`, поэтому оба числа считаются здесь и оба проверяются.
    """
    pool = net.hosts() if hosts else net
    return sum(1 for ip in pool if bin(int(ip)).count('1') % 2 != 0)


def _last_line(source):
    """Последняя строка вывода программы – иначе «ответ» в комментарии не факт.

    Листинг исполняется целиком, а не пересказывается: статья показывает код,
    и он обязан печатать то, что обещает соседний абзац.
    """
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        exec(source, {})
    return out.getvalue().strip().splitlines()[-1]


