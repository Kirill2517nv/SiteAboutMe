# Листинг про отдельный адрес: выражения печатаются, а комментарий с
# результатом дописывается исполнением (`_listing`).
ADDRESS_SETUP = "addr = ip_address('192.168.159.86')"
ADDRESS_EXPRS = [
    'addr',
    'int(addr)',
    'bin(int(addr))',
    'addr + 1',
    "str(addr).split('.')",
]


def _namespace():
    """Имена, в которых вычисляются записи экскурсии: сеть демоверсии и модуль."""
    from ipaddress import ip_address
    return {'net': _net(IP, MASK), 'ip_address': ip_address, 'ip_network': ip_network}


def _rows(pairs):
    """Строки Markdown-таблицы «запись | что это | значение для сети демоверсии»."""
    ns = _namespace()
    return ''.join(
        f'| `{expr}` | {what} | `{eval(expr, ns)}` |\n'
        for expr, what in pairs
    )


def _listing():
    """Листинг про адрес: `print(выражение)` и настоящий результат в комментарии."""
    ns = _namespace()
    exec(ADDRESS_SETUP, ns)
    prints = [f'print({expr})' for expr in ADDRESS_EXPRS]
    width = max(len(p) for p in prints) + 2
    lines = ['from ipaddress import ip_address', '', ADDRESS_SETUP]
    lines += [
        p.ljust(width) + f'# {eval(expr, ns)}'
        for p, expr in zip(prints, ADDRESS_EXPRS)
    ]
    return '\n'.join(lines) + '\n'


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ и с задачами банка.

    Проверяется всё, на что статья опирается прямо: сумма октетов адреса сети,
    двоичные записи третьего октета, длина префикса, широковещательный адрес,
    ValueError без `strict=False` и ответы трёх задач банка. Поменяется
    условие – упадёт команда, а не останется абзац, объясняющий неверную
    двоичную запись.
    """
    net = _net(IP, MASK)

    assert _sum_of_octets(net.network_address) == ANSWER, (
        f'разбор даёт {_sum_of_octets(net.network_address)}, у ФИПИ {ANSWER}'
    )
    assert HOST_OCTET & MASK_OCTET == NET_OCTET == 156, (
        f'третий октет адреса сети получился {NET_OCTET} – блок «Как '
        'рассуждать» называет другое число'
    )
    assert format(HOST_OCTET, '08b') == '10011111', (
        f'{HOST_OCTET} в двоичной записи – {format(HOST_OCTET, "08b")}, '
        'а разбор показывает другую строку битов'
    )
    assert format(MASK_OCTET, '08b') == '11111100', (
        f'{MASK_OCTET} в двоичной записи – {format(MASK_OCTET, "08b")}, '
        'а разбор показывает другую строку битов'
    )
    assert format(NET_OCTET, '08b') == '10011100', (
        f'{NET_OCTET} в двоичной записи – {format(NET_OCTET, "08b")}, '
        'а разбор показывает другую строку битов'
    )
    assert str(net.network_address) == f'192.168.{NET_OCTET}.0', (
        f'адрес сети стал {net.network_address} – шаг 4 «Как рассуждать» '
        'называет другой адрес'
    )
    assert net.prefixlen == 22, (
        f'в маске {net.prefixlen} единиц – абзац про $2^k$ считает адреса '
        'не по той длине префикса'
    )
    assert net.num_addresses == 1024, (
        f'адресов в сети {net.num_addresses} – текст называет другое число'
    )
    assert str(net.broadcast_address) == '192.168.159.255', (
        f'широковещательный адрес стал {net.broadcast_address} – текст '
        'называет другой'
    )

    try:
        ip_network(f'{IP}/{MASK}')
    except ValueError as exc:
        assert 'has host bits set' in str(exc), (
            f'сообщение об ошибке теперь «{exc}» – блок «Решение программой» '
            'и пункт 1 «Типичных ошибок» цитируют его дословно'
        )
    else:
        raise AssertionError(
            f'ip_network({IP}/{MASK}) не упал без strict=False – флаг в задаче '
            'больше не нужен, а статья объясняет его целым абзацем'
        )

    max_host = _net(*MAX_HOST)[-2]
    assert _without_dots(max_host) == MAX_HOST_ANSWER, (
        f'наибольший адрес компьютера записан как {_without_dots(max_host)}, '
        f'в банке {MAX_HOST_ANSWER}'
    )
    count = _net(*COUNT)
    assert _count_odd(count) == COUNT_ANSWER, (
        f'перебор net даёт {_count_odd(count)} адресов, в банке {COUNT_ANSWER}'
    )
    assert _count_odd(count, hosts=True) == COUNT_HOSTS_ANSWER, (
        f'перебор net.hosts() даёт {_count_odd(count, hosts=True)}, а разбор '
        f'обещает {COUNT_HOSTS_ANSWER} – пункт 2 «Типичных ошибок» называет '
        'другую разницу'
    )

    # Подписи экскурсии утверждают то, что не видно из самих значений.
    assert net[0] == net.network_address and net[-1] == net.broadcast_address, (
        'net[0] и net[-1] больше не адрес сети и широковещательный – '
        'таблица «Сеть ведёт себя как список» врёт'
    )
    assert len(list(net.hosts())) == net.num_addresses - 2, (
        'hosts() выбрасывает не ровно два служебных адреса'
    )
    assert str(net.hostmask) == '0.0.3.255', f'обратная маска стала {net.hostmask}'

    assert _last_line(SOLUTION) == str(ANSWER), (
        f'листинг печатает {_last_line(SOLUTION)} – блок 6 обещает {ANSWER}'
    )
    assert f'{IP}/{MASK}' in SOLUTION, (
        'листинг решает не ту задачу – условие демоверсии изменилось'
    )
    assert f'# {ANSWER}' in SOLUTION, (
        f'комментарий в листинге больше не обещает {ANSWER}'
    )


