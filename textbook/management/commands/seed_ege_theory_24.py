# строку целиком.
#
# GROUP_PATTERN – это PATTERN, из которого вычеркнули все `?:`, то есть ровно
# то, что ученик напишет, если спишет шаблон «своими скобками». Подсветка у
# него та же, а findall начинает отдавать кортежи групп, и ответ молча
# становится 3. Объяснение `?:` в блоке «Решение 1» держится на этой кнопке:
# без неё пришлось бы верить на слово.
NAIVE_PATTERN = r'[0-9]+(?:[-*][0-9]+)*'
ALL_PATTERN = r'[0-9*-]+'
GROUP_PATTERN = PATTERN.replace('(?:', '(')

