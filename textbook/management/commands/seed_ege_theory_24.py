def _best_re(s, pattern=PATTERN):
    """Длина самого длинного совпадения – способом из блока 4.

    Шаблон – параметр, потому что тем же счётом меряются неверные заготовки
    виджета: сравнение «10 против 9» в тексте должно считаться, а не
    вписываться руками. Передавать сюда GROUP_PATTERN нельзя – у него скобки
    запоминающие, и findall вернёт кортежи вместо кусков; для него длину как
    раз и считают отдельно, это и есть довод статьи в пользу `?:`.
    """
    return max((len(x) for x in re.findall(pattern, s)), default=0)


def _best_scan(s):
    """То же самое двумя указателями – способом из «Решения 2».

    Записана так же, как в SCAN_LINES: расхождение между тем, что статья
    показывает, и тем, что она проверяет, – ровно то, что ловит _check().
    """
    best = 0
    left = 0
    num_start = 0
    for right, c in enumerate(s):
        if c.isdigit():
            if right > num_start and s[num_start] == '0':
                left = num_start = right
            best = max(best, right - left + 1)
        else:
            if not (right > left and s[right - 1].isdigit()):
                left = right + 1
            num_start = right + 1
    return best


def _scan_trace(text=TRACE_TEXT):
    """Пошаговая трасса второго решения для виджета loop-trace.

    Виджет сам ничего не считает – повторяем алгоритм и складываем полное
    состояние на каждом шаге. Номер строки – индекс в SCAN_LINES плюс один,
    поэтому трасса и листинг не могут показать разные строки.

    Шаг здесь – одна выполненная строка, как в отладчике: заголовок цикла,
    каждая проверка условия со своим ответом True/False и каждое присваивание.
    Сокращённая трасса (по шагу на символ) показывала результат, но не
    показывала, **по какой проверке** алгоритм решил, что кусок рвётся, –
    а это и есть всё содержание второго решения.

    Состояние в таблице – то, что стало **после** выполнения подсвеченной
    строки. Колонка `s[left:right+1]` – не выдуманная переменная, а
    выражение: кусок между указателями, ради которого всё затевалось.
    """
    steps = []
    best = 0
    left = 0
    num_start = 0
    right = None
    c = None

    def snap(line, note):
        """Снимок после выполнения строки line.

        Номер строки – по SCAN_LINES, а в листинге виджета сверху добавлена
        сама строка `s`, поэтому все шаги, кроме нулевого, сдвинуты.
        """
        vars_ = {'s': text, 'best': best, 'left': left, 'num_start': num_start}
        if right is not None:
            vars_['right'] = right
            vars_['c'] = c
            vars_['s[left:right+1]'] = text[left:right + 1]
        steps.append(dict(line=line + TRACE_SHIFT, vars=vars_, note=note))

    steps.append(dict(
        line=1,
        vars={'s': text},
        note=f'Строка, которую разбираем. В решении она читается из файла и '
             f'длиной в десять миллионов символов, здесь – короткая, '
             f'{len(text)} символов, чтобы уместиться в трассу.',
    ))
    snap(1, 'Заводим рекорд: пока не найдено ни одного корректного куска.')
    snap(2, 'Левый указатель – в начале строки. Он помнит, где начинается '
            'кусок, который прямо сейчас остаётся корректным.')
    snap(3, 'И метка начала числа, которое читается прямо сейчас. Без неё '
            'не отличить `0` в конце числа от одиночного нуля.')

    for right, c in enumerate(text):
        snap(5, f'Правый указатель шагнул на {right}, под ним символ `{c}`.')

        if c.isdigit():
            snap(6, f'`{c}` – цифра, идём в первую ветку.')

            lead = right > num_start and text[num_start] == '0'
            checked = (
                f'right > num_start – это {right} > {num_start}, '
                + ('да' if right > num_start else 'нет')
                + f'; s[num_start] = `{text[num_start]}`, '
                + ('это ноль' if text[num_start] == '0' else 'это не ноль')
            )
            if lead:
                snap(7, f'Проверка: {checked}. Оба условия верны – значит, '
                        'число начиналось с нуля, а за ним снова цифра. '
                        'Ведущий ноль запрещён.')
                left = num_start = right
                snap(8, f'Кусок рвётся: левый указатель прыгает на {right}, '
                        'и оба указателя снова стоят на одном символе.')
            else:
                snap(7, f'Проверка: {checked}. Ведущего нуля нет – левый '
                        'указатель остаётся на месте.')

            length = right - left + 1
            grew = length > best
            best = max(best, length)
            snap(9, (
                f'Кусок `{text[left:right + 1]}` – это {length} символ'
                + plural(length, ',а,ов')
                + f' ({right} - {left} + 1). '
                + ('Больше прежнего рекорда: best стал '
                   f'{best}.' if grew else
                   f'Рекорд не побит, best остался {best}.')
            ))
        else:
            snap(6, f'`{c}` – не цифра, значит знак: идём в `else`.')

            after_number = right > left and text[right - 1].isdigit()
            checked = (
                f'right > left – это {right} > {left}, '
                + ('да' if right > left else 'нет')
                + (f'; перед знаком стоит `{text[right - 1]}`, '
                   + ('это цифра' if text[right - 1].isdigit() else
                      'это не цифра')
                   if right > 0 else '; перед знаком ничего нет')
            )
            if after_number:
                snap(11, f'Проверка: {checked}. Знак стоит после числа – '
                         'всё в порядке, кусок продолжается. Длину здесь не '
                         'меряем: на знаке выражение кончиться не может.')
            else:
                snap(11, f'Проверка: {checked}. Знак не на месте – перед ним '
                         'нет законченного числа.')
                left = right + 1
                snap(12, f'Левый указатель уходит за знак, на {right + 1}: '
                         'кусок будет собираться заново.')

            num_start = right + 1
            snap(13, f'Следующее число начнётся с позиции {right + 1}.')

    return steps


def _longest(s, pattern=PATTERN):
    """Сам самый длинный фрагмент – его статья показывает в разборе примера."""
    return max((m.group() for m in re.finditer(pattern, s)), key=len)


def _check():
    """Числа разбора обязаны совпасть с тем, что дают оба способа.

    Ответ на всём файле (154) здесь не проверяется: файла демоверсии на
    сервере может не быть, а 10 млн символов ради seed-команды читать незачем.
    Проверяется то, что статья разбирает вслух, – и то, что оба способа
    согласны между собой.
    """
    for sample, expected in SAMPLES.items():
        assert _best_re(sample) == expected, (
            f'шаблон на строке {sample!r} даёт {_best_re(sample)}, '
            f'а статья обещает {expected}'
        )
        assert _best_scan(sample) == expected, (
            f'проход указателями на строке {sample!r} даёт {_best_scan(sample)}, '
            f'а статья обещает {expected}'
        )
    assert _longest(HEAD) == '809*9*6*7', (
        f'в разбираемом фрагменте самый длинный кусок – {_longest(HEAD)!r}, '
        'а блок с виджетом называет другой'
    )
    assert _best_re('0809') == 3, (
        'строка 0809 перестала разваливаться на 0 и 809 – значит, шаблон '
        'больше не отсекает ведущий ноль, на котором держится весь разбор'
    )
    # Заготовки виджета: каждая обязана показывать ровно ту ошибку, о которой
    # о ней написано, иначе подписи под кнопками врут.
    assert _best_re(HEAD, NAIVE_PATTERN) > _best_re(HEAD), (
        f'шаблон без учёта ведущих нулей даёт {_best_re(HEAD, NAIVE_PATTERN)} '
        f'против {_best_re(HEAD)} у правильного – заготовка «без ведущих '
        'нулей» перестала показывать завышенный ответ'
    )
    assert _longest(HEAD, NAIVE_PATTERN) == '7-99*00-00', (
        f'заготовка «без ведущих нулей» находит {_longest(HEAD, NAIVE_PATTERN)!r}, '
        'а текст виджет-блока называет другой кусок'
    )
    assert re.findall(ALL_PATTERN, HEAD) == [HEAD], (
        'заготовка «всё подряд» перестала хватать весь фрагмент целиком – '
        'довод «шаблон обязан описывать выражение, а не алфавит» пропал'
    )
