# Строка, на которой виджет трассирует алгоритм. Не кусок файла, а собранная
# вручную: в настоящем файле нужные случаи разбросаны на сотни символов, а
# здесь каждый встречается ровно по разу и строка кончается раньше, чем
# ученик устанет жать «шаг».
#
#   8-0   растёт нормальный кусок, знак между числами
#   09    ведущий ноль: кусок рвётся посреди строки
#   --    два знака подряд: левый указатель уходит за оба
#   7*66  новый рекорд, и он берётся на последнем символе – видно, зачем
#         дочитывать строку до конца, а не останавливаться на первом куске
TRACE_TEXT = '8-09--7*66'

# Листинг для виджета – тот же алгоритм, но с первой строкой, которая
# отвечает на вопрос «откуда взялась `s` и чему она равна». В решении её
