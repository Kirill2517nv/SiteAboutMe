def _schedule():
    """Начала и концы процессов примера по правилу, которому учит статья.

    Зависимости разворачиваются рекурсией, а не проходом сверху вниз: строки
    в файле не отсортированы по зависимостям, и статья про это прямо пишет.
    Отбор пустой – у независимого процесса в списке стоит `0`, такого ID
    в таблице нет, – даёт максимум 0, то есть начало 1: отдельной проверки
    на независимость не нужно, как и в формуле Calc.
    """
    table = {pid: (time, deps) for pid, time, deps in EXAMPLE}

    def end_of(pid, seen=()):
        assert pid not in seen, f'цикл в зависимостях процесса {pid}'
        time, deps = table[pid]
        start = max((end_of(dep, seen + (pid,))[1] for dep in deps), default=0) + 1
        return start, start + time - 1

    return {pid: end_of(pid) for pid in table}


def _deps_text(deps, sep, empty):
    """Список зависимостей: `2; 4` в таблице условия, `2, 4` в таблице разбора.

    Пустой список подписывается по-разному: в файле у независимого процесса
    стоит `0`, а в разборе он читается прочерком – ноль там выглядел бы как
    ID процесса, которого в таблице нет.
    """
    return sep.join(str(dep) for dep in deps) if deps else empty


def _data_table():
    """Таблица типового примера ровно в том виде, в каком она в условии.

    Собирается из EXAMPLE, а не набивается руками: те же шесть процессов
    посчитаны в `_check()`, и разойтись таблица условия с проверкой не может.
    """
    lines = [
        '| ID процесса B | Время выполнения процесса B (мс) | '
        'ID процесса(-ов) A |',
        '| --- | --- | --- |',
    ]
    lines += [
        f'| {pid} | {time} | {_deps_text(deps, "; ", "0")} |'
        for pid, time, deps in EXAMPLE
    ]
    return '\n'.join(lines)


def _example_table():
    """Пример с посчитанными началами и концами – из `_schedule()`.

    Это проверка правила на числах самого условия: процесс 3 получает начало 8
    и конец 9, ровно как написано в условии ФИПИ. Таблица собирается из тех же
    значений, что проверяет `_check()`, поэтому статья и проверка не разойдутся.
    """
    schedule = _schedule()
    lines = [
        '| ID | Время | Зависит от | Начало | Конец |',
        '| --- | --- | --- | --- | --- |',
    ]
    lines += [
        f'| {pid} | {time} | {_deps_text(deps, ", ", "–")} | '
        f'{schedule[pid][0]} | {schedule[pid][1]} |'
        for pid, time, deps in EXAMPLE
    ]
    return '\n'.join(lines)


