def _calc_steps():
    """Слайды для screen-steps: Markdown рендерится здесь тем же markdownify,
    что и текст статьи, поэтому виджету не нужен свой разборщик разметки.

    Шаг отдаёт либо `image`, либо `video` с `poster` – как в разборе задания 3:
    виджет показывает видео, если ключ есть, и картинка при нём была бы мёртвым
    весом. Опечатка в ключе выдала бы шаг вообще без кадра, а это заметно только
    глазами на странице, – отсюда проверка в конце.
    """
    steps = []
    for s in CALC_STEPS:
        step = dict(title=s['title'], html=str(markdownify(s['text'])), alt=s['alt'])
        if s.get('video'):
            step['video'] = settings.MEDIA_URL + SHOTS_DIR + s['video']
            step['poster'] = settings.MEDIA_URL + SHOTS_DIR + s['poster']
            if s.get('cues'):
                step['cues'] = s['cues']
        else:
            step['image'] = settings.MEDIA_URL + SHOTS_DIR + s['file']
        steps.append(step)
    assert all(('video' in s) != ('image' in s) for s in steps), 'шаг без кадра'
    return steps


def _check():
    """Числа статьи обязаны сходиться до того, как статья записана.

    Типовой пример из условия считается здесь тем же правилом, которому учит
    разбор, и на тех же константах, из которых собраны таблицы обоих блоков.
    Проверяется то, на что текст опирается прямо: начало и конец процесса 3 –
    они написаны в самом условии ФИПИ, – и ответ демоверсии.
    """
    schedule = _schedule()
    assert schedule[3] == (8, 9), f'процесс 3: {schedule[3]}, в условии 8 и 9'
    assert schedule[1] == (1, 3), f'независимый процесс 1: {schedule[1]}'
    assert ANSWER == 8, 'ответ ФИПИ 8'
    # Ответ снят с таблицы начал и концов, а не посчитан отдельно: в блоке
    # «Решение. Шаг 2» он объясняется именно так. Считаем ровно ту же формулу
    # по-питоновски – по числам из статьи.
    on_seventh = sum(1 for _, start, end in _answer_rows() if start <= 7 <= end)
    assert on_seventh == ANSWER, f'на 7-й мс {on_seventh} процессов, а не {ANSWER}'


