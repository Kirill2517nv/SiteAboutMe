def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _fmt(weight):
    """Число так, как его пишет статья: 12.0 – это 12, а 5.5 – это 5.5."""
    return f'{weight:g}'


def _spaced(number):
    """Большое число с пробелами между разрядами, как принято в текстах."""
    return f'{number:,}'.replace(',', ' ')


def _run(code):
    """Что код статьи печатает на примере из условия – одной строкой."""
    return ' '.join(run_solution(code, DATA_FILE, EXAMPLE_TEXT))


def _table(edges, start=START, passes=None):
    """Таблица best после проходов – та же динамика, что в блоке `Решение`.

    Возвращает таблицу и число проходов. `passes` обрывает счёт раньше –
    так считается ошибка «хватит одного прохода».
    """
    best, done = {start: 0}, 0
    while passes is None or done < passes:
        done += 1
        new = {start: 0}
        for a, b, w in edges:
            if a in best:
                new[b] = min(new.get(b, float('inf')), best[a] + w)
        if new == best:
            break
        best = new
    return best, done


def _weight(edges, a, b):
    """Вес ребра a → b – чтобы слагаемые в тексте брались из тех же рёбер."""
    return next(w for x, y, w in edges if x == a and y == b)


def _route(edges, *way):
    """Путь через перечисленные вершины: слагаемые строкой и их сумма."""
    legs = [_weight(edges, a, b) for a, b in zip(way, way[1:])]
    return ' + '.join(_fmt(leg) for leg in legs), sum(legs)


def _greedy(edges, start=START):
    """Жадный спуск: из каждой вершины идём по самому лёгкому её ребру.

    Это не рабочий алгоритм, а ошибка из блока «Типичные ошибки».
    """
    out = lambda v: [(b, w) for a, b, w in edges if a == v]  # noqa: E731
    vertex, way, total = start, [start], 0.0
    while vertex != TARGET and out(vertex):
        vertex, weight = min(out(vertex), key=lambda edge: edge[1])
        total += weight
        way.append(vertex)
    return way, total


