def _replace_blocks(article, blocks):
    article.blocks.all().delete()
    for b in blocks:
        ArticleBlock.objects.create(article=article, **b)


def _self_check(slug, title, description, questions):
    """Создаёт (или переиспользует) тест самопроверки с вопросами."""
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check:
        quiz.is_self_check = True
        quiz.save(update_fields=['is_self_check'])

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                points=1,
            )
            for choice_text, is_correct in q.get('choices', []):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
    return quiz


# Код, который трассирует виджет loop-trace в уроке 4.2. Держим рядом с
# генератором трассы: номера строк в шагах ссылаются именно на этот список.
COUNTDOWN_CODE = [
    'sec = 5',
    'while sec > 0:',
    '    print(sec)',
    '    sec -= 1',
    "print('Пуск!')",
]


def _countdown_trace(start=5):
    """Пошаговая трасса обратного отсчёта для виджета loop-trace.

    Виджет ничего не вычисляет — трассу готовит Python здесь, буквально
    повторяя разбираемый алгоритм и записывая каждый шаг. `vars` хранит
    полное состояние после строки, поэтому шаг назад и ползунок работают
    без пересчёта. Для нового цикла в другом уроке пишется такая же
    функция — сам виджет менять не нужно.
    """
    steps = []
    sec = start
    steps.append(dict(line=1, vars={'sec': sec}, note='Задаём начальное значение.'))
    while True:
        cond = sec > 0
        steps.append(dict(
            line=2, vars={'sec': sec}, check=cond,
            note='Проверяем условие: {} > 0.'.format(sec),
        ))
        if not cond:
            break
        steps.append(dict(
            line=3, vars={'sec': sec}, out=str(sec),
            note='Печатаем текущее значение.',
        ))
        sec -= 1
        steps.append(dict(
            line=4, vars={'sec': sec},
            note='Уменьшаем sec на 1 — шаг к выходу из цикла.',
        ))
    steps.append(dict(
        line=5, vars={'sec': sec}, out='Пуск!',
        note='Строка без отступа — не тело цикла, выполняется один раз.',
    ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.3.
DIGITS_CODE = [
    'n = 4726',
    'while n > 0:',
    '    digit = n % 10',
    '    print(digit)',
    '    n = n // 10',
]


def _digits_trace(number=4726):
    """Пошаговая трасса разбора числа на цифры для виджета loop-trace.

    Как и в 4.2, трассу считает Python здесь: тот же алгоритм, что в
    DIGITS_CODE, только каждый шаг записывается в список. Переменной
    digit в первых шагах ещё нет — просто не кладём ключ в vars,
    виджет покажет прочерк.
    """
    steps = []
    n = number
    digit = None

    def state():
        s = {'n': n}
        if digit is not None:
            s['digit'] = digit
        return s

    steps.append(dict(line=1, vars=state(), note='Число, которое будем разбирать.'))
    while True:
        cond = n > 0
        steps.append(dict(
            line=2, vars=state(), check=cond,
            note='Осталось ли что разбирать: {} > 0.'.format(n),
        ))
        if not cond:
            break
        digit = n % 10
        steps.append(dict(
            line=3, vars=state(),
            note='Остаток от деления на 10 — последняя цифра числа.',
        ))
        steps.append(dict(
            line=4, vars=state(), out=str(digit),
            note='Печатаем отделённую цифру.',
        ))
        n = n // 10
        steps.append(dict(
            line=5, vars=state(),
            note='Целая часть от деления на 10 — число без последней цифры.',
        ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.4.
ODD_SUM_CODE = [
    'total = 0',
    'for i in range(1, 10, 2):',
    '    total += i',
    'print(total)',
]


def _odd_sum_trace(start=1, stop=10, step=2):
    """Пошаговая трасса накопления суммы циклом for для виджета loop-trace.

    Отличие от трасс 4.2 и 4.3: у шагов на строке заголовка нет поля
    check — цикл for ничего не проверяет, он берёт очередной элемент
    диапазона. Это проговорено в note, чтобы разница с while была
    видна прямо в виджете.
    """
    steps = []
    total = 0
    i = None

    def state():
        s = {'total': total}
        if i is not None:
            s['i'] = i
        return s

    steps.append(dict(line=1, vars=state(), note='Накопитель создаём до цикла.'))
    for i in range(start, stop, step):
        steps.append(dict(
            line=2, vars=state(),
            note='Берём следующее значение из диапазона: i = {}. '
                 'Цикл for не проверяет условие — он просто берёт '
                 'очередной элемент.'.format(i),
        ))
        total += i
        steps.append(dict(
            line=3, vars=state(),
            note='Добавляем текущее i к накопителю.',
        ))
    steps.append(dict(
        line=2, vars=state(),
        note='Значения в диапазоне кончились — цикл завершён.',
    ))
    steps.append(dict(
        line=4, vars=state(), out=str(total),
        note='Строка без отступа — выполняется один раз после цикла.',
    ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.5.
FLOW_CODE = [
    'for i in range(1, 10):',
    '    if i % 2 == 0:',
    '        continue',
    '    print(i)',
    '    if i > 5:',
    '        break',
    "print('конец')",
]


def _flow_trace(stop=10, limit=5):
    """Пошаговая трасса цикла с continue и break для виджета loop-trace.

    Как и в предыдущих уроках, трассу считает Python здесь: тот же
    алгоритм, что в FLOW_CODE, только каждый шаг записывается в список.
    Шаги на строках 3 и 6 — это и есть моменты передачи управления,
    поэтому именно у них самые подробные note.
    """
    steps = []
    stopped = False
    for i in range(1, stop):
        steps.append(dict(
            line=1, vars={'i': i},
            note='Берём следующее значение из диапазона: i = {}.'.format(i),
        ))
        skip = i % 2 == 0
        steps.append(dict(
            line=2, vars={'i': i}, check=skip,
            note='Проверяем чётность: {} % 2 == 0.'.format(i),
        ))
        if skip:
            steps.append(dict(
                line=3, vars={'i': i},
                note='continue: прекращаем текущую итерацию и переходим к '
                     'следующей. print на этой итерации не выполнится.',
            ))
            continue
        steps.append(dict(
            line=4, vars={'i': i}, out=str(i),
            note='Значение нечётное — печатаем его.',
        ))
        leave = i > limit
        steps.append(dict(
            line=5, vars={'i': i}, check=leave,
            note='Проверяем условие выхода: {} > {}.'.format(i, limit),
        ))
        if leave:
            steps.append(dict(
                line=6, vars={'i': i},
                note='break: немедленно выходим из цикла. Оставшиеся значения '
                     'диапазона перебраны не будут.',
            ))
            stopped = True
            break
    if not stopped:
        steps.append(dict(
            line=1, vars={'i': i},
            note='Значения в диапазоне кончились — цикл завершён.',
        ))
    steps.append(dict(
        line=7, vars={'i': i}, out='конец',
        note='Строка без отступа выполняется в любом случае: break выходит '
             'из цикла, а не из программы.',
    ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.6 (проверка на простоту).
# Здесь только ядро цикла, без строки `if n < 2` из кода урока: она к перебору
# отношения не имеет, а номера строк в шагах сдвинула бы.
PRIME_CODE = [
    'n = 91',
    'for i in range(2, n):',
    '    if n % i == 0:',
    "        print('Составное, делится на', i)",
    '        break',
    'else:',
    "    print('Простое')",
]


def _prime_trace(number=91):
    """Пошаговая трасса проверки числа на простоту для виджета loop-trace.

    Как и в предыдущих уроках, трассу считает Python здесь: тот же
    алгоритм, что в PRIME_CODE. Главный шаг — break: именно в его note
    проговаривается, что блок else после прерывания не выполнится.
    """
    steps = []
    n = number
    steps.append(dict(line=1, vars={'n': n}, note='Число, которое проверяем.'))
    divisor = None
    for i in range(2, n):
        steps.append(dict(
            line=2, vars={'n': n, 'i': i},
            note='Берём следующего кандидата в делители: i = {}.'.format(i),
        ))
        found = n % i == 0
        steps.append(dict(
            line=3, vars={'n': n, 'i': i}, check=found,
            note='Проверяем делимость: {} % {} = {}.'.format(n, i, n % i),
        ))
        if found:
            steps.append(dict(
                line=4, vars={'n': n, 'i': i},
                out='Составное, делится на {}'.format(i),
                note='Делитель найден — число составное.',
            ))
            steps.append(dict(
                line=5, vars={'n': n, 'i': i},
                note='break: дальше искать нечего, выходим из цикла. Блок '
                     'else после цикла не выполнится — прерывание было.',
            ))
            divisor = i
            break
    if divisor is None:
        steps.append(dict(
            line=2, vars={'n': n, 'i': n - 1},
            note='Кандидаты кончились, ни один не подошёл — цикл завершён '
                 'естественно, без break.',
        ))
        steps.append(dict(
            line=7, vars={'n': n, 'i': n - 1}, out='Простое',
            note='Сработал блок else: прерывания не было, делителей нет.',
        ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.6 (алгоритм Евклида).
EUCLID_CODE = [
    'a = 1071',
    'b = 462',
    'while b != 0:',
    '    a, b = b, a % b',
    "print('НОД:', a)",
]


def _euclid_trace(first=1071, second=462):
    """Пошаговая трасса алгоритма Евклида для виджета loop-trace.

    Отличие от трасс 4.2–4.5: на каждой итерации меняются сразу две
    переменные — поэтому в note проговаривается, какая пара получилась
    и почему ответ у неё тот же, что у исходной.
    """
    steps = []
    a, b = first, second
    steps.append(dict(line=1, vars={'a': a}, note='Первое число.'))
    steps.append(dict(line=2, vars={'a': a, 'b': b}, note='Второе число.'))
    while True:
        cond = b != 0
        steps.append(dict(
            line=3, vars={'a': a, 'b': b}, check=cond,
            note='Есть ли ещё что сокращать: {} != 0.'.format(b),
        ))
        if not cond:
            break
        prev_a, prev_b = a, b
        a, b = b, a % b
        steps.append(dict(
            line=4, vars={'a': a, 'b': b},
            note='{} % {} = {}. Пара ({}, {}) заменяется на ({}, {}) — общие '
                 'делители у них одни и те же, значит и НОД '
                 'одинаковый.'.format(prev_a, prev_b, b, prev_a, prev_b, a, b),
        ))
    steps.append(dict(
        line=5, vars={'a': a, 'b': b}, out='НОД: {}'.format(a),
        note='Второе число стало нулём — ответ лежит в первом.',
    ))
    return steps


# Код, который трассирует виджет loop-trace в уроке 4.7.
NESTED_CODE = [
    'for i in range(1, 4):',
    '    for j in range(1, 3):',
    '        print(i, j)',
]


def _nested_trace(outer_stop=4, inner_stop=3):
    """Пошаговая трасса вложенного цикла для виджета loop-trace.

    Виджет не привязан к while — трассу готовит Python здесь, буквально
    повторяя разбираемый алгоритм. Главное, что должно быть видно в
    шагах: на каждой итерации внешнего цикла внутренний стартует заново
    с первого значения, поэтому у первого шага внутреннего цикла особый
    note. Переменной j в самом начале ещё нет — просто не кладём ключ в
    vars, виджет покажет прочерк.
    """
    steps = []
    i = None
    j = None

    def state():
        s = {}
        if i is not None:
            s['i'] = i
        if j is not None:
            s['j'] = j
        return s

    for i in range(1, outer_stop):
        steps.append(dict(
            line=1, vars=state(),
            note='Внешний цикл берёт следующее значение: i = {}.'.format(i),
        ))
        for j in range(1, inner_stop):
            if j == 1:
                note = ('Внутренний цикл начинается заново, с первого '
                        'значения: j = {}.'.format(j))
            else:
                note = 'Следующее значение внутреннего цикла: j = {}.'.format(j)
            steps.append(dict(line=2, vars=state(), note=note))
            steps.append(dict(
                line=3, vars=state(), out='{} {}'.format(i, j),
                note='Печатаем пару (i, j).',
            ))
        steps.append(dict(
            line=2, vars=state(),
            note='Внутренний диапазон исчерпан — внутренний цикл завершён, '
                 'управление возвращается во внешний.',
        ))
    steps.append(dict(
        line=1, vars=state(),
        note='Значения внешнего диапазона кончились — оба цикла завершены.',
    ))
    return steps


# Код, который трассирует первый виджет loop-trace в уроке 4.8.
MAXIMUM_CODE = [
    'best = int(input())',
    'for i in range(5):',
    '    x = int(input())',
    '    if x > best:',
    '        best = x',
    'print(best)',
]


def _maximum_trace(values=(-3, -7, -1, -8, -1, -12)):
    """Пошаговая трасса поиска максимума для виджета loop-trace.

    Показания «приходят» из input(), поэтому в трассе они заданы списком
    values — тот же приём, что и в остальных трассах блока: Python здесь
    буквально повторяет алгоритм из MAXIMUM_CODE. Переменную i не
    показываем (её нет в vars виджета) — она в этом алгоритме ничего не
    значит, кроме числа повторений. Данные подобраны отрицательными:
    в шаге вывода видно, что best = 0 испортил бы ответ.
    """
    steps = []
    data = list(values)
    total = len(data) - 1
    best = data[0]
    x = None

    def state():
        s = {}
        if x is not None:
            s['x'] = x
        s['best'] = best
        return s

    steps.append(dict(
        line=1, vars=state(),
        note='Прочитали первое показание: пока оно и есть максимум.',
    ))
    for k in range(total):
        steps.append(dict(
            line=2, vars=state(),
            note='Итерация {} из {}.'.format(k + 1, total),
        ))
        x = data[k + 1]
        steps.append(dict(
            line=3, vars=state(),
            note='Прочитали очередное показание: x = {}.'.format(x),
        ))
        cond = x > best
        steps.append(dict(
            line=4, vars=state(), check=cond,
            note='Сравниваем с текущим максимумом: {} > {}.'.format(x, best),
        ))
        if cond:
            best = x
            steps.append(dict(
                line=5, vars=state(),
                note='Новое значение больше — перезаписываем максимум.',
            ))
    steps.append(dict(
        line=2, vars=state(),
        note='Показания кончились — цикл завершён.',
    ))
    steps.append(dict(
        line=6, vars=state(), out=str(best),
        note='Печатаем ответ. Он отрицательный — с начальным значением '
             'best = 0 программа напечатала бы 0, которого в данных не было.',
    ))
    return steps


# Код, который трассирует второй виджет loop-trace в уроке 4.8 (упрощённый,
# двузначный вариант перебора с конца: сумма цифр считается без while).
BACKWARD_CODE = [
    'for x in range(99, 9, -1):',
    '    digit_sum = x // 10 + x % 10',
    '    if digit_sum == 15:',
    '        print(x)',
    '        break',
    'else:',
    "    print('таких чисел нет')",
]


def _backward_trace(target=15):
    """Пошаговая трасса перебора диапазона с конца для виджета loop-trace.

    Главное, что должно быть видно: первое же найденное число при
    переборе с конца и есть наибольшее подходящее, поэтому сразу
    срабатывает break, а блок else не выполняется. Диапазон двузначный, а
    сумма цифр посчитана арифметикой без вложенного while — иначе трасса
    разрослась бы на сотни шагов.
    """
    steps = []
    x = None
    digit_sum = None

    def state():
        s = {}
        if x is not None:
            s['x'] = x
        if digit_sum is not None:
            s['digit_sum'] = digit_sum
        return s

    found = None
    for x in range(99, 9, -1):
        steps.append(dict(
            line=1, vars=state(),
            note='Идём от конца диапазона к началу: x = {}.'.format(x),
        ))
        digit_sum = x // 10 + x % 10
        steps.append(dict(
            line=2, vars=state(),
            note='Сумма цифр: {} + {} = {}.'.format(x // 10, x % 10, digit_sum),
        ))
        cond = digit_sum == target
        steps.append(dict(
            line=3, vars=state(), check=cond,
            note='Проверяем условие: {} == {}.'.format(digit_sum, target),
        ))
        if cond:
            steps.append(dict(
                line=4, vars=state(), out=str(x),
                note='Первое подходящее число при переборе с конца — '
                     'наибольшее из подходящих.',
            ))
            steps.append(dict(
                line=5, vars=state(),
                note='break: остальные кандидаты меньше, искать нечего. Блок '
                     'else не выполнится — прерывание было.',
            ))
            found = x
            break
    if found is None:
        steps.append(dict(
            line=7, vars=state(), out='таких чисел нет',
            note='Цикл дошёл до конца без break — сработал блок else.',
        ))
    return steps


