DATA_FILE = 'demo_26.txt'

# Он же относительно MEDIA_ROOT – по этому пути файл читает _demo_rows().
DATA_PATH = 'ege/variant-fipi-demo-2027/files/demo_26.txt'

# Типовой пример из условия: время, клиент, объём запроса в Кбайт.
TOY_K = 140000
TOY = [
    ('01:01:01', 101, 20000), ('03:03:03', 202, 110000), ('05:05:05', 101, 90000),
    ('07:07:07', 303, 62000), ('10:10:10', 101, 48000), ('15:15:15', 202, 12000),
    ('21:21:21', 303, 120000), ('23:23:23', 404, 134000),
]
TOY_ANSWER = (303, 220000)
TOY_BACKUPS = [('05:05:05', 130000), ('07:07:07', 90000),
               ('21:21:21', 122000), ('23:23:23', 120000)]
# Клиент → переданный объём на том же примере. Числа из условия: «всего на
# сервер передано 596 000 Кбайт: 158 000, 122 000, 182 000 и 134 000».
TOY_TOTAL = {101: 158000, 202: 122000, 303: 182000, 404: 134000}

