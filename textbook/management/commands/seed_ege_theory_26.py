"""Разбор задания 26 ЕГЭ: обработка журнала с моделированием и сортировкой.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блок «Если спрашивают другое» в скелете не значится, здесь он есть. Сюжет
  у задания 26 не один, но внутри сюжета журнал и раздел одни и те же, а
  меняется только то, что спрашивают: моделирование остаётся прежним и
  правится последняя пара строк. Таблица «что в условии → что править»
  избавляет от разбора каждого варианта заново;
* карты сюжетов номера в статье нет: что задание 26 – это много непохожих
  сюжетов, а каждая статья разбирает один, сказано абзацем на карточке
  задания (templates/quizzes/ege_task.html) над списком статей – там, где
  ученик выбирает, что читать;
* виджета у статьи нет: показывать нечего – журнал на 15 001 строку не
  нагляднее таблицы, а трассировка раздела памяти собирается целиком
  в Python и рисуется таблицей.

* решение разобрано по шагам: между «Как рассуждать» и программой целиком
  стоят четыре пары «текст – фрагмент кода», по фрагменту на вопрос. Готовая
  программа без подводки читалась как «перепишите это»; программа целиком
  склеена из тех же фрагментов (STEP_*), поэтому шаг и итог не расходятся.

Код статьи `_check()` запускает сам (`_run_solution`) – на примере из условия
и, если media на диске есть, на файле демоверсии с ответом ФИПИ. `_simulate` –
та же модель, записанная так, чтобы из неё можно было считать: все пять
неверных ответов «Типичных ошибок» берутся из её режимов, а не вписываются
руками. Без media проверяется только пример: статья публикуется и на машине
без media.

Условие – задание 26 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-26,
файл данных media/ege/variant-fipi-demo-2027/files/demo_26.txt).

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
