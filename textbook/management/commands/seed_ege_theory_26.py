SLUG = 'ege-26-obrabotka-tselyh-chisel-s-sortirovkoy'
ANSWER = (7040, 52204)          # ответ ФИПИ: клиент и сумма двух наибольших копий
BACKUPS_TOTAL = 1072            # сколько всего резервных копий на файле
BACKUPS_MORNING = 534           # из них не позднее 11:59:59
CLIENT_TOTAL = 303454           # сколько Кбайт передал клиент 7040 за день
DATA_LINES = 15001              # строк журнала в файле демоверсии, без заголовка
MORNING = '11:59:59'            # граница из условия: «не позднее 11:59:59»

# Вопрос демоверсии, к которому приложен файл с данными. Разбор без файла
# нечестен: условие говорит «задание выполняется с использованием
# прилагаемого файла», а решать ученику не на чем.
DEMO_QUESTION_ID = 'fipi-demo-2027-26'

# Имя файла в коде разбора – ровно то, под которым он скачивается. Ученик
# файлы не переименовывает: на сайте по имени работает автопроверка, и
