SLUG = 'ege-1-grafy-i-tablitsy-vesov'

# Та же картинка, что в вопросе fipi-demo-2027-01. Путь относительно MEDIA_ROOT.
GRAPH_IMAGE = 'ege/variant-fipi-demo-2027/images/q01_graph.png'
GRAPH_SRC = settings.MEDIA_URL + GRAPH_IMAGE

# Схема дорог демоверсии: буквы и дороги между ними, длин на схеме нет.
GRAPH_EDGES = [
    ('A', 'E'), ('A', 'F'),
    ('B', 'C'), ('B', 'D'), ('B', 'E'),
    ('C', 'F'),
    ('D', 'E'), ('D', 'F'),
]

# Таблица протяжённостей: пункт, пункт, километры.
TABLE_EDGES = [
    (1, 2, 39), (1, 5, 53), (1, 6, 30),
    (2, 3, 21), (3, 4, 8), (3, 5, 3),
    (4, 5, 13), (4, 6, 5),
]

# Координаты вершин в системе виджета (viewBox 0 0 430 300). Расставлены
# вручную по картинке ФИПИ: автоматическая раскладка нарисовала бы тот же граф
# иначе, и ученик не узнал бы схему из своего варианта.
# Третий элемент 'up' поднимает подпись над вершиной: у B и C все рёбра уходят
# вниз, и подпись под ними ложилась прямо на линию.
GRAPH_POS = {
    'A': [210, 248], 'B': [368, 72, 'up'], 'C': [150, 48, 'up'],
    'D': [250, 122], 'E': [332, 188], 'F': [58, 168],
}


def _candidate_rounds(gedges, tedges):
    """Наборы номеров-кандидатов для каждой буквы после каждого раунда уточнения.

    Обе картинки живут в одном словаре смежности: буквы и номера – разные
    ключи, поэтому не путаются. Цвет вершины сначала равен её степени, дальше
    заменяется на «свой цвет + отсортированные цвета соседей». Одинаковый цвет
    у буквы и номера означает, что различить их пока нечем, то есть номер –
    кандидат для этой буквы.

    Возвращает список раундов; первый – сопоставление по одним степеням.
    Остановка, когда очередной раунд перестаёт дробить классы: дальше эта
    техника не сужает ничего, и в задании это и есть ответ «однозначно
    восстановить нельзя».
    """
    adj = {}
    for a, b in list(gedges) + [(e[0], e[1]) for e in tedges]:
        adj.setdefault(a, set()).add(b)
        adj.setdefault(b, set()).add(a)

    letters = sorted(v for v in adj if isinstance(v, str))
    points = sorted(v for v in adj if not isinstance(v, str))

    colour = {v: len(adj[v]) for v in adj}
    result = []
    while True:
        result.append({
            letter: [p for p in points if colour[p] == colour[letter]]
            for letter in letters
        })
        sig = {
            v: (colour[v], tuple(sorted(colour[u] for u in adj[v])))
            for v in adj
        }
        ids = {s: i for i, s in enumerate(sorted(set(sig.values())))}
        nxt = {v: ids[sig[v]] for v in adj}
        if len(set(nxt.values())) == len(set(colour.values())):
            return result
        colour = nxt


def _assignments():
    """Все соответствия «буква -> номер», объясняющие сразу все восемь дорог.

    Перебор всех 720 перестановок: на шести вершинах это мгновенно, а писать
    что-то умнее ради seed-команды незачем. Именно перебор и есть та самая
    проверка «сошлись ли все рёбра», которую ученик делает по таблице руками –
    только здесь она заодно находит и вторую ветку, доказывая, что
    неоднозначность не выдумана.
    """
    letters = sorted({v for edge in GRAPH_EDGES for v in edge})
    points = sorted({p for edge in TABLE_EDGES for p in edge[:2]})
    roads = {frozenset((a, b)) for a, b, _ in TABLE_EDGES}

    found = []
    for perm in permutations(points):
        m = dict(zip(letters, perm))
        if {frozenset((m[a], m[b])) for a, b in GRAPH_EDGES} == roads:
            found.append(m)
    return found


def _km(m, x, y):
    """Длина дороги между буквами x и y при соответствии m."""
    pair = frozenset((m[x], m[y]))
    for a, b, w in TABLE_EDGES:
        if frozenset((a, b)) == pair:
            return w
    raise KeyError(f'нет дороги {x}-{y}')


def _match_steps():
    """Шаги для виджета graph-match: что известно о буквах после каждого хода."""
    rounds = _candidate_rounds(GRAPH_EDGES, TABLE_EDGES)
    # Пояснения написаны под конкретный ход разбора. Если раундов станет
    # больше (другая схема), тексты перестанут соответствовать шагам –
    # пусть команда упадёт здесь, а не выдаст статью с враньём.
    assert len(rounds) == 2, f'ожидалось 2 раунда уточнения, получено {len(rounds)}'
    by_degree, by_neighbours = rounds

    # Буквы, которые определились именно на втором раунде.
    resolved = sorted(
        letter for letter, cand in by_neighbours.items()
        if len(cand) == 1 and len(by_degree[letter]) > 1
    )

    # Две ветки, которыми кончается сужение. Числа в пояснениях берём из них
    # же, а не вписываем руками: иначе правка данных разошлась бы с текстом.
    branches = sorted(_assignments(), key=lambda m: m['A'])
    assert len(branches) == 2, f'ожидалось 2 соответствия, найдено {len(branches)}'
    branch_steps = []
    for n, m in enumerate(branches):
        ea, bc = _km(m, 'E', 'A'), _km(m, 'B', 'C')
        branch_steps.append(dict(
            show='cand', cand={letter: [m[letter]] for letter in sorted(m)},
            hiE=[['E', 'A'], ['B', 'C']],
            hiC=[[m['E'], m['A']], [m['B'], m['C']]],
            title=('Шаг 6. Проверяем ветку A = %d' % m['A']) if n == 0
                  else ('Шаг 7. И вторую ветку, A = %d' % m['A']),
            note=(
                'Подставили и дочитали до конца: '
                + ', '.join(f'{letter} = {m[letter]}' for letter in sorted(m))
                + '. Все восемь дорог схемы нашлись в таблице – соответствие '
                  'верное, номера в шапке таблицы теперь подписаны буквами. '
                + (f'Дорога E–A – это {m["E"]}–{m["A"]}, то есть {ea} км; '
                   f'B–C – это {m["B"]}–{m["C"]}, то есть {bc} км. '
                   f'Сумма: {ea} + {bc} = {ea + bc}.')
                + ('' if n == 0 else
                   ' Соответствие другое, длины поменялись местами – а сумма '
                   'та же. Вот почему спрашивают именно её.')
            ),
        ))

    return [
        dict(
            show='none',
            title='Что дано',
            note='Слева схема дорог, справа таблица их длин. Это один и тот же '
                 'район, но подписи делали разные люди: буквы на схеме и номера '
                 'в таблице никак не связаны. Задача – понять, какая буква какой '
                 'номер, и только потом брать из таблицы километры.',
        ),
        dict(
            show='deg',
            title='Шаг 1. Считаем степени',
            note='Степень пункта – это сколько дорог из него выходит. На схеме '
                 'считаем линии у буквы, в таблице – заполненные клетки в строке '
                 '(складывать числа не надо, важно только сколько их). Наборы '
                 'совпали: две вершины степени 2 и четыре степени 3. Если бы не '
                 'совпали, где-то ошибка в чтении условия.',
        ),
        dict(
            show='cand', cand=by_degree,
            title='Шаг 2. Кандидаты по степеням',
            note='Буква может отвечать только пункту с такой же степенью – '
                 'выписываем под каждой буквой её возможные номера. В лёгких '
                 'вариантах здесь всё и заканчивается: если степень уникальна, '
                 'вершина определена сразу. Здесь не повезло, одинаковых '
                 'степеней много.',
        ),
        dict(
            show='cand', cand=by_neighbours,
            hiL=resolved,
            hiP=[by_neighbours[letter][0] for letter in resolved],
            title='Шаг 3. Смотрим на соседей',
            note='Вершины одной степени различаются окружением. У F среди соседей '
                 'сразу две вершины степени 2 – такая в графе одна, и в таблице '
                 'такой пункт тоже один: первый. У D все три соседа степени 3 – '
                 'и это пункт 5. Два номера определились, а вместе с ними '
                 'сузились остальные.',
        ),
        dict(
            show='cand', cand=by_neighbours,
            title='Шаг 4. Дальше не сужается',
            note='Повторяем тот же приём – ничего нового. A и C остаются '
                 'неразличимы, B и E тоже: если поменять A с C и B с E местами, '
                 'получится ровно та же схема. Однозначно восстановить '
                 'соответствие нельзя, и это не ошибка условия.',
        ),
        dict(
            show='cand', cand=by_neighbours,
            hiE=[['E', 'A'], ['B', 'C']], hiC=[[2, 3], [4, 6]],
            title='Шаг 5. Читаем вопрос',
            note='Спрашивают сумму двух дорог: E–A и B–C. Обе подсвечены на схеме, '
                 'и в таблице им отвечают клетки 21 и 5 – при любой из двух '
                 'расстановок. Та самая перестановка, которая мешала различить '
                 'вершины, просто меняет эти две дороги местами, а сумма от '
                 'перестановки слагаемых не меняется. Осталось довести до конца '
                 'любую из двух веток – на следующих шагах обе.',
        ),
    ] + branch_steps


