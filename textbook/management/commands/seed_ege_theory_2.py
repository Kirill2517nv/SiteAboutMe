"""Разбор задания 2 ЕГЭ: таблицы истинности и порядок столбцов.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* в статье **два** виджета. Первый, `truth-steps`, – разбор по шагам: задание
  решается восстановлением клеток, и текстом это цепочка из семи «значит»,
  в которой читатель теряет, какая клетка откуда взялась. Кадры готовит
  `_steps()`. Второй, `truth-table`, – рабочий черновик, и он намеренно
  универсален: и функция, и фрагмент вводятся руками, так что ученик решает
  в нём задачу со своего листочка, а не смотрит на разобранную. Конфиг из этой
  команды – просто начальное состояние черновика;
* блок `code` стоит внутри второго способа, а не отдельным «решением»:
  экзамен сдают за компьютером, и четыре вложенных цикла печатают нужные
  наборы, не разбирая выражение руками. Восстановление фрагмента после этого
  то же самое, поэтому отдельного разбора у программы нет.

Строки исходной функции виджет не вычисляет: их считает `_rows()`, тем же
разделением труда, что у `loop-trace` и `graph-match`
(docs/textbook-lesson-brief.md). Своё выражение ученик вводит на Python, и вот
его виджет уже разбирает сам; в поле подставляется `PY_EXPR` – та же функция
питоновской записью. Что оба счётчика дают одно и то же, проверяет
`TruthTableParserTests` (textbook/tests.py).

Условие – задание 2 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-02).
`_check()` прогоняет полный перебор соответствий и падает, если ответ
разошёлся с тем, что написано в тексте статьи, – текст и данные правятся
в одном файле и обязаны сходиться.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
from itertools import permutations, product

from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks

SLUG = 'ege-2-tablitsy-istinnosti'

VARS = ('w', 'x', 'y', 'z')

# Фрагмент из условия: столбцы не подписаны, None – пустая клетка,
# последнее значение в строке – F.
FRAGMENT = [
    (None, 0, 1, 0, 0),
    (0, None, None, 0, 0),
    (None, 1, 1, None, 0),
]

ANSWER = 'yxzw'

# Та же функция питоновской записью – она попадает в поле ввода виджета, где
# ученик может её править. Импликация здесь `a <= b`: False меньше True, и
# единственный ложный случай 1 → 0 – единственный, где неравенство не выполнено.
# Что запись считает то же самое, что F() ниже, проверяет TruthTableParserTests
# (textbook/tests.py): он сверяет её таблицу с _rows() настоящим eval().
PY_EXPR = '((x == (not y)) <= (not (w <= x))) or (not z)'


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def F(w, x, y, z):
    """F = ((x ≡ ¬y) → ¬(w → x)) ∨ ¬z."""
    a = x == (not y)                    # x ≡ ¬y
    b = not ((not w) or x)              # ¬(w → x)
    return ((not a) or b) or (not z)    # (a → b) ∨ ¬z


def _rows():
    """Полная таблица истинности: значения переменных в порядке VARS плюс F."""
    return [list(v) + [int(F(*v))] for v in product((0, 1), repeat=len(VARS))]


def _check():
    """Полный перебор соответствий: ответ обязан быть ровно один и равен ANSWER.

    Перебираются и порядок столбцов (24 варианта), и то, какая строка
    фрагмента какой строке таблицы отвечает: строки фрагмента идут в
    произвольном порядке, и жадное сопоставление «первая с первой» в общем
    случае врёт. На трёх строках это мгновенно.
    """
    zero = [r[:len(VARS)] for r in _rows() if r[len(VARS)] == 0]
    assert len(zero) == 3, f'ожидалось 3 строки с F = 0, получено {len(zero)}'

    def fits(cells, row, perm):
        val = dict(zip(VARS, row))
        return all(c is None or c == val[perm[i]] for i, c in enumerate(cells[:len(VARS)]))

    found = [
        ''.join(perm)
        for perm in permutations(VARS)
        if any(
            all(fits(cells, row, perm) for cells, row in zip(FRAGMENT, order))
            for order in permutations(zero, len(FRAGMENT))
        )
    ]
    assert found == [ANSWER], f'ожидался единственный ответ {ANSWER}, найдено {found}'

    # Разбор в статье идёт восстановлением клеток, и каждый его шаг опирается на
    # свойство этих трёх наборов. Свойства проверяем здесь: поменяется функция –
    # упадёт команда, а не останется текст, объясняющий несуществующий ход.
    assert not [i for i in range(len(VARS)) if all(r[i] == 0 for r in zero)], (
        'разбор опирается на то, что нет переменной, равной нулю во всех наборах'
    )
    three = [r for r in zero if sum(r) == len(VARS) - 1]
    assert len(three) == 1 and VARS[three[0].index(0)] == 'y', (
        'разбор опирается на единственный набор из трёх единиц с нулём у y'
    )
    assert len([r for r in zero if r[0] == 0 and r[1] == 0]) == 1, (
        'разбор опирается на единственный набор, где w и x оба нули'
    )


FORMULA = '((x ≡ ¬y) → ¬(w → x)) ∨ ¬z'

# Формула, разрезанная на куски для подсветки: на каждом кадре разбора выделена
# та операция, которую сейчас читают. Куски склеиваются обратно в FORMULA –
# это проверяет ассерт в _steps(), поэтому опечатка в разрезе не доедет до
# статьи незамеченной.
FORMULA_WHOLE = [['', FORMULA]]
FORMULA_OR = [['', '((x ≡ ¬y) → ¬(w → x))'], ['hi', ' ∨ '], ['', '¬z']]
FORMULA_IMP = [['', '((x ≡ ¬y)'], ['hi', ' → '], ['', '¬(w → x)) ∨ ¬z']]
FORMULA_INNER = [['', '(('], ['hi', 'x ≡ ¬y'], ['', ') → ¬('], ['hi', 'w → x'], ['', ')) ∨ ¬z']]


def _zero_sets():
    """Наборы, на которых F ложна, – в порядке строк таблицы."""
    return [dict(zip(VARS, r[:len(VARS)])) for r in _rows() if r[len(VARS)] == 0]


def _grid():
    """Полностью восстановленный фрагмент: строка фрагмента – её набор.

    Соответствие столбцов известно (ANSWER), поэтому каждая строка фрагмента
    просто ложится на свой набор. Строки разбираются по порядку, уже занятый
    набор второй раз не берётся – без этого третья строка фрагмента подходит
    сразу к двум наборам, и восстановление было бы неоднозначным.
    """
    order = list(ANSWER)
    free = _zero_sets()
    grid = []
    for cells in FRAGMENT:
        fits = [
            s for s in free
            if all(c is None or c == s[order[i]] for i, c in enumerate(cells[:len(VARS)]))
        ]
        assert len(fits) == 1, f'строка {cells} ложится на {len(fits)} наборов, ожидался один'
        free.remove(fits[0])
        grid.append([fits[0][order[i]] for i in range(len(VARS))])
    return grid


def _fmt(values):
    """Набор в том виде, в каком он пишется в пояснении: «(1, 1, 0, 1)»."""
    return '(' + ', '.join(str(v) for v in values) + ')'


def _steps():
    """Кадры для виджета truth-steps: разбор формулы, затем восстановление.

    Первые кадры – разбор выражения с последней операции: именно так задание и
    решается, без построения таблицы истинности. Полную таблицу рисует второй
    способ, из блока с программой; показывать её здесь значило бы учить
    противоположному тому, что говорит текст.

    Значения дописываемых клеток берутся из восстановленного решения (`_grid`),
    а не пишутся руками: пояснение и число в клетке правятся в одном месте и
    не могут разойтись. Координаты клеток и порядок ходов – свои для этого
    фрагмента, поэтому каждый ход проверяется ассертом: откроется не та клетка
    – команда упадёт здесь, а не выдаст разбор с враньём.
    """
    for parts in (FORMULA_WHOLE, FORMULA_OR, FORMULA_IMP, FORMULA_INNER):
        joined = ''.join(part[1] for part in parts)
        assert joined == FORMULA, f'разрез формулы склеивается в «{joined}»'

    order = list(ANSWER)
    grid = _grid()
    sets = [[s[v] for v in VARS] for s in _zero_sets()]

    cells = [list(r[:len(VARS)]) for r in FRAGMENT]
    labels = [None] * len(VARS)

    def index_of(values):
        """Номер набора в правой панели – для стрелки."""
        assert list(values) in sets, f'набор {values} не найден'
        return sets.index(list(values))

    def open_cell(r, c):
        assert cells[r][c] is None, f'клетка ({r}, {c}) уже заполнена'
        cells[r][c] = grid[r][c]
        return [r, c]

    def label(i, name):
        assert order[i] == name, f'столбец {i + 1} – это {order[i]}, а не {name}'
        labels[i] = name

    def frame(**kw):
        return dict(cells=[list(row) for row in cells], labels=list(labels), **kw)

    # Наборы в терминах (w, x, y, z) – в таком виде их показывает правая панель.
    top = [grid[0][order.index(v)] for v in VARS]      # верхняя строка фрагмента
    middle = [grid[1][order.index(v)] for v in VARS]
    bottom = [grid[2][order.index(v)] for v in VARS]

    steps = [
        frame(
            panel='formula', formula=FORMULA_WHOLE, facts=[],
            title='Что дано',
            note='Слева фрагмент: столбцы не подписаны, часть клеток пуста, строки '
                 'идут в своём порядке. В столбце F везде ноль – значит, из всей '
                 'таблицы истинности нам нужны только наборы, на которых функция '
                 'ложна. Все 16 строк для этого строить не нужно: их даст разбор '
                 'самой формулы, справа.',
        ),
        frame(
            panel='formula', formula=FORMULA_OR,
            facts=[['z = 1', True], ['(x ≡ ¬y) → ¬(w → x) = 0', True]],
            title='Шаг 1. Последняя операция – дизъюнкция',
            note='Приоритет: → и ≡ выполняются последними, поэтому верхняя операция '
                 'здесь ∨. Дизъюнкция ложна только тогда, когда ложны оба слагаемых, '
                 'значит сразу ¬z = 0, то есть z = 1, и вся импликация слева равна '
                 'нулю. Одна операция – и половина ответа известна.',
        ),
        frame(
            panel='formula', formula=FORMULA_IMP,
            facts=[['z = 1', False], ['x ≡ ¬y = 1', True], ['w → x = 1', True]],
            title='Шаг 2. Импликация ложна только на 1 → 0',
            note='Разбираем то, что осталось. Импликация ложна ровно в одном случае: '
                 'посылка истинна, следствие ложно. Значит (x ≡ ¬y) = 1, а '
                 '¬(w → x) = 0, то есть сама импликация w → x истинна.',
        ),
        frame(
            panel='formula', formula=FORMULA_INNER,
            facts=[['z = 1', False], ['x ≠ y', True], ['w → x = 1', False]],
            title='Шаг 3. Расшифровываем',
            note='x ≡ ¬y истинно, когда x совпадает с отрицанием y, то есть когда x '
                 'и y разные. Условие w → x оставляем как есть – импликация ложна '
                 'только при w = 1, x = 0, все остальные пары подходят.',
        ),
        frame(
            panel='sets',
            title='Шаг 4. Выписываем наборы',
            note=f'Условия z = 1, x ≠ y и w → x дают три набора: при x = 1, y = 0 '
                 f'импликация истинна при любом w – две строки, {_fmt(middle)} и '
                 f'{_fmt(bottom)}; при x = 0, y = 1 – только при w = 0, это '
                 f'{_fmt(top)}. Всего три, ровно столько же, сколько строк во '
                 'фрагменте: значит это они и есть, только столбцы переставлены и '
                 'порядок строк свой. Таблицу из 16 строк мы так и не построили.',
        ),
    ]

    label(2, 'z')
    steps.append(frame(
        panel='sets', added=[open_cell(1, 2)],
        title='Шаг 5. Столбец без нулей – это z',
        note='Дальше восстанавливаем фрагмент. Во всех трёх наборах z = 1, поэтому '
             'в столбце z не может стоять ноль. Слева нули есть в столбцах 1, 2 и 4 '
             '– остаётся третий. Подписываем его буквой z и сразу дописываем '
             'недостающую единицу: раз это z, клетка определена.',
    ))

    steps.append(frame(
        panel='sets', added=[open_cell(2, 3)],
        title='Шаг 6. Внизу столбца 4 – единица',
        note='В столбце 4 уже стоят два нуля, а нижняя клетка пуста. Ноля там быть '
             'не может: столбец из трёх нулей означал бы переменную, равную нулю во '
             'всех трёх наборах, а такой среди них нет. Значит, единица.',
    ))

    fresh = open_cell(2, 0)
    label(0, 'y')
    steps.append(frame(
        panel='sets', added=[fresh], hiRow=[2], hiSet=[index_of(bottom)],
        title='Шаг 7. Строка с тремя единицами',
        note='Теперь смотрим не на столбец, а на строку. В нижней строке три '
             'единицы и одна пустая клетка. Набор с тремя единицами среди наших '
             f'ровно один – {_fmt(bottom)}, и ноль в нём стоит у y. Значит нижняя '
             'строка – это он: слева дописываем 0, а столбец 1 подписываем буквой y.',
    ))

    steps.append(frame(
        panel='sets', added=[open_cell(0, 0)], hiRow=[0], hiSet=[index_of(top)],
        title='Шаг 8. Верхняя строка',
        note='Свободными остались столбцы 2 и 4 – в них w и x, пока неизвестно, в '
             'каком порядке. В верхней строке в обоих стоят нули, а набор, где обе '
             f'эти переменные нулевые, один: {_fmt(top)}. Значит верхняя строка – он, '
             'и y в ней равен 1.',
    ))

    fresh = open_cell(1, 1)
    label(1, 'x')
    label(3, 'w')
    steps.append(frame(
        panel='sets', added=[fresh], hiRow=[1], hiSet=[index_of(middle)],
        title='Шаг 9. Средней достаётся последний набор',
        note=f'Две строки разобраны, средней остаётся {_fmt(middle)}: w = 0, x = 1. '
             'В средней строке в столбце 4 стоит 0 – значит столбец 4 это w, а '
             'столбец 2 – x. Обе буквы встали на места.',
    ))

    assert all(all(v is not None for v in row) for row in cells), 'фрагмент восстановлен не весь'
    assert cells == grid, 'восстановленный фрагмент разошёлся с решением'

    steps.append(frame(
        panel='sets',
        title='Готово',
        note='Фрагмент восстановлен целиком, все четыре столбца подписаны, и ни '
             'одного варианта перебирать не пришлось – каждый шаг был вынужденным. '
             f'Ответ – буквы в порядке столбцов: {ANSWER}.',
    ))
    return steps


def _second_way_code():
    """Программа второго способа: четыре цикла и печать ложных наборов.

    Ожидаемый вывод дописывается комментарием и берётся из тех же данных, что
    и всё остальное в статье, – руками его набирать нельзя, разойдётся. Заодно
    код прогоняется здесь же: напечатает не то – команда упадёт.
    """
    body = (
        "def F(w, x, y, z):\n"
        "    # Импликация a -> b на Python: a <= b, ведь False меньше True.\n"
        "    return ((x == (not y)) <= (not (w <= x))) or (not z)\n"
        "\n"
        "# Четыре вложенных цикла – все 16 наборов. Печатаем только те,\n"
        "# на которых функция ложна: именно они попали во фрагмент.\n"
        "for w in 0, 1:\n"
        "    for x in 0, 1:\n"
        "        for y in 0, 1:\n"
        "            for z in 0, 1:\n"
        "                if not F(w, x, y, z):\n"
        "                    print(w, x, y, z)\n"
    )

    expected = [' '.join(str(s[v]) for v in VARS) for s in _zero_sets()]

    printed = []
    exec(compile(body, 'second-way', 'exec'),
         {'print': lambda *a: printed.append(' '.join(str(x) for x in a))})
    assert printed == expected, f'программа печатает {printed}, ожидалось {expected}'

    return body + '\n# Программа напечатает:\n' + ''.join(
        f'# {line}\n' for line in expected
    )


