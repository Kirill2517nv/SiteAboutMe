class Command(BaseCommand):
    help = 'Создаёт справочник заданий ЕГЭ 1–27 и статьи-заглушки под теорию'

    def add_arguments(self, parser):
        parser.add_argument(
            '--force', action='store_true',
            help='Перезаписать краткие описания заданий из EGE_TASKS. Нужно, когда '
                 'сменился кодификатор: без флага однажды заполненное описание не трогается.',
        )

    @transaction.atomic
    def handle(self, *args, **options):
        force = options['force']
        created_tasks = updated_tasks = 0
        created_articles = 0

        for number, title, description in EGE_TASKS:
            task, was_created = EgeTask.objects.get_or_create(
                number=number,
                defaults={'title': title, 'short_description': description, 'order': number},
            )
            if was_created:
                created_tasks += 1
            else:
                # Выравниваем название и порядок, но не трогаем то, что учитель
                # мог поправить осмысленно – описание перезаписываем только пустое.
                # При смене кодификатора это как раз мешает: там описание нужно
                # обновить принудительно, для этого и нужен --force.
                changed = []
                if task.title != title:
                    task.title = title
                    changed.append('title')
                if task.order != number:
                    task.order = number
                    changed.append('order')
                if (force or not task.short_description) and task.short_description != description:
                    task.short_description = description
                    changed.append('short_description')
                if changed:
                    task.save(update_fields=changed)
                    updated_tasks += 1

            slug = f'ege-{number}-{slugify_ru(title)}'
            article_title = f'Задание {number}. {title}'

            existing = Article.objects.filter(track='ege', ege_task=task).first()
            if existing:
                changed = []
                if existing.title != article_title:
                    existing.title = article_title
                    changed.append('title')
                # Пустая неопубликованная заглушка ещё не адрес: ссылок на неё
                # нет, и оставлять slug снятой темы («ege-10-poisk-v-tekstovom-
                # dokumente» у статьи про маску подсети) незачем. У статьи
                # с содержимым или опубликованной slug неприкосновенен –
                # менять его значит ломать сохранённые ссылки.
                if (existing.slug != slug and not existing.is_published
                        and not existing.blocks.exists()):
                    existing.slug = slug
                    changed.append('slug')
                if changed:
                    existing.save(update_fields=changed)
                continue

            Article.objects.create(
                track='ege',
                ege_task=task,
                slug=slug,
                title=article_title,
                description=description,
                order=number,
                is_published=False,
            )
            created_articles += 1

        self.stdout.write(self.style.SUCCESS(
            f'Заданий ЕГЭ: создано {created_tasks}, обновлено {updated_tasks}. '
            f'Статей-заглушек создано: {created_articles}.'
        ))
