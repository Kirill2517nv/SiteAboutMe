def _trace(program, start=(0, 0), heading=(0, 1)):
    """Прогон программы Черепахи: вершины маршрута, конец и курс.

    Направление – пара целых, а не угол в градусах: все повороты в задании
    кратны 90, и поворот сводится к перестановке координат вектора. Через
    `cos`/`radians` то же самое считается во float, и замкнутый контур
    возвращается не в ноль, а в 7.1e-15 – после этого ни сравнить вершины
    с условием, ни поставить assert на прямоугольник уже нельзя.
    """
    x, y = start
    dx, dy = heading
    pts = [(x, y)]
    for cmd, arg in program:
        if cmd in 'FB':
            step = arg if cmd == 'F' else -arg
            x, y = x + dx * step, y + dy * step
            pts.append((x, y))
        else:
            for _ in range(arg // 90):
                dx, dy = (dy, -dx) if cmd == 'R' else (-dy, dx)
    return pts, (x, y), (dx, dy)


def _rect(pts):
    """Габаритный прямоугольник маршрута: (x_min, y_min, x_max, y_max).

    Обе фигуры задания – прямоугольники со сторонами по осям, поэтому
    габарит и есть сама фигура. Для непрямоугольной фигуры так делать
    нельзя, и разбор об этом говорит прямо.
    """
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def _solution():
    """Оба прямоугольника, точка старта второго, их пересечение и ответ."""
    pts1, end, head = _trace(PROGRAM_1)
    _, start2, head2 = _trace(MOVE, end, head)
    pts2, _, _ = _trace(PROGRAM_2, start2, head2)

    r1, r2 = _rect(pts1), _rect(pts2)
    inter = (
        max(r1[0], r2[0]), max(r1[1], r2[1]),
        min(r1[2], r2[2]), min(r1[3], r2[3]),
    )
    points = (inter[2] - inter[0] + 1) * (inter[3] - inter[1] + 1)
    return r1, r2, start2, inter, points


def _check():
    """Числа разбора обязаны сойтись с ответом ФИПИ, а код блока – печатать его.

    Тут проверяется всё, на что текст статьи ссылается прямо: оба
    прямоугольника, точка, с которой начинается второй, их пересечение,
    площадь и периметр из таблицы «Если условие другое» и сумма, которая
    получается при ошибке на единицу. Разойдётся – команда упадёт здесь,
    а не оставит статью, доказывающую неверный ответ.
    """
    r1, r2, start2, inter, points = _solution()
    assert points == ANSWER, f'разбор даёт {points}, у ФИПИ {ANSWER}'
    assert r1 == (0, 0, 30, 24), f'первая фигура {r1}'
    assert r2 == (10, 2, 81, 77), f'вторая фигура {r2}'
    assert start2 == (10, 2), f'второй прямоугольник начинается в {start2}'
    assert inter == (10, 2, 30, 24), f'пересечение {inter}'

    w, h = inter[2] - inter[0], inter[3] - inter[1]
    assert w * h == 440, f'площадь пересечения {w * h}'
    assert 2 * (w + h) == 84, f'периметр пересечения {2 * (w + h)}'
    assert w * (h + 1) == 460, 'разбор опирается на то, что ошибка на единицу даёт 460'

    # Контур замыкается за два прохода – на этом держится весь блок 3.
    closed, _, _ = _trace(PROGRAM_1[:8])
    assert closed[0] == closed[-1] == (0, 0), f'контур не замкнулся: {closed}'

    # Видимая область черновика обязана вмещать обе фигуры целиком. Это не
    # придирка: при школьном множителе `s = 10` фигура демоверсии уходит за
    # правый верхний угол окна, и ученик видит обрезанную картинку, которую
    # не с чем сверить. Числа продублированы в тексте блока «Масштаб и окно».
    world = (-6, -6, 90, 84)
    assert f'setworldcoordinates{world}' in DRAFT, (
        'окно черновика разошлось с текстом разбора')
    assert world[0] <= min(r1[0], r2[0]) and world[1] <= min(r1[1], r2[1]), (
        'фигура вылезает за левый нижний угол окна')
    assert world[2] >= max(r1[2], r2[2]) and world[3] >= max(r1[3], r2[3]), (
        'фигура вылезает за правый верхний угол окна')

    # Код из блока «Решение» обязан печатать тот же ответ.
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exec(compile(SOLUTION, '<solution>', 'exec'), {})
    printed = buffer.getvalue().strip()
    assert printed == str(ANSWER), f'код блока печатает {printed}, а не {ANSWER}'


