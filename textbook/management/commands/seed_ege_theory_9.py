def _calc_steps():
    """Слайды для screen-steps: Markdown рендерится здесь тем же markdownify,
    что и текст статьи, поэтому виджету не нужен свой разборщик разметки.

    Шаг отдаёт либо `image`, либо `video` с `poster` – смешивать нельзя:
    виджет показывает видео, если ключ есть, и картинка при нём осталась бы
    в конфиге мёртвым весом. Отсюда и проверка ниже: опечатка в ключе выдала бы
    шаг вообще без кадра, а это заметно только глазами на странице.
    """
    steps = []
    for s in CALC_STEPS:
        step = dict(title=s['title'], html=str(markdownify(s['text'])), alt=s['alt'])
        if s.get('video'):
            step['video'] = settings.MEDIA_URL + s['video']
            step['poster'] = settings.MEDIA_URL + s['poster']
            if s.get('cues'):
                step['cues'] = s['cues']
        else:
            step['image'] = settings.MEDIA_URL + s['file']
        steps.append(step)
    assert all(('video' in s) != ('image' in s) for s in steps), 'шаг без кадра'
    return steps


