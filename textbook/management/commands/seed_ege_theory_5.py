SLUG = 'ege-5-algoritmy-dlya-ispolnitelya'
LIMIT = 95        # «R, превышающее 95» из условия демоверсии
ANSWER = 100      # ответ ФИПИ
ANSWER_N = 9      # N, дающее этот ответ
SCAN = 10000      # верхняя граница перебора: ответ заведомо ближе

# Ровно тот код, что стоит в блоке `Решение`. Держим его отдельной
# константой, а не внутри dict: это единственный блок статьи, который читают
# целиком, и в diff он должен выглядеть так же, как на странице.
SOLUTION = (
    "def r(n):\n"
    "    s = bin(n)[2:]              # двоичная запись без приставки '0b'\n"
    "    if n % 2 == 0:\n"
    "        s = '11' + s + '11'     # чётное: по две единицы с обеих сторон\n"
    "    else:\n"
    "        s = '1' + s + '00'      # нечётное: единица слева, два нуля справа\n"
    "    return int(s, 2)\n"
    "\n"
    "# Проверка функции на примерах из условия\n"
    "print(r(13))                    # Должно быть 116\n"
    "print(r(6))                     # должно быть 123\n"
    "\n"
    "print(min(r(n) for n in range(1, 10000) if r(n) > 95)) # 100\n"
)


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _r(n):
    """Число R, которое алгоритм демоверсии строит из числа N.

    Записана она не так, как в блоке `code`: здесь нужны значения, а не
    показ. Правило то же – и `_check()` следит, чтобы оно не разъехалось
    с примерами из условия.
    """
    s = bin(n)[2:]
    if n % 2 == 0:
        s = '11' + s + '11'
    else:
        s = '1' + s + '00'
    return int(s, 2)


def _values(limit=SCAN):
    """Различные значения R для N от 1 до limit, по возрастанию.

    Нужны, чтобы говорить о редкости результатов: между соседними числами
    диапазона почти ничего не встречается, и список это показывает лучше
    любого «результаты редки».
    """
    return sorted({_r(n) for n in range(1, limit + 1)})


def _in_range(low, high):
    """Значения R внутри отрезка – то, что вообще может оказаться ответом."""
    return [value for value in _values() if low <= value <= high]


def _narrow_answer():
    """Ответ, который получается, если остановить перебор на N = 8.

    Это первое подходящее значение R, и на нём останавливается тот, кто взял
    диапазон на глазок. Число считается здесь, а не пишется в тексте строкой:
    «Типичные ошибки» и `_check()` обязаны называть одно и то же.
    """
    return min(value for value in _values(8) if value > LIMIT)


def _table(rows=15):
    """Первые `rows` чисел N и то, что алгоритм делает с их записью.

    Столбец R нарочно идёт вразнобой: строки 8 и 9 (227 и 100) – тот самый
    довод, что искать ответ по возрастанию N бессмысленно. Строку ответа
    выделяем жирным, чтобы её было видно раньше, чем абзац под таблицей.

    Заливку строки даёт `<mark>` в первой ячейке: markdown-таблица не умеет
    повесить класс на `<tr>`, и правило `tr:has(mark) td` в
    static/css/textbook-article.css красит по нему всю строку. Сам `<mark>`
    там обесцвечен, так что в ячейке он ничего не рисует.
    """
    lines = [
        '| N | N в двоичной | Чётность | R в двоичной | R |',
        '| --- | --- | --- | --- | --- |',
    ]
    for n in range(1, rows + 1):
        value = _r(n)
        parity = 'чётное' if n % 2 == 0 else 'нечётное'
        bold = '**' if n == ANSWER_N else ''
        number = f'<mark>{bold}{n}{bold}</mark>' if n == ANSWER_N else str(n)
        lines.append(
            f'| {number} | `{bin(n)[2:]}` | {parity} '
            f'| `{bin(value)[2:]}` | {bold}{value}{bold} |'
        )
    return '\n'.join(lines)


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ и с текстом статьи.

    Поменяется условие – команда упадёт здесь, вместо того чтобы оставить
    в опубликованной статье таблицу, доказывающую неверный ответ.
    """
    assert _r(13) == 116 and _r(6) == 123, (
        f'примеры из условия дают {_r(13)} и {_r(6)} вместо 116 и 123 – '
        'блок «Типовой пример» разбирает по разрядам не то, что обещает'
    )
    assert min(value for value in _values() if value > LIMIT) == ANSWER, (
        f'наименьшее R больше {LIMIT} равно '
        f'{min(value for value in _values() if value > LIMIT)}, а не {ANSWER}: '
        'разбор решает другую задачу, чем условие'
    )
    assert _r(ANSWER_N) == ANSWER, (
        f'N = {ANSWER_N} даёт R = {_r(ANSWER_N)}, а не {ANSWER} – в таблице '
        'и в «Типичных ошибках» назван не тот N'
    )
    assert _in_range(80, 140) == [100, 108, 115, 116, 123, 124], (
        f'в промежутке 80…140 оказались {_in_range(80, 140)} – блок '
        '«Как рассуждать» называет числа, которых там нет'
    )
    assert _r(8) == 227 and _r(9) == 100, (
        f'R(8) = {_r(8)}, R(9) = {_r(9)} – на паре 227 и 100 держится '
        'главный вывод разбора'
    )
    assert _r(8) > _r(9), (
        'соседние N дают R по возрастанию – таблица в блоке «Как рассуждать» '
        'перестала что-либо доказывать'
    )
    assert _narrow_answer() == 115, (
        f'перебор до N = 8 даёт {_narrow_answer()} – в «Типичных ошибках» '
        'названо другое число'
    )


