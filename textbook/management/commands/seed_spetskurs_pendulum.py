def _ordered(blocks):
    """Проставить order по позиции в списке.

    Руками эти номера уже разъезжались: вставишь блок в середину – и дальше
    два блока с одним order, а порядок на странице определяется как повезёт.
    Позиция в списке и есть порядок, второго источника правды не нужно.
    """
    for i, block in enumerate(blocks, start=1):
        block['order'] = i
    return blocks


def _art(slug, text):
    """Ссылка на другую статью учебника – хоть в «Основы C++», хоть внутрь работы."""
    return f'[{text}](/textbook/article/{slug}/)'




class Command(BaseCommand):
    help = 'Наполняет статьи задачи «Математический маятник»'

    @transaction.atomic
    def handle(self, *args, **options):
        task = CourseTask.objects.get(slug=TASK_SLUG)

        for order, (slug, title, description) in enumerate(ARTICLES, start=1):
            fields = dict(
                track='spetskurs',
                course_task=task,
                title=title,
                description=description,
                order=order,
            )
            # Текст статьи принадлежит команде, решение о публикации – учителю.
            # `is_published` поэтому только в create_defaults: новая статья
            # рождается черновиком (её вычитывают на сайте, суперпользователю она
            # открыта по прямой ссылке), а повторный прогон правит текст и не
            # снимает с публикации то, что уже выпущено.
            Article.objects.update_or_create(
                slug=slug,
                defaults=fields,
                create_defaults={**fields, 'is_published': False},
            )

        # Разбор задачи – это ровно ARTICLES, лишнее в базе удаляется. Иначе
        # снятая статья остаётся висеть на сайте: слаг из списка убран, команда
        # его больше не трогает, а страница живёт – и, если она была
        # опубликована, ученик её видит. Так и случилось бы с «Что здесь нового
        # в C++»: она пересказывала статью о методе (порядок присваиваний) и
        # «Основы C++» (типы, ранний выход, деление на ноль), её сняли, а на
        # проде она осталась бы навсегда.
        stale = task.articles.exclude(slug__in=[slug for slug, _, _ in ARTICLES])
        removed = sorted(stale.values_list('slug', flat=True))
        if removed:
            stale.delete()
            self.stdout.write(self.style.WARNING(
                'Удалены статьи, которых больше нет в списке: ' + ', '.join(removed)
            ))

        self.seed_1()
        self.seed_2()
        self.seed_3()
        self.seed_4()
        self.seed_5()
        self.seed_6()

        blocks = sum(a.blocks.count() for a in task.articles.all())
        self.stdout.write(self.style.SUCCESS(
            f'Готово: задача «{task.title}» – {len(ARTICLES)} статей, {blocks} блоков'
        ))

