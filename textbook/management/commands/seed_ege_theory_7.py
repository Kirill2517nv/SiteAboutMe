"""Разбор задания 7 ЕГЭ: объём оцифрованного звука и растрового изображения.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блока `code` нет, как в заданиях 1 и 4. Норматив – 5 минут, всё задание
  укладывается в одну формулу и перевод единиц; программа тут не ускоряет,
  а отвлекает – пока опишешь условие переменными, задача уже решена;
* блоков разбора два, а не один: банк (fixtures/bank-7.json, 30 задач)
  делится на два жанра – звук (10) и растровая графика (20). Формула у них
  разная, а порядок действий один, поэтому звук разобран полностью, а
  графика – вторым проходом того же порядка на задаче из банка. Убрать
  графику нельзя: это две трети выдачи;
* виджета нет. `sampling-wave` и `pixel-grid` стоят в уроках учебника 7.6 и
  7.7, на которые разбор ссылается: там объясняют, что такое отсчёт и
  глубина цвета, а здесь их уже умеют считать.

Разбор ведётся **счётом в лоб на калькуляторе**, а не разложением чисел на
степени двойки. Раскладывать быстрее, но это отдельный навык, который нужно
не сбить под стрессом: сократить двойки не до конца или потерять множитель
при сокращении – ошибка, которую в бланке уже не видно. Умножить четыре
числа подряд и дважды поделить – действие, которое нельзя сделать
«наполовину», и калькулятор на экзамене разрешён. Поэтому в статье везде
стоят полные числа, а не $2^k \\cdot m$.

Порядок один и тот же в обоих примерах: собрать биты одним произведением,
поделить на 8 – байты, поделить на 1024 – Кбайт, ещё раз на 1024 – Мбайт.
Останавливаться на той единице, которую спросили.

Единственное место, где двойка всё же появляется, – глубина цвета по мощности
палитры: $i = \\lceil \\log_2 N \\rceil$. Это не приём ускорения счёта, а сама
формула, и заменять её перебором («делите пополам, считайте деления») незачем –
логарифм есть на любом калькуляторе. Важно тут другое, и разбор проговаривает
это отдельно: скобки означают округление **вверх**, потому что $i$ бит хранят
$2^i$ вариантов, и недобрать бит нельзя.

Числа в тексте вычисляются, а не вписываются руками: вся цепочка считается
в `_audio_steps()` и `_image_steps()`, таблица печатает то же, что посчитано,
а `_check()` сверяет оба итога с ответами ФИПИ и kompege. Разойдётся –
команда упадёт здесь, а не выдаст статью с враньём.

Условие – задание 7 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-07).
Второй пример – задача из fixtures/bank-7.json.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
import math

from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks

SLUG = 'ege-7-kodirovanie-zvuka-i-grafiki'

# Условие демоверсии: стерео, 32 000 Гц, 16 бит, 2 минуты 27 секунд.
RATE = 32_000          # частота дискретизации, Гц
DEPTH = 16             # глубина кодирования, бит
CHANNELS = 2           # стерео
MINUTES, SECONDS = 2, 27
AUDIO_ANSWER = 18375   # Кбайт, ответ ФИПИ

# Второй пример – задача из банка: пакет фотографий в Мбайт.
WIDTH, HEIGHT = 1024, 960
PALETTE = 16_384       # цветов в палитре
SHOTS = 400            # снимков в пакете
IMAGE_ANSWER = 656     # Мбайт, целая часть

# Палитра не из степени двойки – только для объяснения, зачем логарифм
# округляют вверх. В самих задачах номера такая не встречается, поэтому в
# счёт она не идёт и живёт отдельной константой.
EXAMPLE_PALETTE = 300


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _spaced(n):
    """Разряды через пробел: 150 528 000 читается, 150528000 – нет.

    Числа в этом разборе длинные по замыслу – их и правда набирают на
    калькуляторе целиком, – поэтому в тексте они обязаны быть разбиты на
    разряды. Внутри формул $…$ такой пробел ставить нельзя: LaTeX его
    схлопнет.
    """
    return f'{n:,}'.replace(',', ' ')


def _bits_for(colors):
    """Глубина цвета: двоичный логарифм числа цветов, округлённый **вверх**.

    Считается целочисленно: `(N - 1).bit_length()` – это в точности
    $\\lceil \\log_2 N \\rceil$ при $N \\ge 1$. Через `math.log2` то же самое
    вычислять нельзя: на double `log2(2**29)` способен вернуть 28.999999,
    и округление вниз тихо испортит ответ в задаче, где вся арифметика
    целая. Дробный логарифм в статье нужен ровно один раз – показать, что
    он бывает дробным, – и там он честно берётся из `math`.
    """
    return (colors - 1).bit_length()


def _bits_per_pixel():
    """Глубина цвета палитры из условия примера."""
    return _bits_for(PALETTE)


def _audio_steps():
    """Цепочка счёта для звука: (что считаем, выражение, результат, единица).

    Один список кормит и таблицу в статье, и `_check()`, поэтому расписанные
    в разборе промежуточные числа не могут разойтись с настоящими.
    """
    seconds = MINUTES * 60 + SECONDS
    per_second = RATE * DEPTH * CHANNELS
    total_bits = per_second * seconds
    total_bytes = total_bits // 8
    total_kb = total_bytes // 1024
    return [
        ('Длительность в секундах', f'{MINUTES} \\cdot 60 + {SECONDS}',
         seconds, 'с'),
        ('Бит в одной секунде', f'{RATE} \\cdot {DEPTH} \\cdot {CHANNELS}',
         per_second, 'бит'),
        ('Бит во всём сообщении', f'{per_second} \\cdot {seconds}',
         total_bits, 'бит'),
        ('Байты – делим на 8', f'{total_bits} / 8', total_bytes, 'байт'),
        ('Кбайты – делим на 1024', f'{total_bytes} / 1024', total_kb, 'Кбайт'),
    ]


def _image_steps():
    """Та же цепочка для картинки, на два шага длиннее: пиксели и Мбайты."""
    depth = _bits_per_pixel()
    pixels = WIDTH * HEIGHT
    one_shot = pixels * depth
    packet_bits = one_shot * SHOTS
    packet_bytes = packet_bits // 8
    packet_kb = packet_bytes // 1024
    return [
        ('Пикселей на снимке', f'{WIDTH} \\cdot {HEIGHT}', pixels, 'пикселей'),
        ('Бит на снимок', f'{pixels} \\cdot {depth}', one_shot, 'бит'),
        (f'Бит в пакете из {SHOTS} снимков', f'{one_shot} \\cdot {SHOTS}',
         packet_bits, 'бит'),
        ('Байты – делим на 8', f'{packet_bits} / 8', packet_bytes, 'байт'),
        ('Кбайты – делим на 1024', f'{packet_bytes} / 1024', packet_kb, 'Кбайт'),
        ('Мбайты – делим ещё раз', f'{packet_kb} / 1024',
         packet_kb / 1024, 'Мбайт'),
    ]


def _number(value):
    """Результат шага для таблицы: целое с разрядами, дробь – через запятую."""
    if isinstance(value, int):
        return _spaced(value)
    return f'{value}'.replace('.', ',')


def _steps_table(steps):
    """Таблица счёта: шаг, что набираем на калькуляторе, что получаем.

    Второй столбец – ровно то, что нажимают, поэтому в нём стоят полные
    числа, а не буквы формулы: переписать выражение с экрана в калькулятор
    ученик должен без подстановок в уме.
    """
    lines = [
        '| Шаг | Что считаем | На калькуляторе | Результат |',
        '| --- | --- | --- | --- |',
    ]
    for i, (name, expr, value, unit) in enumerate(steps, start=1):
        last = '**' if i == len(steps) else ''
        lines.append(
            f'| {i} | {name} | ${expr}$ | {last}{_number(value)}{last} {unit} |'
        )
    return '\n'.join(lines)


def _check():
    """Оба ответа обязаны совпасть с эталонными, а рассказ – с арифметикой.

    Проверяется не только итог, но и то, на что текст разбора опирается
    прямо: что у звука все деления точные (потому разговора об округлении
    там нет), а у картинки последнее деление даёт дробь – ради неё этот
    пример и выбран из банка.
    """
    audio = _audio_steps()
    total_bits = audio[2][2]
    assert total_bits % (8 * 1024) == 0, (
        'разбор утверждает, что у звука деление точное'
    )
    assert audio[-1][2] == AUDIO_ANSWER, (
        f'звук: {audio[-1][2]} вместо {AUDIO_ANSWER}'
    )

    image = _image_steps()
    packet_kb = image[4][2]
    assert packet_kb % 1024 != 0, (
        'разбор утверждает, что у картинки на последнем делении остаётся дробь'
    )
    assert int(image[-1][2]) == IMAGE_ANSWER, (
        f'картинка: {image[-1][2]} вместо {IMAGE_ANSWER}'
    )
    assert _bits_per_pixel() == 14, 'палитра 16 384 – это 14 бит на пиксель'

    # Пример про округление вверх обязан оставаться примером: логарифм дробный,
    # а бит на один меньше палитре действительно не хватает.
    example_bits = _bits_for(EXAMPLE_PALETTE)
    assert not math.log2(EXAMPLE_PALETTE).is_integer(), (
        f'палитра {EXAMPLE_PALETTE} – степень двойки, округлять в примере нечего'
    )
    assert 2 ** (example_bits - 1) < EXAMPLE_PALETTE <= 2 ** example_bits, (
        f'{example_bits} бит не та граница для палитры {EXAMPLE_PALETTE}'
    )


