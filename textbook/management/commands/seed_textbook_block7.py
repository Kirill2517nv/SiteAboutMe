def _replace_blocks(article, blocks):
    article.blocks.all().delete()
    for b in blocks:
        ArticleBlock.objects.create(article=article, **b)


def _self_check(slug, title, description, questions):
    """Создаёт (или переиспользует) тест самопроверки с вопросами."""
    quiz, _ = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not quiz.is_self_check:
        quiz.is_self_check = True
        quiz.save(update_fields=['is_self_check'])

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                points=1,
            )
            for choice_text, is_correct in q.get('choices', []):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
    return quiz


def _plural(n, one, few, many):
    """Форма существительного при числительном: 1 бит, 2 бита, 5 битов."""
    tail = abs(n) % 100
    if 11 <= tail <= 14:
        return many
    tail %= 10
    if tail == 1:
        return one
    if 2 <= tail <= 4:
        return few
    return many


def _alphabet_bits_trace():
    """Трасса подбора минимального числа битов на символ алфавита (урок 7.1).

    Виджет loop-trace ничего не считает сам — повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.
    """
    code = [
        'N = 33',
        'b = 1',
        'while 2 ** b < N:',
        '    b = b + 1',
        'print(b)',
    ]
    var_names = ['N', 'b', '2 ** b']

    def state(n, b):
        return {'N': n, 'b': b, '2 ** b': (2 ** b) if b is not None else None}

    N = 33
    b = None
    steps = [{
        'line': 1, 'vars': state(N, b),
        'note': 'Мощность алфавита: 33 русские буквы. Ищем, сколько битов нужно на одну.',
    }]
    b = 1
    steps.append({
        'line': 2, 'vars': state(N, b),
        'note': 'Начинаем с одного бита — минимума, который вообще бывает.',
    })
    while True:
        combos = 2 ** b
        cond = combos < N
        bits_word = _plural(b, 'бит', 'бита', 'битов')
        verb = 'даёт' if bits_word == 'бит' else 'дают'
        combo_word = _plural(combos, 'комбинацию', 'комбинации', 'комбинаций')
        short = N - combos
        steps.append({
            'line': 3, 'vars': state(N, b), 'check': cond,
            'note': (
                f'{b} {bits_word} {verb} 2^{b} = {combos} {combo_word}, а символов '
                f'{N}: не хватает ещё '
                f'{short} {_plural(short, "комбинации", "комбинаций", "комбинаций")}. '
                'Добавляем бит.' if cond
                else (
                    f'{b} {bits_word} {verb} 2^{b} = {combos} {combo_word} — этого '
                    f'хватает на все {N} '
                    f'{_plural(N, "символ", "символа", "символов")}. Цикл закончился.'
                )
            ),
        })
        if not cond:
            break
        b += 1
        steps.append({
            'line': 4, 'vars': state(N, b),
            'note': f'Ещё один бит — число комбинаций удвоилось: теперь их {2 ** b}.',
        })
    steps.append({
        'line': 5, 'vars': state(N, b), 'out': str(b),
        'note': (
            f'Ответ: {b} {_plural(b, "бит", "бита", "битов")} на символ. Лишних '
            f'комбинаций при этом остаётся {2 ** b} − {N} = {2 ** b - N} — цена '
            'равномерного кода.'
        ),
    })
    return {'code': code, 'vars': var_names, 'steps': steps}


# Символы записаны escape-последовательностями намеренно: эмодзи и кириллица
# в исходнике легко теряются при редактировании файла инструментами.
SAMPLE_TEXT = 'AЖ\U0001f600'   # A, Ж, «улыбка» — 1 + 2 + 4 байта


def _utf8_scan_trace():
    """Трасса разбора потока байтов UTF-8 на символы (урок 7.3).

    Виджет loop-trace ничего не считает сам — повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.
    """
    data = list(SAMPLE_TEXT.encode('utf-8'))
    code = [
        "data = '" + SAMPLE_TEXT + "'.encode('utf-8')",
        'i = 0',
        'while i < len(data):',
        '    b = data[i]',
        '    if   b < 0x80:  n = 1',
        '    elif b < 0xE0:  n = 2',
        '    elif b < 0xF0:  n = 3',
        '    else:           n = 4',
        "    print(data[i:i + n].decode('utf-8'))",
        '    i = i + n',
    ]
    var_names = ['i', 'b', 'n']

    def state(i, b, n):
        return {
            'i': i,
            'b': None if b is None else f'0x{b:02X} = {b:08b}',
            'n': n,
        }

    def hexes(start, count):
        return ' '.join(f'{x:02X}' for x in data[start:start + count])

    branch = {
        1: (5, 'Старший бит нулевой — сработал шаблон 0xxxxxxx, символ '
               'однобайтовый. Это ровно тот же байт, что был бы в ASCII.'),
        2: (6, 'Байт не меньше 0x80 — значит, не ASCII; и меньше 0xE0 — значит, '
               'начинается с битов 110. Две единицы до нуля: символ занимает '
               'два байта.'),
        3: (7, 'Байт попал между 0xE0 и 0xEF — начинается с битов 1110. Три '
               'единицы: символ занимает три байта.'),
        4: (8, 'Байт не меньше 0xF0 — начинается с битов 11110. Четыре единицы: '
               'символ занимает четыре байта, это максимум для UTF-8.'),
    }

    steps = [{
        'line': 1, 'vars': state(None, None, None),
        'note': (
            'В data легли семь байтов: ' + hexes(0, len(data)) + '. Символов в '
            'строке три, и границы между ними программе предстоит найти самой — '
            'никаких разделителей в ленте нет.'
        ),
    }]

    i = 0
    b = None
    n = None
    steps.append({
        'line': 2, 'vars': state(i, b, n),
        'note': 'Идём по байтам слева направо, начиная с нулевого.',
    })

    while True:
        cond = i < len(data)
        steps.append({
            'line': 3, 'vars': state(i, b, n), 'check': cond,
            'note': (
                f'Разобрано {i} из {len(data)} байтов — работа не закончена.'
                if cond else (
                    'Байты кончились, цикл завершился: семь байтов превратились '
                    'в три символа. Обратите внимание, что алгоритму ни разу не '
                    'понадобилось помнить, что было в ленте раньше, — каждый '
                    'байт сам сообщает свою роль.'
                )
            ),
        })
        if not cond:
            break

        b = data[i]
        steps.append({
            'line': 4, 'vars': state(i, b, n),
            'note': (
                f'Берём байт № {i}. Его старшие биты и есть дорожный знак: по ним '
                'видно, сколько байтов занимает символ.'
            ),
        })

        if b < 0x80:
            n = 1
        elif b < 0xE0:
            n = 2
        elif b < 0xF0:
            n = 3
        else:
            n = 4
        line, note = branch[n]
        steps.append({'line': line, 'vars': state(i, b, n), 'check': True, 'note': note})

        char = bytes(data[i:i + n]).decode('utf-8')
        steps.append({
            'line': 9, 'vars': state(i, b, n), 'out': char,
            'note': (
                f'Забираем {n} ' + _plural(n, 'байт', 'байта', 'байтов') + ' подряд ('
                + hexes(i, n) + f') и декодируем — получился символ «{char}».'
            ),
        })

        i += n
        steps.append({
            'line': 10, 'vars': state(i, b, n),
            'note': (
                f'Сдвигаем i сразу на {n} — на первый байт следующего символа. '
                'Байты-продолжения (те, что начинаются с 10) отдельно смотреть '
                'не пришлось: ведущий байт уже сказал, сколько их будет.'
            ),
        })

    return {'code': code, 'vars': var_names, 'steps': steps}


FANO_TABLE = [('А', '0'), ('Б', '10'), ('В', '110'), ('Г', '111')]
FANO_TAPE = '0110100111'


def _fano_decode_trace():
    """Трасса декодирования префиксного кода по одному биту (урок 7.4).

    Виджет loop-trace ничего не считает сам — повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.
    """
    table = {code: sym for sym, code in FANO_TABLE}
    code = [
        "table = {'0': 'А', '10': 'Б', '110': 'В', '111': 'Г'}",
        "tape = '" + FANO_TAPE + "'",
        "buf = ''",
        "out = ''",
        'for bit in tape:',
        '    buf = buf + bit',
        '    if buf in table:',
        '        out = out + table[buf]',
        "        buf = ''",
        'print(out)',
    ]
    var_names = ['bit', 'buf', 'out']

    def state(bit, buf, out):
        return {
            'bit': None if bit is None else f"'{bit}'",
            'buf': None if buf is None else f"'{buf}'",
            'out': None if out is None else f"'{out}'",
        }

    steps = [
        {
            'line': 1, 'vars': state(None, None, None),
            'note': (
                'Таблица перевёрнута: ключ — кодовое слово, значение — символ. '
                'Декодеру нужно искать именно по коду.'
            ),
        },
        {
            'line': 2, 'vars': state(None, None, None),
            'note': (
                'Лента из десяти битов. Разделителей в ней нет, границы символов '
                'предстоит найти самому — ровно как в уроке 7.3 с байтами UTF-8.'
            ),
        },
        {
            'line': 3, 'vars': state(None, '', None),
            'note': 'buf — цепочка битов, накопленная с прошлого найденного символа.',
        },
        {
            'line': 4, 'vars': state(None, '', ''),
            'note': 'out — то, что уже расшифровано.',
        },
    ]

    buf = ''
    out = ''
    for bit in FANO_TAPE:
        steps.append({
            'line': 5, 'vars': state(bit, buf, out),
            'note': f'Берём следующий бит ленты: {bit}.',
        })

        buf = buf + bit
        steps.append({
            'line': 6, 'vars': state(bit, buf, out),
            'note': f'Дописываем его к накопленной цепочке — стало {buf}.',
        })

        found = buf in table
        if found:
            note = (
                f'Цепочка {buf} нашлась в таблице. Колебаться не о чем: раз условие '
                'Фано выполняется, ни одно кодовое слово не является началом другого, '
                'а значит, продолжения у этой цепочки быть не может.'
            )
        else:
            note = (
                f'Цепочки {buf} в таблице нет — символ ещё не кончился. Возвращаться '
                'назад не придётся, просто читаем дальше.'
            )
        steps.append({'line': 7, 'vars': state(bit, buf, out), 'check': found, 'note': note})

        if found:
            sym = table[buf]
            out = out + sym
            steps.append({
                'line': 8, 'vars': state(bit, buf, out),
                'note': f'Это буква {sym} — дописываем её к ответу.',
            })
            buf = ''
            steps.append({
                'line': 9, 'vars': state(bit, buf, out),
                'note': 'Копилку очищаем: следующий символ начинается с чистого листа.',
            })

    steps.append({
        'line': 10, 'vars': state(None, buf, out), 'out': out,
        'note': (
            'Лента разобрана за один проход слева направо: ни одного возврата '
            'назад, ни одного выбора между вариантами. Именно это и покупается '
            'условием Фано.'
        ),
    })

    return {'code': code, 'vars': var_names, 'steps': steps}


HUFF_WORD = 'АБРАКАДАБРА'


def _huffman(word):
    """Код Хаффмана для слова: частоты, таблица кодов, лента битов (урок 7.5).

    Правило разрешения ничьих повторяет виджет huffman-tree: очередь
    сортируется по (частота, порядок появления), объединяются два первых
    узла, более лёгкий становится левым потомком. Благодаря этому таблица
    в тексте урока совпадает с той, что виджет покажет ученику.
    """
    order = []
    freq = {}
    for ch in word:
        if ch not in freq:
            freq[ch] = 0
            order.append(ch)
        freq[ch] += 1

    born = 0
    nodes = []
    for ch in order:
        nodes.append({'w': freq[ch], 'sym': ch, 'born': born, 'kids': None})
        born += 1

    while len(nodes) > 1:
        nodes.sort(key=lambda n: (n['w'], n['born']))
        left, right = nodes[0], nodes[1]
        nodes = nodes[2:] + [{
            'w': left['w'] + right['w'], 'sym': None,
            'born': born, 'kids': (left, right),
        }]
        born += 1

    codes = {}

    def walk(node, path):
        if node['sym'] is not None:
            codes[node['sym']] = path or '0'
            return
        walk(node['kids'][0], path + '0')
        walk(node['kids'][1], path + '1')

    walk(nodes[0], '')

    # частоты — по убыванию, как в таблице урока
    table = sorted(((ch, freq[ch]) for ch in order), key=lambda p: (-p[1], order.index(p[0])))
    tape = ''.join(codes[ch] for ch in word)
    return {'freq': table, 'codes': codes, 'tape': tape}


