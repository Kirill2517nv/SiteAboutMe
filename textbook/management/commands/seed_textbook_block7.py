FANO_TABLE = [('А', '0'), ('Б', '10'), ('В', '110'), ('Г', '111')]
FANO_TAPE = '0110100111'


def _fano_decode_trace():
    """Трасса декодирования префиксного кода по одному биту (урок 7.4).

    Виджет loop-trace ничего не считает сам – повторяем разбираемый алгоритм
    обычным циклом и складываем полное состояние на каждом шаге.

    Словарей и функций к уроку 7.4 ещё не было, поэтому поиск по таблице
    развёрнут в цепочку if/elif. Номера строк считаются из FANO_TABLE, чтобы
    трасса не разъехалась с листингом при правке таблицы.
    """
    code = [
        "tape = '" + FANO_TAPE + "'",
        "buf = ''",
        "out = ''",
        'for bit in tape:',
        '    buf = buf + bit',
    ]
    cmp_line = {}
    for i, (sym, word) in enumerate(FANO_TABLE):
        cmp_line[word] = len(code) + 1      # строка со сравнением
        code.append('    ' + ('if' if i == 0 else 'elif') + " buf == '" + word + "':")
        code.append("        out = out + '" + sym + "'")
        code.append("        buf = ''")
    code.append('print(out)')

    table = dict((word, sym) for sym, word in FANO_TABLE)
    first_cmp = cmp_line[FANO_TABLE[0][1]]
    last_line = len(code)
    var_names = ['bit', 'buf', 'out']

    def state(bit, buf, out):
        return {
            'bit': None if bit is None else f"'{bit}'",
            'buf': None if buf is None else f"'{buf}'",
            'out': None if out is None else f"'{out}'",
        }

    steps = [
        {
            'line': 1, 'vars': state(None, None, None),
            'note': (
                'Лента из десяти битов. Разделителей в ней нет, границы символов '
                'предстоит найти самому – ровно как в уроке 7.3 с байтами UTF-8.'
            ),
        },
        {
            'line': 2, 'vars': state(None, '', None),
            'note': 'buf – цепочка битов, накопленная с прошлого найденного символа.',
        },
        {
            'line': 3, 'vars': state(None, '', ''),
            'note': 'out – то, что уже расшифровано.',
        },
    ]

    buf = ''
    out = ''
    for bit in FANO_TAPE:
        steps.append({
            'line': 4, 'vars': state(bit, buf, out),
            'note': f'Берём следующий бит ленты: {bit}.',
        })

        buf = buf + bit
        steps.append({
            'line': 5, 'vars': state(bit, buf, out),
            'note': f'Дописываем его к накопленной цепочке – стало {buf}.',
        })

        sym = table.get(buf)
        if sym is None:
            # Ни одно сравнение не сработало – показываем первое из цепочки.
            steps.append({
                'line': first_cmp, 'vars': state(bit, buf, out), 'check': False,
                'note': (
                    f'Цепочка {buf} не совпала ни с одним кодом – символ ещё не '
                    'кончился. Возвращаться назад не придётся, просто читаем дальше.'
                ),
            })
        else:
            line = cmp_line[buf]
            steps.append({
                'line': line, 'vars': state(bit, buf, out), 'check': True,
                'note': (
                    f'Цепочка {buf} совпала с кодом буквы {sym}. Колебаться не о чем: '
                    'раз условие Фано выполняется, ни одно кодовое слово не является '
                    'началом другого, а значит, продолжения у этой цепочки быть не может.'
                ),
            })
            out = out + sym
            steps.append({
                'line': line + 1, 'vars': state(bit, buf, out),
                'note': f'Дописываем букву {sym} к ответу.',
            })
            buf = ''
            steps.append({
                'line': line + 2, 'vars': state(bit, buf, out),
                'note': 'Копилку очищаем: следующий символ начинается с чистого листа.',
            })

    steps.append({
        'line': last_line, 'vars': state(None, buf, out), 'out': out,
        'note': (
            'Лента разобрана за один проход слева направо: ни одного возврата '
            'назад, ни одного выбора между вариантами. Именно это и покупается '
            'условием Фано.'
        ),
    })

    return {'code': code, 'vars': var_names, 'steps': steps}


HUFF_WORD = 'АБРАКАДАБРА'


def _huffman(word):
    """Код Хаффмана для слова: частоты, таблица кодов, лента битов (урок 7.5).

    Правило разрешения ничьих повторяет виджет huffman-tree: очередь
    сортируется по (частота, порядок появления), объединяются два первых
    узла, более лёгкий становится левым потомком. Благодаря этому таблица
    в тексте урока совпадает с той, что виджет покажет ученику.
    """
    order = []
    freq = {}
    for ch in word:
        if ch not in freq:
            freq[ch] = 0
            order.append(ch)
        freq[ch] += 1

    born = 0
    nodes = []
    for ch in order:
        nodes.append({'w': freq[ch], 'sym': ch, 'born': born, 'kids': None})
        born += 1

    while len(nodes) > 1:
        nodes.sort(key=lambda n: (n['w'], n['born']))
        left, right = nodes[0], nodes[1]
        nodes = nodes[2:] + [{
            'w': left['w'] + right['w'], 'sym': None,
            'born': born, 'kids': (left, right),
        }]
        born += 1

    codes = {}

    def walk(node, path):
        if node['sym'] is not None:
            codes[node['sym']] = path or '0'
            return
        walk(node['kids'][0], path + '0')
        walk(node['kids'][1], path + '1')

    walk(nodes[0], '')

    # частоты – по убыванию, как в таблице урока
    table = sorted(((ch, freq[ch]) for ch in order), key=lambda p: (-p[1], order.index(p[0])))
    tape = ''.join(codes[ch] for ch in word)
    return {'freq': table, 'codes': codes, 'tape': tape}


def _canonical(codes):
    """Канонический код Хаффмана: коды, восстановленные по одним длинам (урок 7.5).

    Правило то же, что в JPEG и DEFLATE: символы сортируются по (длина кода,
    сам символ), первому достаётся код из нулей нужной длины, каждый следующий –
    предыдущий плюс единица, а при переходе к большей длине результат
    дописывается нулями справа. Длины не меняются, поэтому запись выходит
    ровно такой же длины, как у кода, снятого с дерева.
    """
    order = sorted(codes, key=lambda sym: (len(codes[sym]), sym))
    out = {}
    value = 0
    prev_len = len(codes[order[0]])
    for i, sym in enumerate(order):
        length = len(codes[sym])
        if i:
            value = (value + 1) << (length - prev_len)
        out[sym] = format(value, '0' + str(length) + 'b')
        prev_len = length
    return out


HUFF = _huffman(HUFF_WORD)
CANON = _canonical(HUFF['codes'])

# Проверка на месте: канонический код обязан остаться префиксным и сохранить
# длины кодовых слов – иначе таблица в уроке разойдётся с подсчётом битов.
assert all(len(CANON[s]) == len(HUFF['codes'][s]) for s in CANON)
assert not any(a != b and b.startswith(a) for a in CANON.values() for b in CANON.values())


