def _rating(rows, mode='ok'):
    """Рейтинг: суммы, собеседование и ID, уже упорядоченные.

    Записана так же, как блок `Решение`, и это единственное место, где
    правило порядка записано кодом: таблица трассировки, ответ и все
    неверные ответы «Типичных ошибок» берутся отсюда.

    `mode` – не украшение, а те самые ошибки, ради которых статья написана:
        'ok'      – ключ условия: сумма вместе с собеседованием, при
                    равенстве сумм – большее собеседование, потом меньший ID;
        'no_talk' – собеседование в сумму не входит и только упорядочивает
                    кандидатов с равной суммой (правило задачи про матросов);
        'tie_id'  – при равной сумме смотрим только на ID.
    """
    if mode == 'no_talk':
        people = [(a + b + c, talk, pid) for pid, a, b, c, talk in rows]
    else:
        people = [(a + b + c + talk, talk, pid) for pid, a, b, c, talk in rows]
    people.sort(key=(lambda p: (-p[0], p[2])) if mode == 'tie_id'
                else (lambda p: (-p[0], -p[1], p[2])))
    return people


def _boundary(people, k):
    """Кто зачислен и кто набрал полупроходной балл.

    Граница смотрится по сумме K-го и (K+1)-го. Совпали – группа с этой
    суммой не влезла целиком: эта сумма полупроходная, а зачислены все, у
    кого больше. Не совпали – полупроходного балла нет, зачислены все, у
    кого не меньше, и второе число ответа равно нулю.
    """
    edge = people[k - 1][0]
    if people[k][0] == edge:
        return ([p for p in people if p[0] > edge],
                [p for p in people if p[0] == edge])
    return [p for p in people if p[0] >= edge], []


def _solve(rows, k, mode='ok'):
    """Оба числа ответа – тем же правилом, что в блоке `Решение`.

    Поверх режимов `_rating` есть ещё два, и каждый добавляет по одной
    ошибке из «Типичных ошибок»:
        'kth'      – первым числом идёт ID K-го, последнего, кому хватило
                     места, а не последнего с проходным баллом;
        'left_out' – вторым числом идут только те, кому мест не хватило.
    """
    people = _rating(rows, mode)
    passed, semi = _boundary(people, k)
    first = passed[-1][2]
    if mode == 'kth':
        first = people[k - 1][2]
    count = len(semi)
    # Полупроходного балла нет – считать «оставшихся без места» не от чего.
    if mode == 'left_out' and semi:
        count -= k - len(passed)
    return first, count


def _bank_rows():
    """Кандидаты и число мест из файла задачи, или None.

    Статья публикуется и на машине без media (каталог приезжает rsync-ом
    отдельно), поэтому отсутствие файла – не ошибка: проверка по нему просто
    не выполняется.
    """
    path = Path(settings.MEDIA_ROOT) / DATA_PATH
    if not path.exists():
        return None
    with path.open(encoding='utf-8') as handle:
        _, k = map(int, handle.readline().split())
        rows = [tuple(map(int, line.split())) for line in handle if line.strip()]
    return rows, k


def _toy_block():
    """Пример данных из условия – тем же текстом, что лежит в файле.

    Собирается из TOY, а не пишется руками: пример в статье и пример,
    на котором считает `_check()`, обязаны быть одним и тем же.
    """
    lines = [f'{len(TOY)} {TOY_K}']
    lines += [f'{pid} {a} {b} {c} {talk}' for pid, a, b, c, talk in TOY]
    return '\n'.join(lines)


def _toy_table():
    """Рейтинг примера из условия – таблица для блока 3.

    Строки идут в том порядке, который считает `_solve`, а столбец «Итог»
    подписан по границе списка: выше неё зачислены, на ней – полупроходной
    балл, ниже – не прошли.

    Строку с ответом выделяем `<mark>` в первой ячейке: markdown-таблица не
    умеет повесить класс на `<tr>`, и правило `tr:has(mark) td` в
    static/css/textbook-article.css красит по нему всю строку. Сам `<mark>`
    там обесцвечен, так что в ячейке он ничего не рисует.
    """
    people = _rating(TOY)
    edge = people[TOY_K - 1][0]        # сумма на последнем месте – полупроходной балл
    lines = [
        '| Место | ID | Сумма | Собеседование | Итог |',
        '| --- | --- | --- | --- | --- |',
    ]
    for place, (total, talk, pid) in enumerate(people, 1):
        if total > edge:
            outcome = 'зачислен'
        elif total == edge:
            outcome = 'полупроходной'
        else:
            outcome = 'ниже проходного'
        number = f'<mark>{place}</mark>' if pid == TOY_ANSWER[0] else str(place)
        lines.append(f'| {number} | {pid} | {total} | {talk} | {outcome} |')
    return '\n'.join(lines)


def _check():
    """Числа разбора обязаны совпасть с примером из условия и с ответом kompege.

    Поменяется условие или файл – команда упадёт здесь, вместо того чтобы
    оставить в опубликованной статье разбор, доказывающий неверный ответ.
    """
    printed = run_solution(SOLUTION, DATA_FILE, _toy_block() + '\n')
    assert printed == [str(x) for x in TOY_ANSWER], (
        f'программа из блока «Решение» печатает на примере из условия '
        f'{printed} вместо {TOY_ANSWER}'
    )

    people = _rating(TOY)
    order = [p[2] for p in people]
    assert order == TOY_ORDER, (
        f'на примере из условия рейтинг получился {order} вместо {TOY_ORDER} – '
        'блок «Типовой пример» разобран не тем ключом сортировки'
    )
    sums = {pid: total for total, talk, pid in people}
    assert sums == {10: 302, 6: 279, 7: 240, 11: 240, 4: 240, 2: 238}, (
        f'суммы примера получились {sums}, а не 302, 279, 240 и 238 – условие '
        'называет другие баллы'
    )
    passed, semi = _boundary(people, TOY_K)
    assert (passed[-1][2], len(semi)) == TOY_ANSWER, (
        f'пример из условия даёт ответ {(passed[-1][2], len(semi))} вместо '
        f'{TOY_ANSWER} – абзац под таблицей обещает другое'
    )
    assert min(p[0] for p in passed) == 279 and semi[0][0] == 240, (
        f'проходной балл примера – {min(p[0] for p in passed)}, полупроходной '
        f'– {semi[0][0]}, а условие называет 279 и 240'
    )

    bank = _bank_rows()
    if bank is None:
        return
    rows, k = bank

    assert len(rows) == N and k == K, (
        f'в файле {len(rows)} кандидатов и {k} мест, а статья обещает {N} и '
        f'{K} – таблицы в ней поверят этому'
    )
    data = (Path(settings.MEDIA_ROOT) / DATA_PATH).read_text(encoding='utf-8')
    printed = run_solution(SOLUTION, DATA_FILE, data)
    assert printed == [str(x) for x in ANSWER], (
        f'программа из блока «Решение» печатает на файле {printed} вместо '
        f'ответа kompege {ANSWER}'
    )

    people = _rating(rows)
    passed, semi = _boundary(people, K)
    assert (people[K - 1][0], people[K][0]) == (EDGE, EDGE), (
        f'на месте {K} и на следующем за ним суммы {people[K - 1][0]} и '
        f'{people[K][0]}, а не {EDGE} – в блоке «Как рассуждать» назван '
        'другой полупроходной балл'
    )
    assert len(passed) == ABOVE, (
        f'больше {EDGE} набрали {len(passed)} кандидатов, а не {ABOVE} – '
        'в статье названо другое число'
    )
    assert K - len(passed) == PLACES_LEFT, (
        f'на группу с суммой {EDGE} осталось {K - len(passed)} мест, а не '
        f'{PLACES_LEFT} – в статье названо другое число'
    )
    assert len(semi) == ANSWER[1], (
        f'полупроходной балл набрали {len(semi)} кандидатов, а не '
        f'{ANSWER[1]} – второе число ответа взято не из решения'
    )
    assert min(p[0] for p in passed) == PASSING, (
        f'проходной балл – минимальная сумма среди зачисленных – равен '
        f'{min(p[0] for p in passed)}, а не {PASSING}: в статье назван другой '
        'проходной балл'
    )
    assert _solve(rows, k) == ANSWER, (
        f'разбор даёт {_solve(rows, k)} вместо ответа kompege {ANSWER}: '
        'решение в блоке «Решение» решает не ту задачу'
    )

    # Режимы «Типичных ошибок» на том же файле: разъедутся – статья назовёт
    # числа, которых решение не даёт.
    assert _solve(rows, k, 'no_talk') == WRONG_NO_TALK, (
        f'«собеседование не в сумме» даёт {_solve(rows, k, "no_talk")} вместо '
        f'{WRONG_NO_TALK} – первая ошибка в списке называет другое число'
    )
    assert _solve(rows, k, 'tie_id')[0] == WRONG_TIE_ID, (
        f'«при равной сумме смотрим только на ID» даёт первым числом '
        f'{_solve(rows, k, "tie_id")[0]} вместо {WRONG_TIE_ID} – вторая '
        'ошибка в списке называет другое число'
    )
    assert _solve(rows, k, 'kth')[0] == WRONG_KTH, (
        f'ID последнего, кому хватило места, – {_solve(rows, k, "kth")[0]}, '
        f'а не {WRONG_KTH} – третья ошибка в списке называет другое число'
    )
    assert _solve(rows, k, 'left_out')[1] == WRONG_LEFT_OUT, (
        f'оставшихся без места – {_solve(rows, k, "left_out")[1]}, а не '
        f'{WRONG_LEFT_OUT} – четвёртая ошибка в списке называет другое число'
    )


class Command(BaseCommand):
    help = 'Наполняет разбор задания 26 ЕГЭ: рейтинг и полупроходной балл'

    @transaction.atomic
    def handle(self, *args, **options):
        _check()

        # Абзац со ссылкой на файл; без файла его просто нет, но молча это
        # не проходит – иначе разбор останется без данных, и заметит это
        # ученик, а не тот, кто выкладывал.
        bank_file, bank_name = _bank_file_link()
        if bank_file:
            if bank_name != DATA_FILE:
                self.stdout.write(self.style.WARNING(
                    f'Файл скачивается как {bank_name}, а код разбора '
                    f'открывает {DATA_FILE}: поправьте DATA_FILE, иначе '
                    'решение из статьи не запустится на скачанном файле.'
                ))
            file_note = (
                f'**Файл с данными:** {bank_file} – {N} '
                f'строк{plural(N, ",а,")}: строка на каждого кандидата. '
                'Положите его рядом со скриптом, **не переименовывая**: код '
                f'ниже открывает `{DATA_FILE}` – то самое имя, под которым '
                'файл скачивается.\n'
                '\n'
            )
        else:
            file_note = ''
            self.stdout.write(self.style.WARNING(
                f'Вопрос {QUESTION_ID} или файл к нему не найден – разбор '
                'опубликован без ссылки на данные. Импортируйте банк '
                '(load_ege fixtures/bank-26.json) и прогоните команду снова.'
            ))

        toy_people = _rating(TOY)
        toy_passed, toy_semi_group = _boundary(toy_people, TOY_K)
        toy_order = ' '.join(str(p[2]) for p in toy_people)
        toy_passing = min(p[0] for p in toy_passed)
        toy_semi = toy_semi_group[0][0]
