def _self_check(slug, title, description, questions, replace=True):
    """Создаёт (или обновляет) тест самопроверки с вопросами.

    `replace=True` пересоздаёт вопросы – это нужно при переписывании урока,
    иначе на сайте остались бы старые формулировки. Если по тесту уже есть
    ответы учеников, замена не делается: удалять вопросы каскадом вместе с
    чужими ответами мы не будем.

    Поддерживаемые ключи вопроса: type, text, title, choices,
    correct_text_answer, alternative_answers, hint,
    test_cases [(stdin, stdout)].
    """
    quiz, created = Quiz.objects.get_or_create(
        slug=slug,
        defaults={
            'title': title,
            'description': description,
            'is_self_check': True,
            'max_attempts': 0,
            'quiz_type': 'standard',
        },
    )
    if not created:
        quiz.title, quiz.description, quiz.is_self_check = title, description, True
        quiz.save(update_fields=['title', 'description', 'is_self_check'])

    if replace and quiz.questions.exists():
        if not UserAnswer.objects.filter(question__quiz=quiz).exists():
            quiz.questions.all().delete()

    if quiz.questions.count() == 0:
        for q in questions:
            question = Question.objects.create(
                quiz=quiz,
                question_type=q['type'],
                title=q.get('title', ''),
                text=q['text'],
                correct_text_answer=q.get('correct_text_answer', ''),
                alternative_answers=q.get('alternative_answers'),
                hint=q.get('hint', ''),
                points=1,
            )
            for choice_text, is_correct in _shuffle_choices(q['text'], q.get('choices', [])):
                Choice.objects.create(question=question, text=choice_text, is_correct=is_correct)
            for stdin, stdout in q.get('test_cases', []):
                TestCase.objects.create(question=question, input_data=stdin, output_data=stdout)
    else:
        # Вопросы уже решали – пересоздать нельзя, но условия обновить можно.
        _sync_question_texts(quiz, questions)
    return quiz


def _tenth_binary_trace(iterations=12):
    """Готовая трасса для loop-trace: перевод 0,1 в двоичную дробь.

    Алгоритм обратный делению уголком из урока 2.5: дробную часть умножаем
    на 2 и собираем целые части. Считаем парой целых (num/den), а не
    вещественным числом: у float одна десятая уже округлена до конечной
    двоичной дроби, и цикл на нём оборвался бы через 55 шагов – ровно то
    расхождение, которое урок и разбирает. На целых дробь остаётся точной,
    и повтор состояния (то есть период) виден честно.
    """
    code = [
        'num, den = 1, 10        # точная дробь 1/10, без вещественных чисел',
        "bits = ''",
        'for step in range(%d):' % iterations,
        '    num = num * 2',
        '    bit = num // den',
        '    bits = bits + str(bit)',
        '    num = num - bit * den',
    ]

    num, den = 1, 10
    bits = ''
    steps = [
        dict(line=1, vars={'num': num}, note=(
            'Одну десятую держим парой целых чисел: если взять float, '
            'округление влезет в сам эксперимент.'
        )),
        dict(line=2, vars={'num': num, 'bits': bits}),
    ]

    seen = {num: 0}          # дробная часть → номер итерации, где она была
    cycle_reported = False
    bit = None               # на первой итерации переменной ещё нет

    for it in range(1, iterations + 1):
        num = num * 2
        note = None
        if it == 1:
            note = 'Умножение на 2 сдвигает запятую на один разряд вправо.'
        # Состояние в шаге всегда полное, поэтому bit с прошлой итерации
        # никуда не девается – прочерк стоит только до первого присваивания.
        state = {'num': num, 'bits': bits}
        if bit is not None:
            state['bit'] = bit
        steps.append(dict(line=4, vars=state, note=note))

        bit = num // den
        note = None
        if bit == 1 and '1' not in bits:
            note = 'Первая единица: 16 // 10 = 1. Это четвёртый разряд после запятой.'
        steps.append(dict(line=5, vars={'num': num, 'bit': bit, 'bits': bits}, note=note))

        bits = bits + str(bit)
        steps.append(dict(line=6, vars={'num': num, 'bit': bit, 'bits': bits}))

        num = num - bit * den
        note = None
        if num in seen and not cycle_reported:
            cycle_reported = True
            note = (
                'Дробная часть снова равна %d/10 – точно как после итерации %d. '
                'Состояние повторилось, значит цифры дальше идут по кругу: '
                'период 0011 без конца.' % (num, seen[num])
            )
        elif it == iterations:
            note = (
                'Двенадцать цифр: 0,%s… – и конца не будет.' % bits
            )
        if num not in seen:
            seen[num] = it
        steps.append(dict(line=7, vars={'num': num, 'bit': bit, 'bits': bits}, note=note))

    return {'code': code, 'vars': ['num', 'bit', 'bits'], 'steps': steps}


