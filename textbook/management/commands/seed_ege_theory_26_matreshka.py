"""Разбор задания 26 ЕГЭ: матрёшка – самая длинная цепочка коробок.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блок «Если спрашивают другое» в скелете не значится, здесь он есть. Сюжет
  один, но спрашивают в нём то наибольшее количество коробок, то самую
  маленькую из них, то самую большую – и от вопроса к вопросу меняется
  направление прохода. Таблица «что в условии → что править» избавляет от
  разбора каждого варианта заново;
* виджета у статьи нет: вся наглядность – цепочка из пяти коробок, и она
  рисуется таблицей трассировки, собранной целиком в Python;
* решение разобрано по шагам: три пары «текст – фрагмент кода», а программа
  целиком склеена из тех же фрагментов (STEP_*). `_check()` запускает её
  саму (`run_solution`) на примере и на файле.

Это вторая статья задания 26: основной разбор – про журнал сервера
(демонстрационный вариант), этот – про задачу из банка kompege.ru. Статью
команда создаёт сама: seed_ege_tasks заводит по одной заглушке на задание, а
второй статьи у номера нет. Отсюда и ORDER больше номера задания – см.
комментарий у константы.

`_greedy` в команде – та же программа, что в блоке `code`, записанная так,
чтобы из неё можно было считать: оба числа ответа, неверные ответы «Типичных
ошибок» и таблица трассировки берутся из неё, а не вписываются руками.
`_check()` сверяет её с примером из условия и с ответом kompege, а если media
на диске нет – хотя бы с примером: статья публикуется и на машине без media.

Условие – задача 21910 банка kompege.ru (fixtures/bank-26.json, external_id
kompege-26-21910, файл данных
media/ege/bank-26/files/bank-26_21910_26_1.txt).
"""
