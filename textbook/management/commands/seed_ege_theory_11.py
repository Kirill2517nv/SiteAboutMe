"""Разбор задания 11 ЕГЭ: объём информации, или сколько байт занимает запись.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блока `code` нет, как в заданиях 1, 4 и 7. Норматив – 3 минуты, и вся
  задача состоит из двух делений с двумя округлениями; программы здесь не
  из чего написать, а перевод условия в переменные отнимает больше времени,
  чем сам счёт на калькуляторе;
* блоков разбора два, а не один, и они решают задачу в разные стороны:
  типовой пример ищет алфавит по известной длине записи, задача из банка –
  длину по известному алфавиту. Приём один, но подстановка идёт то в один
  конец формулы, то в другой, и на одном примере второй ход не виден;
* виджета нет: связь «N символов требуют i бит» разобрана в уроке 7.1, на
  который статья ссылается, а здесь её уже применяют к базе данных.

Главная мысль разбора – **в задании два округления, и оба до целого**:
сначала дробь от байт на запись, потом биты на символ в целые байты самой
записи. Направление первого диктует одно слово условия: «не более»
отбрасывает дробь вниз, «более» и «не менее» – вверх. Спутать их и значит
потерять балл: арифметика в обоих примерах одна и та же.

Числа в тексте вычисляются, а не вписываются руками: `_record_bytes` считает
целые байты записи, `_bounds` показывает, между какими целыми легла дробь
(округлённое «78,54» в статье стоять не может – это уже готовый ответ на
вопрос «куда округлять»), а `_check()` сверяет оба итога с ответами ФИПИ и
kompege. Разойдётся – команда упадёт здесь, а не выдаст статью с враньём.

Условие – задание 11 демонстрационного варианта ФИПИ-2027. Второй пример –
задача из fixtures/bank-11.json.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks

SLUG = 'ege-11-obem-informatsii'

# Типовой пример: длина номера, число номеров и лимит памяти под них.
LENGTH = 157                 # символов в серийном номере
NUMBERS = 12_450             # серийных номеров в базе
LIMIT_KB = 955               # Кбайт, отведено «не более»
ALPHABET_ANSWER = 8          # ответ ФИПИ

# Задача из банка – обратный ход: алфавит задан, длину ищем.
DIGITS = 10                  # десятичные цифры в алфавите
SPECIAL = 17                 # плюс столько специальных символов
NUMBERS_2 = 7_564_230        # серийных номеров в базе
REQUIRED_MB = 31             # Мбайт, требуется «более»
LENGTH_ANSWER = 7            # ответ из банка

LIMIT_BYTES = LIMIT_KB * 1024                 # весь отведённый объём в байтах
REQUIRED_BYTES = REQUIRED_MB * 1024 * 1024    # весь требуемый объём в байтах


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _spaced(n):
    """Разряды через пробел: 12 450 читается, 12450 – нет."""
    return f'{n:,}'.replace(',', ' ')


def _bits_per_symbol(alphabet):
    """Минимальное i, при котором 2**i >= alphabet.

    Это первое из двух округлений задания: 27 символов требуют 5 бит, хотя
    log2(27) не целое. Считается целочисленно, а не через логарифм: на
    double log2(32) возвращает 5.0, а log2(2**29) уже может вернуть
    28.999999, и округление вниз даёт ошибку на ровном месте.
    """
    return (alphabet - 1).bit_length()


BITS_PER_SYMBOL = _bits_per_symbol(DIGITS + SPECIAL)   # 5 бит на символ


def _record_bytes(length, bits):
    """Сколько целых байт занимает запись из length символов по bits бит на символ.

    Второе округление задания и главный его подвох: ceil, а не деление
    нацело. 157 символов по 3 бита – это 471 бит, но запись занимает 59
    байт, а не 58: байт недобирать нельзя.
    """
    return -(-length * bits // 8)


def _bounds(numerator, denominator):
    """Целые, между которыми лежит дробь: границы вместо округлённого значения.

    В статье нельзя написать «78,54» – это уже округление, а задание именно
    про то, куда округлять. Границы считаются целочисленно; assert ловит
    случай, когда дробь оказалась целой и разговор об округлении потерял бы
    смысл.
    """
    low = numerator // denominator
    assert low * denominator != numerator, 'дробь целая – округлять нечего'
    return low, low + 1


def _alphabet_answer():
    """Ответ примера 1: максимальная мощность алфавита, ещё влезающая в лимит.

    Идём по битам вверх и останавливаемся там, где запись перестаёт
    помещаться, – так найденное i максимальное. При i = 2 запись тоже
    влезает, но ответ был бы 4, а не 8: спрашивают максимум.
    """
    per_record = LIMIT_BYTES // NUMBERS
    bits = 1
    while _record_bytes(LENGTH, bits + 1) <= per_record:
        bits += 1
    return 2 ** bits


def _length_answer():
    """Ответ примера 2: минимальная длина записи, дающая требуемый объём.

    Здесь округление в другую сторону: «требуется более» – это не заданный
    объём, а нижняя граница, поэтому берём первую длину, при которой запись
    занимает не меньше требуемых байт. Перебор снизу делает её минимальной
    по построению.
    """
    per_record = -(-REQUIRED_BYTES // NUMBERS_2)
    length = 1
    while _record_bytes(length, BITS_PER_SYMBOL) < per_record:
        length += 1
    return length


def _choice_table():
    """Таблица подбора i: считает то же, что делает `_alphabet_answer()`.

    Показаны все варианты подряд – видно, что при i = 1 и i = 2 номер тоже
    помещается, и выбор делается не по первому подходящему, а по последнему.
    """
    per_record = LIMIT_BYTES // NUMBERS
    best = _bits_per_symbol(ALPHABET_ANSWER)
    lines = [
        f'| Бит на символ $i$ | Бит на номер ${LENGTH} \\cdot i$ | '
        f'Байт на номер | Влезает ли в {per_record} байт |',
        '| --- | --- | --- | --- |',
    ]
    for bits in range(1, best + 2):
        record = _record_bytes(LENGTH, bits)
        verdict = 'да' if record <= per_record else 'нет'
        if bits == best:
            verdict = '**да – это максимум**'
        lines.append(f'| {bits} | {LENGTH * bits} | {record} | {verdict} |')
    return '\n'.join(lines)


def _check():
    """Ответы и промежуточные числа обязаны совпасть с эталонными.

    Проверяется не только итог, но и то, на что текст разбора опирается
    прямо: что при i = 4 номер перестаёт помещаться, а длина 6 не дотягивает
    до требуемого объёма. Иначе статья объясняла бы неверный шаг.
    """
    per_record = LIMIT_BYTES // NUMBERS
    assert _alphabet_answer() == ALPHABET_ANSWER, (
        f'пример 1: {_alphabet_answer()} вместо {ALPHABET_ANSWER}'
    )
    best = _bits_per_symbol(ALPHABET_ANSWER)
    assert _record_bytes(LENGTH, best) <= per_record, 'i = 3 обязан влезать'
    assert _record_bytes(LENGTH, best + 1) > per_record, 'i = 4 обязан не влезать'
    _bounds(LIMIT_BYTES, NUMBERS)

    assert BITS_PER_SYMBOL == 5, 'алфавит 10 + 17 = 27 требует 5 бит'
    per_record_2 = -(-REQUIRED_BYTES // NUMBERS_2)
    assert _length_answer() == LENGTH_ANSWER, (
        f'пример 2: {_length_answer()} вместо {LENGTH_ANSWER}'
    )
    assert _record_bytes(LENGTH_ANSWER - 1, BITS_PER_SYMBOL) < per_record_2, (
        'L = 6 обязан не дотягивать до требуемого объёма'
    )
    assert _record_bytes(LENGTH_ANSWER, BITS_PER_SYMBOL) >= per_record_2
    low_2, high_2 = _bounds(REQUIRED_BYTES, NUMBERS_2)

    # Шаг 3 второго примера выбирает между двумя целыми, подставляя каждое
    # обратно в условие. Обе подстановки напечатаны в статье числами, значит
    # обе обязаны давать заявленный результат.
    assert low_2 * NUMBERS_2 < REQUIRED_BYTES, (
        f'{low_2} байт на номер обязаны не дотягивать до {REQUIRED_MB} Мбайт'
    )
    assert high_2 * NUMBERS_2 > REQUIRED_BYTES, (
        f'{high_2} байт на номер обязаны превышать {REQUIRED_MB} Мбайт'
    )
    assert per_record_2 == high_2, 'на номер уходит верхняя из двух границ'


