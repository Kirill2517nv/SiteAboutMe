"""Разбор задания 17 ЕГЭ: обработка последовательности чисел.

Эталонная статья теории ЕГЭ – по ней пишутся остальные 26. Скелет из семи
блоков описан в docs/ege-theory-brief.md; отступать от него без причины не надо.

Статья-заглушка создаётся командой seed_ege_tasks, здесь она только наполняется
блоками и публикуется.
"""
from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks

SLUG = 'ege-17-obrabotka-posledovatelnosti-chisel'


class Command(BaseCommand):
    help = 'Наполняет разбор задания 17 ЕГЭ'

    @transaction.atomic
    def handle(self, *args, **options):
        article = Article.objects.get(slug=SLUG)
        article.description = (
            'Как читать файл с числами, отбирать элементы по условию и находить '
            'нужный максимум за один проход.'
        )

        replace_blocks(article, [
            dict(order=1, block_type='text', title='Что проверяет задание', content=(
                'Задание 17 – это файл с целыми числами и условие отбора. Обычно '
                'спрашивают две вещи сразу: **сколько** элементов подходят под '
                'условие и **какой максимум** среди них. Ответ – два числа через '
                'пробел.\n'
                '\n'
                '**1 балл, норматив 14 минут.** Это первое задание второй части, '
                'и оно же – самое дешёвое из «программистских». Терять его нельзя: '
                'решается оно почти механически.\n'
                '\n'
                'Что нужно уметь заранее:\n'
                '\n'
                '- прочитать файл в список чисел;\n'
                '- пройти по списку, обращаясь к соседним элементам;\n'
                '- собрать максимум за один проход, без сортировки.\n'
                '\n'
                'Ничего сверх этого в задании 17 не бывает. Вся сложность – '
                'в аккуратном чтении условия.'
            )),

            dict(order=2, block_type='text', title='Типовой пример', content=(
                'В файле содержится последовательность целых положительных чисел. '
                'Рассматриваются все пары различных элементов последовательности, '
                'находящихся на расстоянии не менее 4 друг от друга (разность '
                'индексов не менее 4). Необходимо определить количество таких пар, '
                'для которых произведение элементов делится на 26, и максимальное '
                'произведение среди них.\n'
                '\n'
                '**Входные данные.** Первая строка – количество чисел $N$ '
                '($4 \\le N \\le 1000$). Каждая из следующих $N$ строк содержит '
                'одно натуральное число, не превышающее 10 000.\n'
                '\n'
                '**Пример входных данных:**\n'
                '\n'
                '```\n'
                '6\n'
                '13\n'
                '4\n'
                '5\n'
                '7\n'
                '2\n'
                '26\n'
                '```\n'
                '\n'
                'Разберём пример руками. Нумерация с единицы, расстояние не менее '
                '4 – значит подходят пары (1, 5), (1, 6) и (2, 6):\n'
                '\n'
                '| Пара | Произведение | Делится на 26 |\n'
                '| --- | --- | --- |\n'
                '| (1, 5) | $13 \\cdot 2 = 26$ | да |\n'
                '| (1, 6) | $13 \\cdot 26 = 338$ | да |\n'
                '| (2, 6) | $4 \\cdot 26 = 104$ | да |\n'
                '\n'
                'Ответ: `3 338`.\n'
                '\n'
                'Обратите внимание на пару (1, 6) – её легко не заметить, если '
                'разбирать пример «на глаз» и остановиться на первом подходящем '
                'варианте для каждого элемента. Именно поэтому пары перебирает '
                'программа, а не человек.'
            )),

            dict(order=3, block_type='text', title='Как рассуждать', content=(
                'До того как писать код, надо ответить на три вопроса. Именно на '
                'них теряются баллы – не на синтаксисе.\n'
                '\n'
                '**1. Какие пары перебирать?**\n'
                '\n'
                'В условии сказано «расстояние не менее 4», то есть $j - i \\ge 4$. '
                'Каждый элемент может входить в несколько подходящих пар – в примере '
                'выше первый элемент даёт сразу две. '
                'Это не соседние элементы, значит одним проходом не обойтись – '
                'нужен двойной цикл. При $N \\le 1000$ это до полумиллиона пар, '
                'Python справится за доли секунды.\n'
                '\n'
                'Ловушка: «на расстоянии не менее 4» и «между ними не менее 4 '
                'элементов» – **разные** условия. Во втором случае $j - i \\ge 5$. '
                'Читайте формулировку буквально.\n'
                '\n'
                '**2. Как проверить условие?**\n'
                '\n'
                '«Произведение делится на 26» – это `a * b % 26 == 0`. Не пытайтесь '
                'умничать с разложением на 2 и 13: проверка в лоб короче и её '
                'невозможно испортить.\n'
                '\n'
                '**3. Как искать максимум?**\n'
                '\n'
                'Не собирать все подходящие произведения в список и потом брать '
                '`max` – достаточно одной переменной, которая обновляется по ходу. '
                'Стартовое значение – ноль, потому что числа положительные. Если бы '
                'в условии допускались отрицательные, стартовать надо было бы '
                'с `-float(\'inf\')`, иначе ответ был бы неверным.\n'
                '\n'
                'Порядок действий получается такой: прочитать числа → двойной цикл '
                'по парам с нужным расстоянием → проверка делимости → счётчик и '
                'максимум обновляем в одном месте.'
            )),

            dict(order=4, block_type='code', title='Решение', code_language='python', content=(
                "with open('17.txt') as f:\n"
                "    n = int(f.readline())\n"
                "    a = [int(f.readline()) for _ in range(n)]\n"
                "\n"
                "count = 0\n"
                "best = 0          # числа положительные, поэтому ноль безопасен\n"
                "\n"
                "for i in range(n):\n"
                "    for j in range(i + 4, n):     # расстояние не менее 4\n"
                "        p = a[i] * a[j]\n"
                "        if p % 26 == 0:\n"
                "            count += 1\n"
                "            if p > best:\n"
                "                best = p\n"
                "\n"
                "print(count, best)\n"
            )),

            dict(order=5, block_type='text', title='Если условие другое', content=(
                'Каркас решения не меняется никогда – меняются три места: диапазон '
                'внутреннего цикла, условие отбора и то, что считаем максимумом.\n'
                '\n'
                '| Что в условии | Что править в коде |\n'
                '| --- | --- |\n'
                '| «соседние элементы» | внутренний цикл убрать, идти по `a[i]` и `a[i+1]` |\n'
                '| «между ними не менее 4 элементов» | `range(i + 5, n)` – расстояние на единицу больше |\n'
                '| «сумма делится на 26» | `p = a[i] + a[j]` вместо произведения |\n'
                '| «хотя бы один делится на 13» | `if a[i] % 13 == 0 or a[j] % 13 == 0:` |\n'
                '| «минимальное произведение» | `best = float(\'inf\')`, сравнение `if p < best` |\n'
                '| числа могут быть отрицательными | стартовое `best = -float(\'inf\')` |\n'
                '| «элементы на чётных позициях» | `for i in range(0, n, 2)` |\n'
                '\n'
                'Отдельный случай – когда спрашивают только количество, без '
                'максимума. Тогда переменная `best` не нужна вовсе, а в `print` '
                'уходит одно число. Не выводите лишнее: проверяющая система '
                'сверяет строку целиком.'
            )),

            dict(order=6, block_type='text', title='Типичные ошибки', content=(
                '1. **Перепутан знак в расстоянии.** `range(i + 4, n)` даёт '
                '$j - i \\ge 4$, а `range(i + 3, n)` – уже $\\ge 3$. Проверьте на '
                'примере из условия: если ваш ответ на демо-данных не совпал, '
                'дело почти всегда здесь.\n'
                '2. **Максимум ищется среди всех пар, а не среди подходящих.** '
                'Обновление `best` должно стоять **внутри** `if`, а не рядом с ним.\n'
                '3. **Стартовое значение максимума взято с потолка.** Ноль годится '
                'только для положительных чисел. Если подходящих пар не нашлось '
                'вообще, ноль ещё и окажется в ответе – прочитайте, что требуется '
                'выводить в этом случае.\n'
                '4. **Первая строка файла принята за число последовательности.** '
                'В ней лежит $N$, а не элемент. Лишний элемент сдвинет все индексы.\n'
                '5. **Ответ выведен списком.** `print(count, best)` печатает '
                '`2 104`, а `print([count, best])` – `[2, 104]`. Второе не '
                'засчитают.'
            )),
        ])

        article.is_published = True
        article.save(update_fields=['description', 'is_published'])

        self.stdout.write(self.style.SUCCESS('Готово: разбор задания 17 обновлён и опубликован.'))
