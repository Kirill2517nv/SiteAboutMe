"""Разбор задания 17 ЕГЭ: обработка последовательности чисел.

Скелет – docs/ege-theory-brief.md. Отступления от него осознанные:

* блок «Если условие другое» в скелете не значится, здесь он есть: каркас
  решения у всего номера один, и правят в нём ровно три места – какие пары
  перебираем, что проверяем у элементов и что считаем максимумом. Таблица
  «что в условии → что править» избавляет от разбора каждого варианта заново;
* виджета у статьи нет: показывать нечего – последовательность из десяти тысяч
  чисел не нагляднее строки текста, а таблица разбора игрушечного примера
  собирается целиком в Python.

`_solve` в команде – тот же разбор, что в блоке `code`, записанный так, чтобы
из него можно было считать: игрушечный пример, все неверные ответы «Типичных
ошибок» и оба числа ответа берутся из него, а не вписываются руками. `_check()`
сверяет его с ответом ФИПИ, а если media на диске нет, проверяет хотя бы
игрушечный пример – статья публикуется и на машине без media.

Условие – задание 17 демонстрационного варианта ФИПИ-2027
(fixtures/variant_fipi_demo_2027.json, external_id fipi-demo-2027-17).

Статья-заглушка создаётся командой seed_ege_tasks, здесь она наполняется
блоками и публикуется.
"""
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import transaction

from textbook.models import Article
from textbook.services import replace_blocks

SLUG = 'ege-17-obrabotka-posledovatelnosti-chisel'
MOD = 33                       # делитель из условия
ANSWER = (622, 174933)         # ответ ФИПИ: количество пар и максимальная сумма
MIN_ELEMENT = 8                # минимальный элемент в файле демоварианта
TOTAL = 10000                  # сколько чисел в файле демоварианта
TOY = [40, 12, 71, 9, 100, 5]  # игрушечный пример для разбора руками
TOY_ANSWER = (3, 105)
WRONG_AND = (12, 144886)       # если «хотя бы один» прочитан как «оба»
WRONG_ELEMENT = (2, 56829)     # если сравнивают сам элемент, а не остаток
WRONG_BEST = (622, 177727)     # если максимум обновляется вне if
WRONG_RUNNING_MIN = (92, 157324)   # если минимум ищут по ходу того же цикла
DATA_FILE = 'ege/variant-fipi-demo-2027/files/demo_17.txt'   # относительно MEDIA_ROOT

# Ровно тот код, что стоит в блоке `Решение`. Держим его отдельной
# константой, а не внутри dict: это единственный блок статьи, который читают
# целиком, и в diff он должен выглядеть так же, как на странице.
SOLUTION = (
    "with open('17.txt') as f:\n"
    "    a = [int(line) for line in f]   # в файле по одному числу в строке\n"
    "\n"
    "m = min(a)                          # минимум – свойство всей последовательности\n"
    "\n"
    "count = 0\n"
    "best = 0                            # числа натуральные, ноль безопасен\n"
    "\n"
    "for i in range(len(a) - 1):\n"
    "    x, y = a[i], a[i + 1]\n"
    "    if x % 33 == m or y % 33 == m:\n"
    "        count += 1\n"
    "        if x + y > best:\n"
    "            best = x + y\n"
    "\n"
    "print(count, best)\n"
)


def _link(slug, text):
    """Markdown-ссылка на статью учебника.

    Адрес берётся у самой статьи, а не пишется строкой: переименуют slug –
    команда упадёт здесь, вместо того чтобы оставить в тексте битую ссылку.
    """
    return f'[{text}]({Article.objects.get(slug=slug).get_absolute_url()})'


def _solve(numbers, rule=None):
    """Тот же разбор, что в блоке `Решение`, но пригодный для счёта.

    `rule` – функция (x, y, m) -> bool; по умолчанию правило условия
    `x % MOD == m or y % MOD == m`. Через неё же считаются неверные
    ответы для блока «Типичные ошибки»: числа в тексте не вписываются
    руками, а получаются из кода.
    """
    minimum = min(numbers)
    count = 0
    best = 0
    for i in range(len(numbers) - 1):
        x, y = numbers[i], numbers[i + 1]
        if rule is not None:
            fits = rule(x, y, minimum)
        else:
            fits = x % MOD == minimum or y % MOD == minimum
        if fits:
            count += 1
            if x + y > best:
                best = x + y
    return count, best


def _running_min(numbers):
    """Ответ того, кто ищет минимум в том же цикле, что и пары.

    Отдельная функция, а не параметр `_solve`: у этой ошибки другая
    форма – меняется не условие отбора, а момент, когда известен
    минимум.
    """
    current = numbers[0]
    count = 0
    best = 0
    for i in range(len(numbers) - 1):
        x, y = numbers[i], numbers[i + 1]
        current = min(current, x, y)
        if x % MOD == current or y % MOD == current:
            count += 1
            if x + y > best:
                best = x + y
    return count, best


def _demo_numbers():
    """Числа из файла демоварианта или None, если media на диске нет.

    Статья публикуется и на машине без media (каталог приезжает rsync-ом
    отдельно), поэтому отсутствие файла – не ошибка: проверка по нему
    просто не выполняется.
    """
    path = Path(settings.MEDIA_ROOT) / DATA_FILE
    if not path.exists():
        return None
    with path.open(encoding='utf-8') as handle:
        return [int(line) for line in handle if line.strip()]


def _toy_table():
    """Разбор игрушечного примера по парам – таблица для блока 2.

    Строки считаются, а не пишутся: таблица и TOY_ANSWER обязаны
    говорить одно и то же.
    """
    minimum = min(TOY)
    lines = [
        '| Пара | Остатки от деления на 33 | Подходит | Сумма |',
        '| --- | --- | --- | --- |',
    ]
    count = 0
    best = 0
    for i in range(len(TOY) - 1):
        x, y = TOY[i], TOY[i + 1]
        fits = x % MOD == minimum or y % MOD == minimum
        if fits:
            count += 1
            best = max(best, x + y)
        lines.append(
            f'| {x} и {y} | `{x % MOD}` и `{y % MOD}` | {"да" if fits else "нет"} '
            f'| {x + y if fits else "–"} |'
        )
    assert (count, best) == TOY_ANSWER, (
        f'игрушечный пример даёт {count} и {best} вместо {TOY_ANSWER} – '
        'таблица в блоке «Типовой пример» доказывает не то, что обещает абзац'
    )
    return '\n'.join(lines)


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ.

    Поменяется условие или файл – команда упадёт здесь, вместо того чтобы
    оставить в опубликованной статье разбор, доказывающий неверный ответ.
    """
    assert min(TOY) == 5, (
        f'минимум игрушечного примера равен {min(TOY)}, а в тексте названо 5 – '
        'весь разбор руками идёт не от того числа'
    )
    assert _solve(TOY) == TOY_ANSWER, (
        f'игрушечный пример даёт {_solve(TOY)} вместо {TOY_ANSWER} – таблица '
        'и абзац под ней обещают другое'
    )

    numbers = _demo_numbers()
    if numbers is None:
        return

    assert len(numbers) == TOTAL, (
        f'в файле {len(numbers)} чисел, а не {TOTAL} – статья называет '
        'другой размер последовательности и другое число пар'
    )
    assert min(numbers) == MIN_ELEMENT, (
        f'минимум файла равен {min(numbers)}, а не {MIN_ELEMENT} – на этом '
        'числе держится весь разбор условия'
    )
    assert _solve(numbers) == ANSWER, (
        f'разбор даёт {_solve(numbers)} вместо ответа ФИПИ {ANSWER}: '
        'решение в блоке «Решение» решает не ту задачу'
    )
    assert MIN_ELEMENT < MOD, (
        f'минимум {MIN_ELEMENT} не меньше делителя {MOD} – остаток не может '
        'равняться минимуму ни у одного элемента, и разбор ловушек немыслим'
    )

    def both(x, y, m):
        return x % MOD == m and y % MOD == m

    def element(x, y, m):
        return x == m or y == m

    assert _solve(numbers, both) == WRONG_AND, (
        f'«оба элемента» дают {_solve(numbers, both)} вместо {WRONG_AND} – '
        'в «Типичных ошибках» назван другой ответ'
    )
    assert _solve(numbers, element) == WRONG_ELEMENT, (
        f'сравнение самих элементов даёт {_solve(numbers, element)} вместо '
        f'{WRONG_ELEMENT} – в «Типичных ошибках» назван другой ответ'
    )

    best_pair = max(x + y for x, y in zip(numbers, numbers[1:]))
    assert best_pair == WRONG_BEST[1], (
        f'максимум по всем парам равен {best_pair}, а не {WRONG_BEST[1]} – '
        'этим числом «Типичные ошибки» доказывают, что обновлять максимум '
        'надо внутри if'
    )
    assert _running_min(numbers) == WRONG_RUNNING_MIN, (
        f'минимум по ходу цикла даёт {_running_min(numbers)} вместо '
        f'{WRONG_RUNNING_MIN} – первая ошибка в списке называет другое число'
    )


