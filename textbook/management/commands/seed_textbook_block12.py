def _greet_trace(names=('Аня', 'Борис')):
    """Трасса вызова функции для виджета loop-trace.

    Виджет ничего не вычисляет – шаги готовим здесь. Смысл трассы в том,
    что подсветка прыгает из строки вызова в тело и возвращается обратно:
    строка `def` тело не выполняет, а тело выполняется столько раз,
    сколько было вызовов. Переменной `name` до вызова не существует –
    просто не кладём ключ в vars, виджет покажет прочерк.
    """
    steps = [dict(
        line=1, vars={},
        note='Строка def только создаёт функцию и привязывает к ней имя. '
             'Тело не выполняется – на экране пока пусто.',
    )]
    for idx, name in enumerate(names):
        call_line = 5 + idx
        steps.append(dict(
            line=call_line, vars={},
            note="Вызов greet('{}'): выполнение прыгает в тело функции.".format(name),
        ))
        steps.append(dict(
            line=2, vars={'name': name}, out='Привет, {}!'.format(name),
            note='Параметр name получил значение аргумента – и печатается строка.',
        ))
        steps.append(dict(
            line=call_line, vars={},
            note='Тело кончилось – возвращаемся ровно в ту точку, откуда прыгнули. '
                 'Локальное имя name перестало существовать.',
        ))
    return steps


