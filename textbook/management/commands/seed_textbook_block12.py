def _stack_stepper(func_name):
    """Сборщик шагов для виджета call-stack.

    Возвращает пару (steps, snap): `steps` – накопленный список шагов,
    `snap(...)` – снимок текущего состояния стопки. Стопка ведётся списком
    [n, expr]: каждый начатый и ещё не законченный вызов держит своё
    значение параметра и своё незаконченное выражение.

    Снимок делаем полным (все кадры целиком, а не «что изменилось») – как и
    в loop-trace, иначе шаг назад и перетаскивание ползунка потребовали бы
    пересчёта. Верхний кадр – тот, который сейчас выполняется.
    """
    steps = []
    stack = []

    def snap(line, note, top_state='active', top_ret=None, top_done=False,
             returned=None, out=None, check=None):
        frames = []
        for i, (n, expr) in enumerate(stack):
            last = i == len(stack) - 1
            frame = {
                'call': '{}({})'.format(func_name, n),
                'vars': {'n': n},
                'expr': expr,
                'state': top_state if last else 'waiting',
            }
            if last and top_ret is not None:
                frame['ret'] = top_ret
            if last and top_done:
                frame['done'] = True
            frames.append(frame)
        step = dict(line=line, stack=frames, note=note)
        if returned is not None:
            step['returned'] = returned
        if out is not None:
            step['out'] = out
        if check is not None:
            step['check'] = check
        steps.append(step)

    return steps, stack, snap


def _countdown_frames(start=3):
    """Шаги рекурсивного отсчёта для виджета call-stack.

    Отсчёт ничего не возвращает, поэтому вместо «вернул N» кадр закрывается
    бейджем «закончился» (флаг `top_done`). Выражение кадра здесь – не
    формула, а короткая подпись «что этот вызов сейчас делает»: напечатал
    число, ждёт вложенный вызов, дошёл до конца тела.
    """
    steps, stack, snap = _stack_stepper('countdown')

    def walk(n):
        stack.append([n, ''])
        snap(2, 'Начался вызов countdown({0}) – у него своя карточка и своё '
                'n = {0}. Проверяем базовый случай: n == 0?'.format(n),
             check=n == 0)
        if n == 0:
            stack[-1][1] = 'печатает «Пуск!»'
            snap(3, 'Базовый случай сработал: этот вызов не зовёт никого дальше, '
                    'а просто печатает «Пуск!».',
                 top_state='base', out='Пуск!')
            stack[-1][1] = 'дошёл до return'
            snap(4, 'return заканчивает самый глубокий вызов. Стопка перестала '
                    'расти – дальше она будет только уменьшаться.',
                 top_state='base', top_done=True)
            stack.pop()
            return
        stack[-1][1] = 'напечатал {}'.format(n)
        snap(5, 'Печать стоит до рекурсивного вызова – значит, работает на спуске.',
             out=str(n))
        stack[-1][1] = 'ждёт countdown({})'.format(n - 1)
        snap(6, 'Вызов countdown({}) – та же задача, размер меньше. Карточка '
                'остаётся в стопке: её тело ещё не дошло до конца.'.format(n - 1))
        walk(n - 1)
        stack[-1][1] = 'тело кончилось'
        snap(6, 'Вложенный вызов закрылся – вернулись в карточку с n = {}. '
                'Дальше в теле ничего нет, закрывается и она.'.format(n),
             top_done=True,
             returned={'from': 'countdown({})'.format(n - 1),
                       'to': 'countdown({})'.format(n)})
        stack.pop()

    snap(1, 'Строка def только создаёт функцию. Стопка вызовов пока пуста.')
    snap(9, 'Вызов countdown({}) – начинается первый вызов, спуск пошёл.'.format(start))
    walk(start)
    snap(9, 'Стопка опустела: все начатые вызовы закончились. Программа идёт дальше.')
    return steps


def _factorial_frames(start=4):
    """Шаги рекурсивного факториала для виджета call-stack.

    Кадр помнит своё `n` и своё незаконченное умножение – на спуске в нём
    стоит «?», на подъёме «?» заменяется числом, которое вернул вызов снизу.
    Именно ради этой замены виджет и делался: словами «отдал наверх»
    происходящее не читается.
    """
    steps, stack, snap = _stack_stepper('factorial')

    def walk(n):
        stack.append([n, ''])
        snap(2, 'Начался вызов factorial({0}) – у него своя карточка и своё '
                'n = {0}. Проверяем базовый случай: n == 0?'.format(n),
             check=n == 0)
        if n == 0:
            stack[-1][1] = 'ответ готов: 1'
            snap(3, 'Дно достигнуто: 0! = 1, этот вызов отвечает сразу. '
                    'Посмотрите на карточки выше – в каждой стоит «?»: ни одного '
                    'умножения ещё не сделано.',
                 top_state='base', top_ret=1)
            stack.pop()
            return 1
        stack[-1][1] = '{} $\\cdot$ ? = ?'.format(n)
        snap(4, 'Чтобы умножить, нужен второй сомножитель – за ним уходим в '
                'factorial({}). Карточка остаётся в стопке с незаконченным '
                'умножением и ждёт.'.format(n - 1))
        inner = walk(n - 1)
        result = n * inner
        stack[-1][1] = '{} $\\cdot$ {} = {}'.format(n, inner, result)
        snap(4, 'Карточка снизу закрылась и отдала {}. Это число встало на место '
                '«?»: {} $\\cdot$ {} = {}. Теперь и этот вызов закончен.'.format(
                    inner, n, inner, result),
             top_ret=result,
             returned={'value': inner,
                       'from': 'factorial({})'.format(n - 1),
                       'to': 'factorial({})'.format(n)})
        stack.pop()
        return result

    snap(1, 'Строка def только создаёт функцию. Стопка вызовов пока пуста.')
    snap(7, 'Вызов factorial({}). Печатать пока нечего: сначала должен '
            'посчитаться аргумент.'.format(start))
    total = walk(start)
    snap(7, 'Стопка опустела: все вызовы закончились. Первый вернул {} – вот '
            'теперь print печатает ответ.'.format(total), out=str(total))
    return steps


def _overflow_frames(start=3, limit=5):
    """Шаги отсчёта без базового случая для виджета call-stack (урок 12.4).

    Предел глубины занижен до `limit`: настоящую стопку из тысячи карточек
    показать негде, а вся мысль урока видна уже на пяти. Кадры, начиная с
    номера `limit + 1`, получают состояние 'over' – виджет рисует их красными,
    и бейдж «глубина: N из M» тоже краснеет.

    Отдельный сборщик, а не `_stack_stepper`: там состояние задаётся только
    верхнему кадру, а здесь красным должен становиться сам кадр, вышедший
    за предел.
    """
    steps = []
    stack = []

    def snap(line, note, out=None):
        frames = []
        for i, (n, expr) in enumerate(stack):
            last = i == len(stack) - 1
            if i >= limit:
                state = 'over'
            else:
                state = 'active' if last else 'waiting'
            frames.append({
                'call': 'countdown({})'.format(n),
                'vars': {'n': n},
                'expr': expr,
                'state': state,
            })
        step = dict(line=line, stack=frames, note=note)
        if out is not None:
            step['out'] = out
        steps.append(step)

    snap(1, 'Строка def только создаёт функцию. Стопка вызовов пока пуста.')
    snap(6, 'Вызов countdown({}) – спуск пошёл. Предел глубины здесь занижен '
            'до {}: настоящую стопку из тысячи карточек показать негде, а всё '
            'важное видно уже на пяти.'.format(start, limit))

    n = start
    while len(stack) < limit:
        stack.append([n, 'напечатал {}'.format(n)])
        snap(2, 'Начался вызов countdown({0}) – своя карточка и своё n = {0}. '
                'Базового случая в этой функции нет, проверять нечего: сразу '
                'печатаем.'.format(n),
             out=str(n))
        stack[-1][1] = 'ждёт countdown({})'.format(n - 1)
        snap(3, 'Вызов countdown({}). Карточка остаётся в стопке – её тело ещё '
                'не дошло до конца. Обратите внимание: ни один вызов пока не '
                'закончился, снимать со стопки нечего.'.format(n - 1))
        n -= 1

    stack.append([n, 'не помещается в стек'])
    snap(3, 'Кадр номер {} не помещается: предел глубины – {}. Заметьте, '
            'программа не «зациклилась» и не сломалась логически – числа '
            'исправно уменьшаются дальше. У неё просто кончилось место в '
            'стопке.'.format(limit + 1, limit))
    snap(3, 'Python останавливает программу сам, не дожидаясь, пока она '
            'съест всю память. Ни один вызов так и не завершился.',
         out='RecursionError: maximum recursion depth exceeded')
    return steps


