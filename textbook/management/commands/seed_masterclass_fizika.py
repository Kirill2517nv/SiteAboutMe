class Command(BaseCommand):
    help = 'Страница мастер-класса «Программирование помогает изучать физику»'

    @transaction.atomic
    def handle(self, *args, **options):
        article, _ = Article.objects.update_or_create(
            slug=SLUG,
            defaults=dict(
                track='event',
                course_task=None,
                section=None,
                ege_task=None,
                title='Как программирование помогает изучать физику',
                description='Мастер-класс: четыре задачи спецкурса по численному '
                            'моделированию, в каждой – физический сюрприз и '
                            'численная ловушка.',
                order=1,
                is_published=True,
            ),
        )
        replace_blocks(article, [dict(b, order=i) for i, b in enumerate(BLOCKS, start=1)])

        # QR – картинкой из кода, а не через админку: адрес страницы задан здесь
        # же, и после переименования slug код не разойдётся с адресом. Файл один
        # на оба блока; повторный прогон его не плодит – replace_blocks отдаёт
        # блокам прежний файл.
        qr_blocks = list(article.blocks.filter(block_type='image').order_by('order'))
        if qr_blocks and not qr_blocks[0].image:
            qr_blocks[0].image.save('master-klass-qr.png', ContentFile(_qr_png()))
        for block in qr_blocks[1:]:
            if block.image.name != qr_blocks[0].image.name:
                block.image.name = qr_blocks[0].image.name
                block.save(update_fields=['image'])

        self.stdout.write(self.style.SUCCESS(f'Готово: {PAGE_URL}'))
