def _particles(text):
    """Частицы файла в его порядке: (x, y, энергия, признак)."""
    rows = []
    for line in text.splitlines():
        s = line.replace(',', '.').split()
        if not s:
            continue
        x, y, vx, vy, m = map(float, s[:5])
        rows.append((x, y, m * (vx ** 2 + vy ** 2) / 2, s[5]))
    return rows


def _clusters(rows):
    """Раскладка по BORDERS с сохранением порядка файла – как в SOLUTION."""
    clusters = [[] for _ in range(len(BORDERS) + 1)]
    for p in rows:
        clusters[sum(p[2] > b for b in BORDERS)].append(p)
    return clusters


def _center(cluster):
    return min(cluster, key=lambda p: sum(abs(p[2] - q[2]) for q in cluster))


def _q1(groups):
    best = 0
    for c in groups:
        two = [p for p in c if p[3] == 'II']
        for a in two:
            for b in two:
                best = max(best, dist(a[:2], b[:2]))
    return int(best * 10000)


def _demo_text():
    """Текст файла демоверсии или None, если media на машине нет."""
    path = Path(settings.MEDIA_ROOT) / DATA_PATH
    return path.read_text(encoding='utf-8') if path.exists() else None


def _gap_chains(rows):
    """Кластеры по правилу «новый кластер, где разрыв больше R» – ошибка 1."""
    energies = sorted(p[2] for p in rows)
    return 1 + sum(b - a > R for a, b in zip(energies, energies[1:]))


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ и с текстом статьи.

    Без файла демоверсии (media не приехал) проверка по нему пропускается:
    команда публикует статью, а сверку сделает прогон там, где файл есть.
    """
    text = _demo_text()
    if text is None:
        return
    rows = _particles(text)
    assert len(rows) == DATA_LINES, (
        f'в файле {len(rows)} частиц, а не {DATA_LINES} – текст статьи '
        'называет другое число строк'
    )
    energies = sorted(p[2] for p in rows)
    for low, high in GAPS:
        inside = [e for e in energies if low < e < high]
        assert not inside, (
            f'в полосе {low}…{high} есть частицы {inside[:3]} – граница '
            'кластера стоит не в пустоте'
        )
    for border, (low, high) in zip(BORDERS, GAPS):
        assert low < border < high, f'граница {border} вне полосы {low}…{high}'

    clusters = _clusters(rows)
    assert [len(c) for c in clusters] == SIZES, (
        f'кластеры по {[len(c) for c in clusters]} частиц, а не {SIZES}'
    )
    for c in clusters:
        width = max(p[2] for p in c) - min(p[2] for p in c)
        assert width <= R, f'кластер шириной {width:.3f} больше R = {R}'
    assert round(rows[0][2], 3) == FIRST_E and rows[0] in clusters[2], (
        f'первая частица: E = {rows[0][2]:.3f} – шаг 2 разбирает её как '
        f'{FIRST_E} из третьего кластера'
    )
    for tip in (TIP_LEFT, TIP_RIGHT):
        value = float(tip.replace(',', '.'))
        assert any(abs(p[2] - value) < 1e-4 for p in rows), (
            f'в файле нет частицы с энергией {tip} – подпись к видео '
            'называет число, которого на графике нет'
        )

    assert _gap_chains(rows) == 1, (
        f'правило «разрыв больше R» даёт {_gap_chains(rows)} кластер(ов) – '
        'первая типичная ошибка описывает не то, что выходит на файле'
    )

    q2 = int(max(_center(c)[2] for c in clusters) * 10000)
    assert (_q1(clusters), q2) == ANSWER, (
        f'разбор даёт {_q1(clusters)} {q2} вместо ответа ФИПИ {ANSWER}'
    )
    assert _q1([rows]) == WRONG_Q1_ALL, (
        f'Q1 по всему файлу – {_q1([rows])}, а не {WRONG_Q1_ALL}'
    )

    printed = run_solution(SOLUTION, DATA_FILE, text)
    assert printed[-2:] == [str(x) for x in ANSWER], (
        f'код из статьи печатает {printed[-2:]} вместо ответа ФИПИ {ANSWER}'
    )
    # Два кандидата в центр равны в точной арифметике (см. докстринг), и
    # выбор между ними решает шум float. Статья молчит об этом, пока ответ от
    # `<` / `<=` не зависит; перестанет – придётся писать о нём ученику.
    lax = SOLUTION.replace('if total < best:', 'if total <= best:')
    assert lax != SOLUTION, 'в SOLUTION пропала строка `if total < best:`'
    printed = run_solution(lax, DATA_FILE, text)
    assert printed[-2:] == [str(x) for x in ANSWER], (
        f'с <= код печатает {printed[-2:]} – выбор центра стал зависеть от '
        'сравнения, статье нужен пункт об этом'
    )


