def can_swap(n):
    """Команда B применима: цифра десятков меньше цифры единиц.

    Та же функция, что в обоих блоках `code`. Здесь она нужна расчёту:
    и таблица, и проверки берут применимость отсюда, а не решают заново.
    """
    return n // 10 % 10 < n % 10


def swap(n):
    """Меняем местами две младшие цифры, старшие разряды не трогаем.

    Сотни остаются на месте: 114 превращается в 141, а не в 411.
    """
    return n // 100 * 100 + n % 10 * 10 + n // 10 % 10


def _recurrence():
    """Рекуррентное соотношение для выносного блока `formula`.

    Записано снизу вверх: $G(m)$ – сколько программ ведёт из START в m.
    Условие перевёрнуто относительно команды B намеренно: сама команда
    применяется к числу, у которого десятков меньше, чем единиц, значит
    у её результата – наоборот, больше. Соотношение смотрит на входящие
    стрелки, поэтому в нём стоит $a > b$, а не $a < b$.

    Кириллицы внутри нет намеренно: в математических шрифтах MathJax её нет,
    и `\\text{…}` выдаёт «тофу». Поэтому цифры десятков и единиц названы
    латинскими $a$ и $b$, а результат обмена – $s(m)$; оба обозначения
    вводятся в тексте прямо над формулой.

    START подставляется, а не пишется строкой: поменяется условие –
    поменяется и формула, вместо того чтобы разойтись с разбором.
    """
    return (
        r'G(m) = \begin{cases}'
        rf'1, & m = {START},\\'
        rf'G(m-1) + G(s(m)), & m > {START},\ a > b,\\'
        rf'G(m-1), & m > {START},\ a \le b.'
        r'\end{cases}'
    )


def _tape():
    """Лента клеток: разметка, а не ASCII.

    bleach пропускает `div` и `span` с `class`, но вычищает `style`,
    поэтому здесь только классы, а вся геометрия – в `.tape`
    (static/css/textbook-article.css).

    Дуга прыжка не отдельный элемент: её собирают сами клетки, каждая
    своим куском линии. Разъехаться с числами она поэтому не может – она
    из них и состоит, а не выставлена по вычисленным координатам.

    Разметка идёт одной строкой: markdown включён с `nl2br`, и перевод
    строки внутри блока превратился бы в `<br>` посреди ленты.
    """
    counts = _counts()
    src, dst = _useful_swaps()[0]
    middle = (src + dst) // 2

    cells = []
    for n in range(START, TAPE_HI + 1):
        mods = ['tape__cell--start'] if n == START else []
        if n == src:
            mods.append('tape__cell--arc-from')
        elif n == dst:
            mods.append('tape__cell--arc-to')
        elif src < n < dst:
            mods.append('tape__cell--arc')
        # Подпись сидит в средней клетке прыжка: так она оказывается по
        # центру дуги без единой вычисленной координаты.
        label = (f'<span class="tape__b">B: {src} \u2192 {dst}</span>'
                 if n == middle else '')
        # Стрелка шага A рисуется от центра своей клетки до центра
        # следующей, поэтому у последней клетки её нет. Наконечник –
        # отдельным элементом: оба псевдоэлемента стрелки заняты
        # хвостиками, которыми она загибается в клетки. Буква A стоит
        # только над первой: остальные стрелки такие же, десять подписей
        # были бы шумом.
        step = ''
        if n < TAPE_HI:
            letter = '<span class="tape__a-label">A</span>' if n == START else ''
            step = ('<span class="tape__a">'
                    f'<span class="tape__a-tip"></span>{letter}</span>')
        # Наконечник дуги B: отдельным элементом, потому что оба
        # псевдоэлемента клетки-цели уже заняты линией и хвостиком.
        tip = '<span class="tape__tip"></span>' if n == dst else ''
        cells.append(
            f'<div class="tape__cell {" ".join(mods)}">'
            f'<span class="tape__n">{n}</span>'
            f'<span class="tape__g">{counts[n]}</span>'
            f'{step}{tip}{label}</div>'
        )
    return '<div class="tape">' + ''.join(cells) + '</div>'


def _counts():
    """Число программ из START в каждое число до TARGET включительно.

    Тот же цикл, что в SOLUTION_DP: разбор обязан считать ровно тем кодом,
    который показывает читателю, иначе статья и её эталон разъедутся.
    """
    counts = [0] * (TARGET + 1)
    counts[START] = 1          # в стартовое число ведёт пустая программа
    for n in range(START, TARGET):
        counts[n + 1] += counts[n]
        if can_swap(n) and swap(n) <= TARGET:
            counts[swap(n)] += counts[n]
    return counts


def _useful_swaps():
    """Пары (n, swap(n)) там, где обмен применим и не выходит за TARGET.

    Это ровно те числа, в которые ведёт больше одного хода: без списка
    таблица либо перечисляла бы все 42 числа подряд, либо называла бы этот
    факт словами, не показывая его.
    """
    return [
        (n, swap(n)) for n in range(START, TARGET)
        if can_swap(n) and swap(n) <= TARGET
    ]


def _trace(program, n):
    """Траектория: результаты выполнения команд программы по порядку.

    Нужна, чтобы сверить пример ABA из условия – он же готовая проверка
    обеих функций, которые читатель напишет первым делом.
    """
    path = []
    for command in program:
        n = n + 1 if command == 'A' else swap(n)
        path.append(n)
    return path


@lru_cache(maxsize=None)
def _recursive(n):
    """Число программ из n в TARGET – счёт с противоположного конца.

    В статье этой функции нет: там оба способа считают одну формулу $G$
    (сколько программ ведёт из START в число). Здесь она стоит нарочно как
    независимый оракул – разбор по **первому** ходу вместо разбора по
    последнему. Два разных счёта, сойтись обязаны на одном числе; если бы
    проверка повторяла тот же алгоритм, она не проверяла бы ничего.
    """
    if n == TARGET:
        return 1
    if n > TARGET:
        return 0
    total = _recursive(n + 1)
    if can_swap(n):
        total += _recursive(swap(n))
    return total


def _naive_calls():
    """Сколько вызовов делает та же рекурсия без кеша.

    Считает счётчиком внутри функции: разница с числом различных чисел –
    единственный довод за `@lru_cache`, и он должен быть измерен, а не
    назван на глазок.
    """
    calls = 0

    def count(m):
        nonlocal calls
        calls += 1
        if m == START:
            return 1
        if m < START:
            return 0
        total = count(m - 1)
        if m // 10 % 10 > m % 10:
            total += count(swap(m))
        return total

    count(TARGET)
    return calls


def _table():
    """Markdown-таблица: из чего складывается число программ у каждого числа.

    Строки – START и дальше только те числа, куда ведёт обмен, по возрастанию.
    У остальных вклад ровно один, и строка повторяла бы соседнюю, ничего не
    объясняя. Последняя строка – TARGET, ответ; её выделяем жирным, чтобы она
    читалась раньше абзаца под таблицей.
    """
    counts = _counts()
    source = {target: n for n, target in _useful_swaps()}

    lines = [
        '| Число | Как складывается | Программ |',
        '| --- | --- | --- |',
    ]
    for m in [START] + sorted(source):
        if m == START:
            how = '1 – пустая программа'
        else:
            how = f'{counts[m - 1]} (A из {m - 1}) + {counts[source[m]]} (B из {source[m]})'
        # <mark> в первой ячейке красит всю строку: markdown-таблица не даёт
        # повесить класс на <tr>, и в textbook-article.css под это уже есть
        # правило `tr:has(mark) td` (тем же приёмом подсвечена строка-ответ
        # в разборе задания 5). Сам <mark> там обесцвечен.
        bold = '**' if m == TARGET else ''
        first = f'<mark>{bold}{m}{bold}</mark>' if m == TARGET else str(m)
        lines.append(f'| {first} | {how} | {bold}{counts[m]}{bold} |')
    return '\n'.join(lines)


def _check():
    """Числа разбора обязаны совпасть с ответом ФИПИ и с текстом статьи.

    Поменяется условие – команда упадёт здесь, вместо того чтобы оставить
    в опубликованной статье таблицу, доказывающую неверный ответ. Главная
    проверка – совпадение двух способов: если разойдутся они, разойдётся и
    статья, где оба обещают одно и то же число.
    """
    counts = _counts()
    assert counts[TARGET] == ANSWER, (
        f'таблица даёт {counts[TARGET]}, у ФИПИ {ANSWER} – разбор решает '
        'другую задачу, чем условие'
    )
    assert _recursive(START) == counts[TARGET], (
        f'рекурсия даёт {_recursive(START)}, таблица {counts[TARGET]} – '
        'два способа в статье обязаны сходиться'
    )
    assert _trace('ABA', 13) == [14, 41, 42], (
        f"пример ABA из 13 даёт {_trace('ABA', 13)} вместо 14, 41, 42 – "
        'блок «Типовой пример» разбирает не тот пример, что в условии'
    )
    for n in range(10, 1000):
        if can_swap(n):
            assert swap(n) > n, (
                f'обмен превращает {n} в {swap(n)} – обе команды обязаны '
                'увеличивать число, иначе в траектории возможен цикл и '
                'отсечение по TARGET перестаёт работать'
            )
    assert counts[TARGET - 1] == 14 and counts[114] == 2, (
        f'в {TARGET - 1} ведёт {counts[TARGET - 1]} программ, в 114 – '
        f'{counts[114]} – на этой паре держится проверка ответа руками '
        'в блоке «Как рассуждать»'
    )
    assert counts[TARGET - 1] + counts[114] == ANSWER, (
        f'{counts[TARGET - 1]} + {counts[114]} не даёт {ANSWER} – последний '
        'пункт блока «Как рассуждать» называет не те слагаемые'
    )
    src, dst = _useful_swaps()[0]
    assert dst <= TAPE_HI, (
        f'первый прыжок команды B ведёт в {dst}, а лента нарисована до '
        f'{TAPE_HI} – дуге в блоке «Как рассуждать» некуда приземлиться'
    )
    assert counts[dst] == counts[dst - 1] + counts[src], (
        f'в {dst} стоит {counts[dst]}, а подпись под лентой обещает '
        f'{counts[dst - 1]} + {counts[src]}'
    )
    tape = _tape()
    drawn = tape.count('tape__cell ')
    assert drawn == TAPE_HI - START + 1, (
        f'в ленте {drawn} клеток вместо {TAPE_HI - START + 1}'
    )
    steps = tape.count('tape__a-tip')
    assert steps == TAPE_HI - START, (
        f'стрелок шага A в ленте {steps}, а промежутков между клетками '
        f'{TAPE_HI - START}: последняя клетка не должна никуда указывать'
    )
    for mod in ('tape__cell--start', 'tape__cell--arc-from',
                'tape__cell--arc-to', 'tape__b', 'tape__tip',
                'tape__a-label'):
        assert tape.count(mod) == 1, (
            f'класс {mod} встречается в ленте {tape.count(mod)} раз – '
            'разметка ленты разошлась со стилями в textbook-article.css'
        )
    assert chr(10) not in tape, (
        'в ленте появился перевод строки – markdown с nl2br вставит <br> '
        'посреди разметки'
    )
    assert all(not can_swap(swap(n)) for n, _ in _useful_swaps()), (
        'нашёлся обмен, после которого команда B снова применима – '
        'пункт 2 «Типичных ошибок» обещает обратное: проверка условия '
        'у результата теряет все обмены разом'
    )
    assert len(_useful_swaps()) == 8, (
        f'обменов внутри отрезка {len(_useful_swaps())}, а разбор говорит '
        'о восьми – таблица в блоке «Способ 2» перечисляет не все'
    )
    assert _naive_calls() == 148, (
        f'рекурсия без кеша делает {_naive_calls()} вызовов – в блоке про '
        '@lru_cache названо другое число'
    )
    assert _naive_calls() > SPAN, (
        f'без кеша {_naive_calls()} вызовов, различных чисел {SPAN} – довод '
        'за декоратор пропал, и блок «Способ 1» его обещает зря'
    )


